//! The **action groupoid** — what symmetry breaking *means*, categorically, as checked code.
//!
//! Symmetry breaking is not a heuristic; it is the computation of `π₀` of a groupoid. A symmetry
//! group `G` acts on the space `X` of assignments (the "possible worlds"). The **action groupoid**
//! `X ⫽ G` has the assignments as objects and the group elements as the (iso)morphisms `α → g·α`:
//! two assignments are *isomorphic* iff related by a symmetry — bisimilar worlds. Symmetry breaking
//! keeps ONE assignment per isomorphism class — it computes the **skeleton**, equivalently
//! `π₀(X ⫽ G)` (the set of orbits = connected components). The exponential→polynomial collapse is
//! exactly `|X| → |π₀(X ⫽ G)|`.
//!
//! This `X ⫽ G` is a **1-groupoid** (h-level 3 in the homotopy-level table). The ∞-tower above it —
//! symmetries *between* symmetry-breakings, then between those, … — is the honest open direction. We
//! build the first rung (this 1-groupoid) solidly and *check* that symmetry breaking is its `π₀`; the
//! next rung (a groupoid of measures-and-their-morphisms) is sketched in the campaign notes. We do
//! not claim to have built an ∞-groupoid — only the 1-truncation that the present theory occupies,
//! and the precise statement of what climbing would mean.

use std::collections::HashMap;

use crate::cdcl::Lit;
use crate::proof::Perm;

/// The action groupoid `X ⫽ G`: assignments over `nv` variables acted on by the group generated by
/// `gens` (literal permutations). Small `nv` only — it enumerates all `2^nv` objects, which is the
/// point: it makes the orbit collapse *visible and checkable*.
pub struct ActionGroupoid {
    nv: usize,
    gens: Vec<Perm>,
}

impl ActionGroupoid {
    pub fn new(nv: usize, gens: Vec<Perm>) -> Self {
        ActionGroupoid { nv, gens }
    }

    /// Act by a (sign-respecting) symmetry on an assignment encoded as a bitmask: variable `v`'s value
    /// is carried to variable `σ(+v).var`, flipped iff `σ(+v)` is negative.
    fn act(&self, g: &Perm, a: u32) -> u32 {
        let mut b = 0u32;
        for v in 0..self.nv {
            let val = (a >> v) & 1;
            let img = g.apply(Lit::pos(v as u32));
            let w = img.var() as usize;
            let new_val = if img.is_positive() { val } else { 1 - val };
            if new_val == 1 {
                b |= 1 << w;
            }
        }
        b
    }

    /// The orbit id of every assignment — `π₀(X ⫽ G)`, computed as the connected components of the
    /// action via union-find. `orbits()[a]` is the canonical representative (smallest member) of `a`'s
    /// orbit.
    pub fn orbits(&self) -> Vec<u32> {
        let total = 1u32 << self.nv;
        let mut parent: Vec<u32> = (0..total).collect();
        fn find(parent: &mut [u32], x: u32) -> u32 {
            let mut r = x;
            while parent[r as usize] != r {
                r = parent[r as usize];
            }
            // path compression
            let mut c = x;
            while parent[c as usize] != r {
                let next = parent[c as usize];
                parent[c as usize] = r;
                c = next;
            }
            r
        }
        for a in 0..total {
            for g in &self.gens {
                let b = self.act(g, a);
                let (ra, rb) = (find(&mut parent, a), find(&mut parent, b));
                if ra != rb {
                    // union by smaller-root so representatives are canonical (smallest)
                    if ra < rb {
                        parent[rb as usize] = ra;
                    } else {
                        parent[ra as usize] = rb;
                    }
                }
            }
        }
        (0..total).map(|a| find(&mut parent, a)).collect()
    }

    /// `|π₀(X ⫽ G)|` — the number of essentially-different worlds, i.e. exactly what symmetry breaking
    /// reduces the search space to.
    pub fn num_orbits(&self) -> usize {
        let reps = self.orbits();
        let mut distinct: Vec<u32> = reps.clone();
        distinct.sort_unstable();
        distinct.dedup();
        distinct.len()
    }

    /// The full group `G` generated by `gens` (closed under composition, including the identity).
    /// Bounded to `cap` elements so a pathological generating set can't blow up; the caller's small
    /// examples are well within it.
    pub fn group_elements(&self, cap: usize) -> Vec<Perm> {
        let mut seen: std::collections::HashSet<Perm> = std::collections::HashSet::new();
        let id = Perm::identity(self.nv);
        seen.insert(id.clone());
        let mut elems = vec![id];
        let mut frontier = elems.clone();
        while !frontier.is_empty() && elems.len() < cap {
            let mut next = Vec::new();
            for e in &frontier {
                for g in &self.gens {
                    let prod = g.compose(e); // g ∘ e
                    if seen.insert(prod.clone()) {
                        next.push(prod.clone());
                        elems.push(prod);
                        if elems.len() >= cap {
                            return elems;
                        }
                    }
                }
            }
            frontier = next;
        }
        elems
    }

    /// `π₁(X ⫽ G)` at the assignment `a` — its **stabilizer**: the group elements that fix `a`
    /// (`g · a = a`). These are the loops at `a` in the action groupoid; the fundamental-group data of
    /// the homotopy type at that component.
    pub fn stabilizer_size(&self, a: u32, group: &[Perm]) -> usize {
        group.iter().filter(|g| self.act(g, a) == a).count()
    }

    /// The size of `a`'s orbit (the connected component of `a`).
    pub fn orbit_size(&self, a: u32) -> usize {
        let reps = self.orbits();
        reps.iter().filter(|&&r| r == reps[a as usize]).count()
    }
}

/// `τ ∘ σ` on an assignment held as a bitmask: variable `v` takes the value `τ` gives the literal `σ(+v)`. This is the
/// model a substitution-redundant clause leaves in place of a model `τ` it removes.
pub fn pull_back(nv: usize, sigma: &Perm, tau: u32) -> u32 {
    let mut out = 0u32;
    for v in 0..nv {
        let img = sigma.apply(Lit::pos(v as u32));
        let val = (tau >> img.var()) & 1 == 1;
        if val == img.is_positive() {
            out |= 1 << v;
        }
    }
    out
}

fn satisfies(clauses: &[Vec<Lit>], a: u32) -> bool {
    clauses
        .iter()
        .all(|c| c.iter().any(|l| ((a >> l.var()) & 1 == 1) == l.is_positive()))
}

/// The **model groupoid** of a formula under literal mappings that need not be symmetries of it. Its objects are the
/// formula's models; a mapping `σ` relates a model `τ` to the model `τ ∘ σ` ([`pull_back`]) whenever that is a model
/// too. A mapping that is an automorphism relates every model to one (the action groupoid's orbits, restricted to the
/// models); a *partial* symmetry relates only the models where it happens to carry a model to a model, which is what a
/// conditional symmetry is. `π₀` is the set of connected components.
///
/// Substitution-redundant breaking with partial symmetries (a [`crate::proof::Witness::PartialSymmetry`] step)
/// removes a model `τ` only with `τ ∘ σ` surviving in its place, in the same component; by induction over the steps,
/// every component that held a model still holds one. [`ModelGroupoid::kept_in_every_component`] checks exactly that,
/// by enumeration, so the claim is testable rather than argued. Small `nv` only: it enumerates `2^nv` assignments.
pub struct ModelGroupoid {
    models: Vec<u32>,
    component: Vec<usize>,
    count: usize,
}

impl ModelGroupoid {
    /// The groupoid of the models of `clauses` over `nv ≤ 24` variables under `maps`.
    pub fn new(nv: usize, clauses: &[Vec<Lit>], maps: &[Perm]) -> ModelGroupoid {
        assert!(nv <= 24, "the model groupoid enumerates 2^nv assignments");
        let models: Vec<u32> = (0..1u32 << nv).filter(|&a| satisfies(clauses, a)).collect();
        let index: HashMap<u32, usize> = models.iter().enumerate().map(|(i, &m)| (m, i)).collect();
        let mut parent: Vec<usize> = (0..models.len()).collect();
        fn find(parent: &mut [usize], x: usize) -> usize {
            let mut r = x;
            while parent[r] != r {
                r = parent[r];
            }
            let mut c = x;
            while parent[c] != r {
                let next = parent[c];
                parent[c] = r;
                c = next;
            }
            r
        }
        for (i, &m) in models.iter().enumerate() {
            for sigma in maps {
                if let Some(&j) = index.get(&pull_back(nv, sigma, m)) {
                    let (ri, rj) = (find(&mut parent, i), find(&mut parent, j));
                    if ri != rj {
                        parent[ri.max(rj)] = ri.min(rj);
                    }
                }
            }
        }
        let roots: Vec<usize> = (0..models.len()).map(|i| find(&mut parent, i)).collect();
        let mut id_of: HashMap<usize, usize> = HashMap::new();
        let component: Vec<usize> = roots
            .iter()
            .map(|&r| {
                let next = id_of.len();
                *id_of.entry(r).or_insert(next)
            })
            .collect();
        ModelGroupoid { models, count: id_of.len(), component }
    }

    /// The models, increasing as bitmasks.
    pub fn models(&self) -> &[u32] {
        &self.models
    }

    /// `|π₀|`: the number of components.
    pub fn num_components(&self) -> usize {
        self.count
    }

    /// The component a model lies in; `None` for an assignment that is not a model.
    pub fn component_of(&self, model: u32) -> Option<usize> {
        self.models.binary_search(&model).ok().map(|i| self.component[i])
    }

    /// Whether every component keeps a model that also satisfies `extra`, the clauses symmetry breaking added.
    pub fn kept_in_every_component(&self, extra: &[Vec<Lit>]) -> bool {
        let mut kept = vec![false; self.count];
        for (i, &m) in self.models.iter().enumerate() {
            if satisfies(extra, m) {
                kept[self.component[i]] = true;
            }
        }
        kept.into_iter().all(|k| k)
    }
}

