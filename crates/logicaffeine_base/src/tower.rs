//! The exact real types in a program's value model: real algebraic numbers, computable reals, the
//! program's infinitesimal and the hyperreals it generates, infinite integers, ordinals, and the
//! values a supertask leaves.
//!
//! Each type lives in its own module of this crate; this module decides how they mix with the
//! numeric tower and with each other, once, for every value model that holds them. A value model
//! (the interpreter's runtime value, a compiled program's value) implements [`TowerValue`]: how to
//! see one of its values as an exact type or a standard number, and how to build one. Everything
//! here is generic over it, so every tier computes, compares and prints these values identically.
//!
//! - an integer, rational or float operand is lifted exactly (a float is the dyadic rational it
//!   denotes, never a rounding of the other side) into the exact type it meets;
//! - real algebraic numbers sit below computable reals; the hyperreals are generated by the
//!   infinitesimal over the algebraic numbers, exactly as rational functions of `dt`; a value a flow
//!   leaves, or a computable transcendental meeting the infinitesimal, is a germ — known by its
//!   series in `dt` with exact coefficients, compared by the sign of its first nonzero one;
//! - an infinite integer meets a standard integer as an infinite integer (`+ − ×`, floor division
//!   and remainder keep integer meaning) and anything fractional as a hyperreal;
//! - a value that depends on the residue of `1/dt` lifts every operation branch by branch, and a
//!   comparison of infinite integers can itself depend on that residue;
//! - an ordinal meets only ordinals and naturals.
//!
//! Every result is held in its smallest exact form — a hyperreal with no infinitesimal part is
//! its standard value, a hyperreal that is an integer for every admitted `⌈1/dt⌉` is that infinite
//! integer, an algebraic number that is rational is a rational — so a value has one representation
//! whatever route produced it, exactly as the tower downsizes `BigInt` to `Int`.

