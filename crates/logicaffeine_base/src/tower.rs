/// An infinitesimal of the program: the name it was declared under, what is known about the
/// residues of its reciprocal, the infinite natural `⌈1/dt⌉`, and where it stands among the others.
///
/// `dx` declared much smaller than `dt` is smaller than every positive number made from `dt`, so the
/// two are ordered as levels: every value of `dx` with coefficients made from `dt` has the sign of
/// its lowest-order coefficient in `dx`. A declaration names at most one infinitesimal it is much
/// smaller than and one it is much larger than, and the order of any two is what those statements
/// give by transitivity ([`Scale::order`]); two the declarations do not order are never combined.
#[derive(Debug, PartialEq, Eq, Hash)]
pub struct Scale {
    pub name: String,
    pub residues: ResidueType,
    /// The infinitesimal this one was declared much smaller than.
    pub much_smaller_than: Option<Arc<Scale>>,
    /// The infinitesimal this one was declared much larger than.
    pub much_larger_than: Option<Arc<Scale>>,
    /// The declared infinitesimal this is, read on one residue class of its reciprocal: the
    /// engine's copy for a class keeps the declaration it refines, and is that infinitesimal.
    pub refines: Option<Arc<Scale>>,
}

impl Scale {
    /// An infinitesimal declared on its own.
    pub fn new(name: &str, residues: ResidueType) -> Scale {
        Scale {
            name: name.to_string(),
            residues,
            much_smaller_than: None,
            much_larger_than: None,
            refines: None,
        }
    }

    /// An infinitesimal declared much smaller than `larger` and much larger than `smaller`, each
    /// when given; refused when the bounds are not already ordered, smaller below larger, or when it
    /// would share a name with an infinitesimal it is ordered with.
    pub fn ordered(
        name: &str,
        residues: ResidueType,
        larger: Option<Arc<Scale>>,
        smaller: Option<Arc<Scale>>,
    ) -> Result<Scale, String> {
        if let (Some(l), Some(s)) = (&larger, &smaller) {
            match s.order(l) {
                Some(Ordering::Less) => {}
                Some(Ordering::Equal) => {
                    return Err(format!("{name} cannot be both much smaller and much larger than {}", l.name))
                }
                Some(Ordering::Greater) => {
                    return Err(format!(
                        "{name} is declared much smaller than {} and much larger than {}, but {} is much larger than {}",
                        l.name, s.name, s.name, l.name
                    ))
                }
                None => {
                    return Err(format!(
                        "{name} is declared much smaller than {} and much larger than {}, but the program does not state that {} is much smaller than {}",
                        l.name, s.name, s.name, l.name
                    ))
                }
            }
        }
        let related = larger
            .iter()
            .flat_map(|l| l.larger_chain())
            .chain(smaller.iter().flat_map(|s| s.smaller_chain()));
        if let Some(clash) = related.into_iter().find(|s| s.name == name) {
            return Err(format!(
                "{name} is ordered with the infinitesimal {}, so it needs a name of its own",
                clash.name
            ));
        }
        Ok(Scale {
            name: name.to_string(),
            residues,
            much_smaller_than: larger,
            much_larger_than: smaller,
            refines: None,
        })
    }

    /// The same infinitesimal on a narrower residue type of its reciprocal.
    pub fn with_residues(self: &Arc<Scale>, residues: ResidueType) -> Scale {
        Scale {
            name: self.name.clone(),
            residues,
            much_smaller_than: self.much_smaller_than.clone(),
            much_larger_than: self.much_larger_than.clone(),
            refines: Some(self.declaration_arc()),
        }
    }

    fn declaration_arc(self: &Arc<Scale>) -> Arc<Scale> {
        match &self.refines {
            Some(d) => d.clone(),
            None => self.clone(),
        }
    }

    /// The declaration this infinitesimal is: itself, or the one a residue class's copy refines.
    fn declaration(&self) -> &Scale {
        self.refines.as_deref().unwrap_or(self)
    }

    /// Whether the two are one infinitesimal: one declaration, whatever residue class either is read on.
    pub fn same_infinitesimal(&self, o: &Scale) -> bool {
        std::ptr::eq(self.declaration(), o.declaration()) || self.declaration() == o.declaration()
    }

    /// This infinitesimal and each it was declared much smaller than, in turn.
    fn larger_chain(&self) -> Vec<&Scale> {
        let mut out = vec![self];
        let mut at = self;
        while let Some(next) = at.much_smaller_than.as_deref() {
            out.push(next);
            at = next;
        }
        out
    }

    /// This infinitesimal and each it was declared much larger than, in turn.
    fn smaller_chain(&self) -> Vec<&Scale> {
        let mut out = vec![self];
        let mut at = self;
        while let Some(next) = at.much_larger_than.as_deref() {
            out.push(next);
            at = next;
        }
        out
    }

    /// `Less` when this infinitesimal is much smaller than `o`, `Greater` when much larger, `Equal`
    /// for one infinitesimal; `None` when the declarations do not order them. `a` is much smaller than
    /// `b` when some infinitesimal reached from `a` through the ones declared above it is reached
    /// from `b` through the ones declared below it: every declaration states its bounds' order
    /// already known, so no later one orders two earlier ones, and that meeting is the only route.
    pub fn order(&self, o: &Scale) -> Option<Ordering> {
        if self.same_infinitesimal(o) {
            return Some(Ordering::Equal);
        }
        let meets = |low: &Scale, high: &Scale| {
            let up = low.declaration().larger_chain();
            let down = high.declaration().smaller_chain();
            up.iter().any(|u| down.iter().any(|d| u.same_infinitesimal(d)))
        };
        if meets(self, o) {
            Some(Ordering::Less)
        } else if meets(o, self) {
            Some(Ordering::Greater)
        } else {
            None
        }
    }

    /// The refusal for two infinitesimals whose order the program does not state.
    pub fn unordered(&self, o: &Scale) -> String {
        format!(
            "cannot combine values of two infinitesimals, {} and {}, whose order the program does not state; declare one much smaller than the other",
            self.name, o.name
        )
    }

    /// How the infinite generator is written in a dependence: `⌈1/dt⌉`.
    pub fn generator_text(&self) -> String {
        format!("⌈1/{}⌉", self.name)
    }

    /// A residue system the value would need, refused in the program's own words.
    fn refuse(&self, e: ResidueError) -> String {
        e.describe(&self.generator_text())
    }
}

/// A hyperreal's representations: an exact rational function of `dt`; a real algebraic Puiseux
/// series that is none, a root of one ([`crate::puiseux`]); the germ a flow leaves, known by its
/// series in `dt`; or a value of several ordered infinitesimals ([`Multi`]). A Puiseux series compares
/// and hashes by its value, a germ by its canonical encoding.
#[derive(Debug, Clone)]
pub enum HyperForm {
    Rational(Hyperreal),
    Puiseux(Puiseux),
    Germ(Germ),
    Multi(Multi),
    /// An infinite integer of several infinitesimals — `⌊1/dt + 1/dx⌋`, a step count of `⌈1/(dt·dx)⌉`: a
    /// value of several that is a polynomial in their reciprocals with rational coefficients and an
    /// integer on every class the facts its scales carry admit ([`Multi::is_integral`]), as a polynomial
    /// in one infinitesimal's reciprocal that is one is an infinite integer of it. It computes and
    /// compares as the value it is, and prints as an infinite integer does.
    Integer(Multi),
    Nested(Arc<NestedGerm>),
}

impl PartialEq for HyperForm {
    fn eq(&self, o: &Self) -> bool {
        match (self, o) {
            (HyperForm::Rational(a), HyperForm::Rational(b)) => a == b,
            (HyperForm::Puiseux(a), HyperForm::Puiseux(b)) => {
                Closed::Series(a.clone()) == Closed::Series(b.clone())
            }
            (HyperForm::Germ(a), HyperForm::Germ(b)) => a.to_bytes() == b.to_bytes(),
            (HyperForm::Multi(a) | HyperForm::Integer(a), HyperForm::Multi(b) | HyperForm::Integer(b)) => a == b,
            (HyperForm::Nested(a), HyperForm::Nested(b)) => NestedGerm::same_recipe(a, b),
            _ => false,
        }
    }
}

impl Eq for HyperForm {}

impl std::hash::Hash for HyperForm {
    fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
        match self {
            HyperForm::Rational(h) => {
                0u8.hash(state);
                h.hash(state);
            }
            HyperForm::Germ(g) => {
                1u8.hash(state);
                g.to_bytes().hash(state);
            }
            HyperForm::Puiseux(p) => {
                2u8.hash(state);
                Closed::Series(p.clone()).hash(state);
            }
            HyperForm::Multi(m) | HyperForm::Integer(m) => {
                3u8.hash(state);
                m.hash(state);
            }
            HyperForm::Nested(g) => {
                4u8.hash(state);
                g.scale.name.hash(state);
            }
        }
    }
}

impl HyperForm {
    /// The rational function, when the value is one.
    pub fn rational(&self) -> Option<&Hyperreal> {
        match self {
            HyperForm::Rational(h) => Some(h),
            HyperForm::Puiseux(_)
            | HyperForm::Germ(_)
            | HyperForm::Multi(_)
            | HyperForm::Integer(_)
            | HyperForm::Nested(_) => None,
        }
    }

    /// How the value prints, its infinitesimal written `name`; a value of several prints each by its
    /// own name.
    pub fn render(&self, name: &str) -> String {
        match self {
            HyperForm::Rational(h) => h.render(name),
            HyperForm::Puiseux(p) => Closed::Series(p.clone()).render(name),
            HyperForm::Germ(g) => g.render(name),
            HyperForm::Multi(m) | HyperForm::Integer(m) => m.render(),
            HyperForm::Nested(g) => g.render(),
        }
    }
}

