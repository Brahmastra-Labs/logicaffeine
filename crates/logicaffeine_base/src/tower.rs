/// The program's infinitesimal: `Let <name> be an infinitesimal …`, its reciprocal's residues
/// modulo `modulus` limited to `allowed` (the parser has already intersected the stated facts),
/// or the contradiction refused when nothing is allowed.
pub fn new_infinitesimal<V: TowerValue>(name: &str, modulus: u64, allowed: &[u64]) -> Result<V, String> {
    let residues = ResidueType::from_allowed(modulus.max(1), allowed)
        .map_err(|e| e.describe(&format!("1/{name}")))?;
    Ok(V::hyper(HyperValue {
        value: HyperForm::Rational(Hyperreal::dt()),
        scale: Arc::new(Scale::new(name, residues)),
    }))
}

/// `Let <name> be an infinitesimal much smaller than <larger> [and much larger than <smaller>] …`: an
/// infinitesimal below `larger` and above `smaller`, each an infinitesimal itself or nothing, with its
/// reciprocal's residues as [`new_infinitesimal`] reads them. Refused when a bound is no infinitesimal,
/// when the two bounds are not already ordered, and when the name is one an infinitesimal it would be
/// ordered with already has.
pub fn new_ordered_infinitesimal<V: TowerValue>(
    name: &str,
    larger: &V,
    smaller: &V,
    modulus: u64,
    allowed: &[u64],
) -> Result<V, String> {
    let bound = |v: &V, relation: &str| -> Result<Option<Arc<Scale>>, String> {
        if v.is_nothing() {
            return Ok(None);
        }
        infinitesimal_scale(v).map(Some).ok_or_else(|| {
            format!(
                "an infinitesimal is declared {relation} another infinitesimal itself, not than {}",
                v.display_string()
            )
        })
    };
    let larger = bound(larger, "much smaller than")?;
    let smaller = bound(smaller, "much larger than")?;
    let residues = ResidueType::from_allowed(modulus.max(1), allowed)
        .map_err(|e| e.describe(&format!("1/{name}")))?;
    let scale = Scale::ordered(name, residues, larger, smaller)?;
    Ok(V::hyper(HyperValue {
        value: HyperForm::Rational(Hyperreal::dt()),
        scale: Arc::new(scale),
    }))
}

/// The infinitesimal a value is, when it is an infinitesimal itself.
fn infinitesimal_scale<V: TowerValue>(v: &V) -> Option<Arc<Scale>> {
    match v.exact()? {
        ExactRef::Hyper(h) if h.value == HyperForm::Rational(Hyperreal::dt()) => Some(h.scale.clone()),
        _ => None,
    }
}

/// The infinite natural `⌈1/dt⌉` generated by an infinitesimal value.
pub fn generator_of<V: TowerValue>(v: &V) -> Result<V, String> {
    match v.exact() {
        Some(ExactRef::Hyper(h)) if h.value == HyperForm::Rational(Hyperreal::dt()) => {
            Ok(V::natural(NaturalValue {
                value: Hypernatural::generator(&h.scale.residues),
                scale: h.scale.clone(),
            }))
        }
        _ => Err(format!(
            "the infinite generator is taken of the infinitesimal itself, not of {}",
            v.display_string()
        )),
    }
}

/// A limit rule by its English name.
pub fn limit_rule(name: &str) -> Result<LimitRule, String> {
    Ok(match name {
        "the standard part" | "standard part" => LimitRule::StandardPart,
        "the limit" | "limit" => LimitRule::Limit,
        "the limit superior" | "limit superior" => LimitRule::LimitSuperior,
        "the limit inferior" | "limit inferior" => LimitRule::LimitInferior,
        "the Cesàro mean" | "the Cesaro mean" | "Cesàro mean" | "Cesaro mean" => LimitRule::CesaroMean,
        other => return Err(format!("unknown limit rule: {other}")),
    })
}

/// Resolve a residue-dependent value under a limit rule; a value that does not depend on the
/// residue is its own limit under every rule. A value that depends on the residues of several
/// generators resolves each branch's finer dependence first: the residues of different generators
/// are independent, so the rule over every pair of classes is the rule over the coarser generator's
/// classes of the rule over the finer one's.
pub fn apply_limit<V: TowerValue>(v: &V, rule: LimitRule) -> Result<V, String> {
    let Some(d) = depends_of(v) else {
        return Ok(v.clone());
    };
    if d.value.branches().any(|(_, b)| residue_generator(&b.0).is_some()) {
        let inner = map_depends(d, |b| apply_limit(&b, rule)).map_err(|e| match rule {
            LimitRule::Limit | LimitRule::StandardPart => {
                format!("no limit: the value is {}", display(v).expect("a dependence displays"))
            }
            _ => e,
        })?;
        return apply_limit(&inner, rule);
    }
    let as_alg = d.value.map(|b| match classify(&b.0) {
        Some(Num::Rat(r)) => Some(Algebraic::from_rational(r)),
        Some(Num::Alg(a)) => Some(a),
        _ => None,
    });
    let all_numeric = as_alg.branches().all(|(_, a)| a.is_some());
    if !all_numeric {
        return match (rule, d.value.single()) {
            (_, Some(b)) => Ok(b.0.clone()),
            (LimitRule::Limit | LimitRule::StandardPart, None) => Err(format!(
                "no limit: the value is {}",
                display(v).expect("a dependence displays")
            )),
            _ => Err("only a numeric value has a limit superior, inferior or mean".to_string()),
        };
    }
    let algebraic = as_alg.map(|a| a.clone().expect("checked numeric"));
    algebraic
        .apply_with(rule, &d.scale.generator_text())
        .map(from_algebraic)
}

/// A provisional answer: the current guess after `steps` cases with `revisions` changes. A guess
/// that is already an answer joins this evidence to its own.
pub fn provisional<V: TowerValue>(value: V, steps: u64, revisions: u64) -> V {
    carry_evidence(&Converging::provisional((), steps, revisions), value)
}

/// Why a value cannot decide a branch — a residue-dependent answer, or a provisional one no proof
/// settled — or `None` for any other value. Every tier refuses such a branch with this sentence.
pub fn undecided_branch<V: TowerValue>(v: &V) -> Option<String> {
    match v.exact()? {
        ExactRef::Depends(_) => {
            let mut generators = Vec::new();
            generators_read(v, &mut generators);
            let listed = |each: &dyn Fn(&Scale) -> String| {
                let words: Vec<String> = generators.iter().map(|g| each(g)).collect();
                match words.split_last() {
                    Some((last, [])) => last.clone(),
                    Some((last, init)) => format!("{} and {last}", init.join(", ")),
                    None => unreachable!("a dependence reads a generator"),
                }
            };
            Some(format!(
                "this condition depends on the residue{} of {}: it is {}; declare what is known about {} or take a limit",
                if generators.len() > 1 { "s" } else { "" },
                listed(&|g| g.generator_text()),
                display(v).expect("a dependence displays"),
                listed(&|g| format!("1/{}", g.name)),
            ))
        }
        ExactRef::Converging(c) if !c.is_settled() => Some(format!(
            "a provisional answer cannot decide a condition: {}",
            display(v).expect("a provisional answer displays")
        )),
        _ => None,
    }
}

/// `not` lifted over residue branches and through provisional values; `None` for any other value.
pub fn not<V: TowerValue>(
    v: &V,
    recurse: &dyn Fn(V) -> Result<V, String>,
) -> Option<Result<V, String>> {
    match v.exact()? {
        ExactRef::Depends(d) => Some(map_depends(d, recurse)),
        ExactRef::Converging(c) => Some(recurse(c.value().clone()).map(|x| carry_evidence(c, x))),
        _ => None,
    }
}

// ── transport ─────────────────────────────────────────────────────────────────────────────────

/// Whether a value of the exact types can travel as data — to a task, through a channel, over the
/// wire: every value but one holding a real built from a function a program defines, in itself, in a
/// germ, in a branch of a residue-dependent value or as a provisional answer. A value model's own
/// lists are its own to walk.
pub fn transmissible<V: TowerValue>(v: &V) -> bool {
    match v.exact() {
        Some(ExactRef::Real(x)) => x.is_transmissible(),
        Some(ExactRef::Hyper(h)) => match &h.value {
            HyperForm::Germ(g) => g.is_transmissible(),
            HyperForm::Nested(g) => g.is_transmissible(),
            HyperForm::Rational(_) | HyperForm::Puiseux(_) | HyperForm::Multi(_) | HyperForm::Integer(_) => true,
        },
        Some(ExactRef::Depends(d)) => d.value.branches().all(|(_, b)| transmissible(&b.0)),
        Some(ExactRef::Converging(c)) => transmissible(c.value()),
        Some(ExactRef::Algebraic(_) | ExactRef::Natural(_) | ExactRef::Ordinal(_)) | None => true,
    }
}

/// An algebraic number (`0`), computable real (`1`) or ordinal (`2`) as its canonical bytes; `None`
/// for any other value, and for a real built from a function a program defines, which stays with the
/// program.
pub fn exact_bytes<V: TowerValue>(v: &V) -> Option<(u8, Vec<u8>)> {
    Some(match v.exact()? {
        ExactRef::Algebraic(a) => (0, a.to_bytes()),
        ExactRef::Real(x) if x.is_transmissible() => (1, x.to_bytes()),
        ExactRef::Ordinal(o) => (2, o.to_bytes()),
        _ => return None,
    })
}

/// The value [`exact_bytes`] wrote; `None` for a forged or non-canonical encoding.
pub fn from_exact_bytes<V: TowerValue>(kind: u8, bytes: &[u8]) -> Option<V> {
    let v: V = match kind {
        0 => from_algebraic(Algebraic::from_bytes(bytes)?),
        1 => from_exact_real(ExactReal::from_bytes(bytes)?),
        2 => from_ordinal(Ordinal::from_bytes(bytes)?),
        _ => return None,
    };
    (exact_bytes(&v)? == (kind, bytes.to_vec())).then_some(v)
}

/// The infinitesimal's name and its declaration's bytes ([`Scale::to_bytes`]): its reciprocal's
/// residue facts, and where it stands among the others.
pub fn scale_parts(scale: &Scale) -> (String, Vec<u8>) {
    (scale.name.clone(), scale.to_bytes())
}

/// The scale [`scale_parts`] wrote.
pub fn scale_from_parts(name: &str, bytes: &[u8]) -> Option<Arc<Scale>> {
    Scale::from_bytes(name, bytes)
}

impl Scale {
    /// The declaration's canonical bytes: the residue type of the reciprocal, and for an infinitesimal
    /// declared much smaller or much larger than another, a `1` and each of those two in turn — a `0`
    /// for none, or a `1`, its name and its own bytes. An infinitesimal declared on its own writes its
    /// residue type alone. A residue class's copy writes the declaration it refines.
    pub fn to_bytes(&self) -> Vec<u8> {
        let mut out = Vec::new();
        self.write_declaration(&mut out);
        out
    }

    fn write_declaration(&self, out: &mut Vec<u8>) {
        let scale = self.declaration();
        scale.residues.write(out);
        if scale.much_smaller_than.is_none() && scale.much_larger_than.is_none() {
            return;
        }
        out.push(1);
        for bound in [&scale.much_smaller_than, &scale.much_larger_than] {
            match bound {
                None => out.push(0),
                Some(b) => {
                    out.push(1);
                    crate::exact_codec::write_len(b.name.len(), out);
                    out.extend_from_slice(b.name.as_bytes());
                    let bytes = b.to_bytes();
                    crate::exact_codec::write_len(bytes.len(), out);
                    out.extend_from_slice(&bytes);
                }
            }
        }
    }

    /// The infinitesimal [`Scale::to_bytes`] wrote under `name`; `None` for a forged or non-canonical
    /// encoding, or a declaration its bounds refuse.
    pub fn from_bytes(name: &str, bytes: &[u8]) -> Option<Arc<Scale>> {
        Scale::read_declaration(name, bytes, 0)
    }

    fn read_declaration(name: &str, bytes: &[u8], depth: usize) -> Option<Arc<Scale>> {
        use crate::exact_codec::{read_byte, read_len, MAX_WIRE_DEPTH, MAX_WIRE_LEN};
        if depth > MAX_WIRE_DEPTH {
            return None;
        }
        let mut pos = 0;
        let residues = ResidueType::read(bytes, &mut pos)?;
        let scale = if pos == bytes.len() {
            Scale::new(name, residues)
        } else {
            if read_byte(bytes, &mut pos)? != 1 {
                return None;
            }
            let mut bounds = Vec::with_capacity(2);
            for _ in 0..2 {
                bounds.push(match read_byte(bytes, &mut pos)? {
                    0 => None,
                    1 => {
                        let n = read_len(bytes, &mut pos, MAX_WIRE_LEN)?;
                        let bound_name = std::str::from_utf8(bytes.get(pos..pos.checked_add(n)?)?).ok()?.to_string();
                        pos += n;
                        let n = read_len(bytes, &mut pos, MAX_WIRE_LEN)?;
                        let inner = bytes.get(pos..pos.checked_add(n)?)?;
                        pos += n;
                        Some(Scale::read_declaration(&bound_name, inner, depth + 1)?)
                    }
                    _ => return None,
                });
            }
            let smaller = bounds.pop().expect("two bounds");
            let larger = bounds.pop().expect("two bounds");
            if larger.is_none() && smaller.is_none() {
                return None;
            }
            Scale::ordered(name, residues, larger, smaller).ok()?
        };
        (pos == bytes.len() && scale.to_bytes() == bytes).then(|| Arc::new(scale))
    }
}

/// A hyperreal (`0`), infinite integer (`1`), germ (`2`), root of a hyperreal (`3`), exact value of
/// several infinitesimals (`4`), germ of several (`5`) or infinite integer of several (`6`) as its
/// scale and canonical bytes — the scale of
/// a value of several its smallest infinitesimal, the bytes naming every one it involves; `None` for any
/// other value, and for a germ holding a real built from a function a program defines.
pub fn scaled_bytes<V: TowerValue>(v: &V) -> Option<(u8, String, Vec<u8>, Vec<u8>)> {
    Some(match v.exact()? {
        ExactRef::Hyper(h) => {
            let (name, residues) = scale_parts(&h.scale);
            match &h.value {
                HyperForm::Rational(r) => (0, name, residues, r.to_bytes()),
                HyperForm::Puiseux(p) => (3, name, residues, p.to_bytes()),
                HyperForm::Germ(g) if g.is_transmissible() => (2, name, residues, g.to_bytes()),
                HyperForm::Germ(_) => return None,
                HyperForm::Multi(m) => (4, name, residues, m.to_bytes()),
                HyperForm::Integer(m) => (6, name, residues, m.to_bytes()),
                HyperForm::Nested(g) if g.is_transmissible() => (5, name, residues, g.to_bytes()),
                HyperForm::Nested(_) => return None,
            }
        }
        ExactRef::Natural(n) => {
            let (name, residues) = scale_parts(&n.scale);
            (1, name, residues, n.value.to_bytes())
        }
        _ => return None,
    })
}

/// The value [`scaled_bytes`] wrote; `None` for a forged or non-canonical encoding.
pub fn from_scaled_bytes<V: TowerValue>(kind: u8, name: &str, residues: &[u8], bytes: &[u8]) -> Option<V> {
    let scale = scale_from_parts(name, residues)?;
    let v: V = match kind {
        0 => from_hyper(Hyperreal::from_bytes(bytes)?, &scale),
        1 => from_natural(Hypernatural::from_bytes(bytes)?, &scale),
        2 => from_germ(Germ::from_bytes(bytes)?, &scale),
        3 => from_closed(Closed::Series(Puiseux::from_bytes(bytes)?), &scale),
        4 => from_multi(Multi::from_bytes(bytes)?),
        5 => from_nested(NestedGerm::from_bytes(bytes)?),
        6 => from_multi(Multi::from_bytes(bytes)?),
        _ => return None,
    };
    let canonical = scaled_bytes(&v)?;
    (canonical == (kind, name.to_string(), residues.to_vec(), bytes.to_vec())).then_some(v)
}

/// A residue-dependent value rebuilt from its scale, modulus and per-class values.
pub fn depends_from_parts<V: TowerValue>(
    name: &str,
    residues: &[u8],
    modulus: u64,
    branches: Vec<Option<V>>,
) -> Option<V> {
    let scale = scale_from_parts(name, residues)?;
    let raw = branches.into_iter().map(|b| b.map(Branch)).collect();
    let value = Depends::from_branches(scale.residues.clone(), modulus, raw)?;
    let built: V = from_depends(value.clone(), &scale);
    match depends_of(&built) {
        Some(d) if d.value == value => Some(built),
        _ => None,
    }
}

