//! # RUNG 4 — the Steenrod squares are the operations that structure the char-2 tower
//!
//! The characteristic-2 tower (the split §27, the Frobenius twist §30, the `Λ³` tangent §32–§38) lives in the
//! mod-2 cohomology `H*((RP^∞)^o; 𝔽₂) = 𝔽₂[x_1,…,x_o]`, where the **Steenrod squares** `Sq^i` act. The total
//! square `Sq` is the ring endomorphism `x ↦ x + x²` — literally `identity + Frobenius`. We show, reusing the
//! repo's Steenrod engine (`src/steenrod.rs`), that the tower's characteristic-2 phenomena ARE Steenrod facts:
//!
//!   1. `Sq = 1 + Frobenius`: the top component of the total square is the squaring, and the Frobenius twist
//!      `O^{(1)} = ⟨x_j²⟩` is its image.
//!   2. **§30's polarization-invisibility is a Steenrod fact:** the Frobenius twists `O^{(2^m)} = ⟨x_j^{2^m}⟩`
//!      are *Steenrod-simple* — every intermediate square `Sq^i` (`0 < i < 2^m`) kills them, because
//!      `C(2^m, i) ≡ 0 (mod 2)` (Lucas). The `p`-th power the multilinear/exterior attacks cannot see is the
//!      class only the identity and the *top* square touch.
//!   3. The squaring is multiplicative (Cartan) — the Frobenius ring endomorphism `(a+b)² = a²+b²`, the `p=2`
//!      engine `p ∣ C(p,k)`, now as the Steenrod Cartan formula.
//!   4. The Steenrod generators are the iterated Frobenius squares `Sq^{2^m}` (the `h_m`) — the same
//!      power-of-two layers the Frobenius cascade climbs.

use logicaffeine_proof::steenrod::{adams_one_line, apply_sq, sq, total_square};

#[test]
fn the_total_steenrod_square_is_identity_plus_frobenius() {
    // Sq(x) = x + x²  — the total square on a linear form is identity + squaring. The Frobenius twist O^{(1)}
    // is the top (x²) component. So Sq^0 = id, Sq^1 = the Frobenius square, on degree-1 classes.
    assert_eq!(total_square(&[0, 1]), vec![0, 1, 1], "Sq(x) = x + x²");
    assert_eq!(sq(0, 1), 1, "Sq⁰ = identity");
    assert_eq!(sq(1, 1), 1, "Sq¹(x) = x² — the Frobenius square");
    for i in 2..8 {
        assert_eq!(
            sq(i, 1),
            0,
            "Sqⁱ(x) = 0 for i > deg — nothing above the top square"
        );
    }
    // Sq¹ applied to a linear form literally squares it (the Frobenius twist, one class).
    assert_eq!(apply_sq(1, &[0, 1]), vec![0, 0, 1], "Sq¹(x) = x²");
}

#[test]
fn the_frobenius_twists_are_the_steenrod_simple_classes_section_30_as_a_steenrod_fact() {
    // §30's polarization-invisibility, identified: the p-th power x_j^{2^m} is invisible to every intermediate
    // Steenrod square. Only Sq⁰ (identity) and Sq^{2^m} (its own Frobenius square) act nontrivially — because
    // C(2^m, i) ≡ 0 (mod 2) for 0 < i < 2^m (Lucas: 2^m has a single binary digit). This is EXACTLY the reason
    // the multilinear/exterior attacks cannot read the Frobenius layer.
    for m in 1..=5usize {
        let p = 1usize << m; // 2^m
        assert_eq!(sq(0, p), 1, "Sq⁰(x^{p}) = x^{p} (identity)");
        assert_eq!(
            sq(p, p),
            1,
            "Sq^{p}(x^{p}) = x^{{2·{p}}} — the top square is the Frobenius"
        );
        for i in 1..p {
            assert_eq!(
                sq(i, p),
                0,
                "Sq^{i}(x^{p}) = 0 — the Frobenius twist is invisible to the intermediate squares"
            );
        }
    }
}

#[test]
fn the_squaring_is_multiplicative_the_frobenius_ring_endomorphism_is_cartan() {
    // Cartan: the total square is a ring homomorphism, Sq(f·g) = Sq(f)·Sq(g). This IS the Frobenius endomorphism
    // (a+b)² = a²+b² (the p=2 case of the engine p ∣ C(p,k)), phrased in the Steenrod algebra. We verify it on
    // several polynomials in 𝔽₂[x] (the single-generator cohomology; the multi-variable case is Cartan applied
    // coordinatewise).
    fn poly_mul(a: &[u8], b: &[u8]) -> Vec<u8> {
        let mut r = vec![0u8; a.len() + b.len()];
        for (i, &x) in a.iter().enumerate() {
            for (j, &y) in b.iter().enumerate() {
                r[i + j] ^= x & y;
            }
        }
        while r.len() > 1 && *r.last().unwrap() == 0 {
            r.pop();
        }
        r
    }
    let samples: [&[u8]; 4] = [&[0, 1], &[1, 1], &[0, 0, 1], &[1, 0, 1]]; // x, 1+x, x², 1+x²
    for f in samples {
        for g in samples {
            let lhs = total_square(&poly_mul(f, g));
            let rhs = poly_mul(&total_square(f), &total_square(g));
            assert_eq!(
                lhs, rhs,
                "Sq is a ring homomorphism (Cartan / Frobenius): Sq(fg) = Sq(f)Sq(g)"
            );
        }
    }
}

#[test]
fn the_steenrod_generators_are_the_iterated_frobenius_squares() {
    // The mod-2 Steenrod algebra is generated by Sq^{2^m} (the h_m), and dim Ext^{1,t} = 1 iff t is a power of
    // two — i.e. the indecomposable operations are exactly the iterated Frobenius squares. The Frobenius
    // cascade climbs precisely these power-of-two layers (O → O^{(2)} → O^{(4)} → …).
    for t in 1..=32usize {
        let expected = usize::from(t.is_power_of_two());
        assert_eq!(
            adams_one_line(t),
            expected,
            "dim Ext^{{1,{t}}} = {expected} (=1 iff {t} is a power of two = a Frobenius square)"
        );
    }
}
