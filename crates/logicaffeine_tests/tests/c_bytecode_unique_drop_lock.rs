//! Bytecode C's `own[]` copy-on-write proof must also reclaim function-local
//! scalar sequences on return. Recursive merge sort is the lock: without this,
//! each frame retains its two work buffers until the process exits.

#![cfg(not(target_arch = "wasm32"))]

mod common;

use logicaffeine_compile::compile::{
    compile_to_c_via_bytecode, compile_to_c_via_bytecode_traced, vm_outcome,
};
use logicaffeine_compile::optimization::Opt;

const SORT: &str = r#"
## To mergeSort (arr: Seq of Int) -> Seq of Int:
    Let n be length of arr.
    If n is less than 2:
        Return arr.
    Let mid be n / 2.
    Let mutable left be a new Seq of Int.
    Let mutable right be a new Seq of Int.
    Let mutable i be 1.
    While i is at most mid:
        Push item i of arr to left.
        Set i to i + 1.
    While i is at most n:
        Push item i of arr to right.
        Set i to i + 1.
    Set left to mergeSort(left).
    Set right to mergeSort(right).
    Let mutable result be arr.
    Let mutable li be 1.
    Let mutable ri be 1.
    Let mutable k be 1.
    While li is at most length of left and ri is at most length of right:
        If item li of left is at most item ri of right:
            Set item k of result to item li of left.
            Set li to li + 1.
        Otherwise:
            Set item k of result to item ri of right.
            Set ri to ri + 1.
        Set k to k + 1.
    While li is at most length of left:
        Set item k of result to item li of left.
        Set li to li + 1.
        Set k to k + 1.
    While ri is at most length of right:
        Set item k of result to item ri of right.
        Set ri to ri + 1.
        Set k to k + 1.
    Return result.

## Main
Let mutable values be [9, 1, 7, 3, 5, 2, 8, 4, 6].
Set values to mergeSort(values).
Show values.
"#;

fn c_output(source: &str) -> String {
    let c = compile_to_c_via_bytecode(source).expect("source compiles through bytecode to C");
    let dir = tempfile::Builder::new()
        .prefix("logos_cbc_unique_drop_")
        .tempdir()
        .expect("temporary C directory");
    let c_path = dir.path().join("main.c");
    let bin_path = dir.path().join("main");
    std::fs::write(&c_path, c).expect("write generated C");
    let build = common::build_c_release(&c_path, &bin_path).expect("C compiler starts");
    assert!(
        build.status.success(),
        "generated bytecode C builds:\n{}",
        String::from_utf8_lossy(&build.stderr)
    );
    let run = std::process::Command::new(&bin_path)
        .output()
        .expect("generated bytecode C starts");
    assert!(
        run.status.success(),
        "generated bytecode C exits cleanly:\n{}",
        String::from_utf8_lossy(&run.stderr)
    );
    String::from_utf8_lossy(&run.stdout).into_owned()
}

#[test]
fn bytecode_c_reclaims_owned_recursive_work_buffers() {
    let (c, trace) =
        compile_to_c_via_bytecode_traced(SORT).expect("sort compiles to traced bytecode C");
    assert!(
        c.contains("/* unique local drop */"),
        "bytecode C emitted no owned-register reclamation:\n{c}"
    );
    assert!(
        c.contains("lc_gc_free(_drop") && c.contains("->data); lc_gc_free(_drop"),
        "cleanup must release both the scalar payload and its register-sized box to the collector:\n{c}"
    );
    assert!(
        trace.lowering.fired(Opt::Unbox),
        "owned-register reclamation silently disappeared from the bytecode-C trace: {:?}",
        trace.lowering.keywords()
    );
}

#[test]
fn reclaimed_bytecode_c_matches_the_vm_across_early_and_recursive_returns() {
    if !common::require_tool(&common::c_compiler()) {
        return;
    }
    let vm = vm_outcome(SORT);
    assert!(vm.error.is_none(), "VM failed: {:?}", vm.error);
    assert_eq!(
        c_output(SORT),
        vm.output,
        "reclaimed bytecode C diverged from the VM"
    );
}
