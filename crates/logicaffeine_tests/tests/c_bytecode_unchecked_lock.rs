//! Bytecode C must preserve the VM compiler's proven-unchecked sequence
//! opcodes.  Merging `IndexUnchecked`/`SetIndexUnchecked` back into the checked
//! `logos_idx0` lowering silently discarded the optimizer's proof in exactly
//! the hot matrix loop that Rust and the JIT keep check-free.

#![cfg(not(target_arch = "wasm32"))]

mod common;

use logicaffeine_compile::compile::{
    compile_to_c_via_bytecode, compile_to_c_via_bytecode_traced, vm_outcome,
};
use logicaffeine_compile::optimization::Opt;

const DYNAMIC_MATRIX: &str = include_str!("../../../benchmarks/programs/matrix_mult/main.lg");

const MATRIX: &str = r#"
## Main
Let n be 7.
Let a be a new Seq of Int.
Let b be a new Seq of Int.
Let c be a new Seq of Int.
Let seed be 42.
Let i be 0.
While i is less than n * n:
    Set seed to (seed * 1103515245 + 12345) % 2147483648.
    Push (seed / 65536) % 100 to a.
    Set i to i + 1.
Set i to 0.
While i is less than n * n:
    Set seed to (seed * 1103515245 + 12345) % 2147483648.
    Push (seed / 65536) % 100 to b.
    Push 0 to c.
    Set i to i + 1.
Set i to 0.
While i is less than n:
    Let k be 0.
    While k is less than n:
        Let j be 0.
        While j is less than n:
            Let idx be i * n + j + 1.
            Set item idx of c to (item idx of c + item (i * n + k + 1) of a * item (k * n + j + 1) of b) % 1000000007.
            Set j to j + 1.
        Set k to k + 1.
    Set i to i + 1.
Let checksum be 0.
Set i to 1.
While i is at most n * n:
    Set checksum to (checksum * 31 + item i of c) & 268435455.
    Set i to i + 1.
Show checksum.
"#;

fn c_output(source: &str) -> String {
    let c = compile_to_c_via_bytecode(source).expect("source compiles through bytecode to C");
    let dir = tempfile::Builder::new()
        .prefix("logos_cbc_unchecked_")
        .tempdir()
        .expect("temporary C directory");
    let c_path = dir.path().join("main.c");
    let bin_path = dir.path().join("main");
    std::fs::write(&c_path, c).expect("write generated C");
    let build = common::build_c_release(&c_path, &bin_path).expect("C compiler starts");
    assert!(
        build.status.success(),
        "generated bytecode C builds:\n{}",
        String::from_utf8_lossy(&build.stderr)
    );
    let run = std::process::Command::new(&bin_path)
        .output()
        .expect("generated bytecode C starts");
    assert!(
        run.status.success(),
        "generated bytecode C exits cleanly:\n{}",
        String::from_utf8_lossy(&run.stderr)
    );
    String::from_utf8_lossy(&run.stdout).into_owned()
}

#[test]
fn bytecode_c_consumes_unchecked_index_opcodes() {
    let (c, trace) = compile_to_c_via_bytecode_traced(DYNAMIC_MATRIX)
        .expect("matrix compiles to traced bytecode C");
    assert!(
        trace.lowering.fired(Opt::Unchecked),
        "bytecode C silently put bounds checks back after unchecked bytecode selection: optimizer={:?} lowering={:?}",
        trace.optimizer.keywords(),
        trace.lowering.keywords()
    );
    assert!(
        c.contains("->data[(size_t)(r["),
        "the generated bytecode C contains no direct proven-in-bounds sequence access"
    );
}

#[test]
fn unchecked_bytecode_c_matrix_matches_the_vm() {
    if !common::require_tool(&common::c_compiler()) {
        return;
    }
    let vm = vm_outcome(MATRIX);
    assert!(vm.error.is_none(), "VM failed: {:?}", vm.error);
    assert_eq!(
        c_output(MATRIX),
        vm.output,
        "unchecked bytecode-C loads/stores diverged from the VM"
    );
}
