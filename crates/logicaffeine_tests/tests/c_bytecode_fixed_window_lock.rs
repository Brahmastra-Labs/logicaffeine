//! C bytecode must consume the same fixed-window text-comparison shape as
//! Rust and direct C. The scalar bytecode loop remains the guarded fallback,
//! but an owned ASCII builder must not allocate two one-character Text values
//! for every candidate byte.

#![cfg(not(target_arch = "wasm32"))]

mod common;

use logicaffeine_compile::compile::{
    compile_to_c_via_bytecode, compile_to_c_via_bytecode_traced, vm_outcome_with_args,
};
use logicaffeine_compile::optimization::{decorate_source, Opt};

const STRING_SEARCH: &str = include_str!("../../../benchmarks/programs/string_search/main.lg");
const MARKER: &str = "shared fixed-window byte compare: guarded bytecode-C fast path";

fn c_output(source: &str, args: &[&str]) -> String {
    let c = compile_to_c_via_bytecode(source).expect("source compiles through bytecode to C");
    let dir = tempfile::Builder::new()
        .prefix("logos_cbc_fixed_window_")
        .tempdir()
        .expect("temporary C directory");
    let c_path = dir.path().join("main.c");
    let bin_path = dir.path().join("main");
    std::fs::write(&c_path, c).expect("write generated C");
    let build = common::build_c_release(&c_path, &bin_path).expect("C compiler starts");
    assert!(
        build.status.success(),
        "generated bytecode C builds:\n{}",
        String::from_utf8_lossy(&build.stderr)
    );
    let run = std::process::Command::new(&bin_path)
        .args(args)
        .output()
        .expect("generated bytecode C starts");
    assert!(
        run.status.success(),
        "generated bytecode C exits cleanly:\n{}",
        String::from_utf8_lossy(&run.stderr)
    );
    String::from_utf8_lossy(&run.stdout).into_owned()
}

#[test]
fn bytecode_c_traces_the_fixed_window_fast_path() {
    let (c, trace) = compile_to_c_via_bytecode_traced(STRING_SEARCH)
        .expect("string search compiles to traced bytecode C");
    assert!(
        c.contains(MARKER),
        "the C-bytecode string-search hot loop silently lost its fixed-window fast path"
    );
    assert!(
        trace.lowering.fired(Opt::Simd),
        "C bytecode emitted the fast path without reporting Simd: {:?}",
        trace.lowering.keywords()
    );

    let disabled = decorate_source(STRING_SEARCH, &["simd"]);
    let (off, off_trace) = compile_to_c_via_bytecode_traced(&disabled)
        .expect("string search compiles with Simd disabled");
    assert!(
        !off.contains(MARKER),
        "disabling Simd must restore the scalar bytecode-C loop"
    );
    assert!(
        !off_trace.lowering.fired(Opt::Simd),
        "a disabled C-bytecode optimization must not be traced"
    );
}

#[test]
fn fixed_window_bytecode_c_matches_the_vm() {
    if !common::require_tool(&common::c_compiler()) {
        return;
    }
    let vm_args = vec!["bench".to_string(), "5000".to_string()];
    let vm = vm_outcome_with_args(STRING_SEARCH, &vm_args, None);
    assert!(vm.error.is_none(), "VM failed: {:?}", vm.error);
    assert_eq!(
        c_output(STRING_SEARCH, &["5000"]),
        vm.output,
        "the guarded C-bytecode fixed-window path diverged from the VM"
    );
}
