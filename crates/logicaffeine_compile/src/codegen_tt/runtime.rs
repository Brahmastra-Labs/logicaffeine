//! `kernel_main()` entry, and substitutes the `{KERNEL_FILE}` token in the host
//! and CMake with [`super::KERNEL_FILE_NAME`].

/// Prepended to the LOGOS→C compute body to form the compute kernel. Brings in
/// the TT-Metalium data-movement + DPRINT APIs and bridges the C backend's
/// `printf`/`puts` (how `Show` is emitted) to the host DPRINT stream, so kernel
/// output is textually identical to the VM's.
pub const TT_KERNEL_PREAMBLE: &str = r#"// Auto-generated by LOGOS codegen_tt — do not edit.
// TT-Metalium compute kernel: runs a whole LOGOS program on ONE Tensix baby
// RISC-V core (DataMovementProcessor::RISCV_0). `Show` output is streamed to the
// host via the DPRINT server. The compute body below is the LOGOS→C lowering —
// byte-for-byte equal to the VM (locked by the host oracle in tenstorrent_aot_lock).
#include "dataflow_api.h"
#include "debug/dprint.h"

// --- Show bridge -------------------------------------------------------------
// The C backend prints with printf/puts; on-core we format into a small stack
// buffer and stream it through DPRINT so the host sees identical text.
#ifndef LOGOS_TT_SHOW_BRIDGE
#define LOGOS_TT_SHOW_BRIDGE
#define printf(...) do { char _logos_lb[256]; snprintf(_logos_lb, sizeof _logos_lb, __VA_ARGS__); DPRINT << _logos_lb; } while (0)
#define puts(_s)    do { DPRINT << (_s) << ENDL(); } while (0)
#endif
// --- LOGOS→C compute body ----------------------------------------------------
"#;

/// The host orchestrator. Opens a 1x1 unit mesh on device 0, creates a program
/// with a single data-movement kernel on `RISCV_0`, launches it, waits, and
/// closes. Targets the current TT-Metalium `MeshDevice` API (as in the
/// `add_2_integers_in_riscv` example). `{KERNEL_FILE}` is the kernel source path.
pub const TT_HOST_TEMPLATE: &str = r#"// Auto-generated by LOGOS codegen_tt — do not edit.
// Host orchestrator for a single-Tensix-core LOGOS program.
#include <tt-metalium/host_api.hpp>
#include <tt-metalium/device.hpp>
#include <tt-metalium/mesh_device.hpp>

using namespace tt;
using namespace tt::tt_metal;

int main() {
    // 1x1 unit mesh on device 0; DPRINT (TT_METAL_DPRINT_CORES) streams `Show` output.
    auto mesh = distributed::MeshDevice::create_unit_mesh(0);
    distributed::MeshCommandQueue& cq = mesh->mesh_command_queue();

    Program program = CreateProgram();
    constexpr CoreCoord core = {0, 0};

    // The whole LOGOS program runs on ONE baby RISC-V core (data-movement 0).
    KernelHandle compute = CreateKernel(
        program,
        "{KERNEL_FILE}",
        core,
        DataMovementConfig{.processor = DataMovementProcessor::RISCV_0,
                           .noc = NOC::RISCV_0_default});
    SetRuntimeArgs(program, compute, core, {});

    distributed::MeshWorkload workload;
    workload.add_program(distributed::MeshCoordinateRange(mesh->shape()), std::move(program));
    distributed::EnqueueMeshWorkload(cq, workload, /*blocking=*/true);
    Finish(cq);

    mesh->close();
    return 0;
}
"#;

