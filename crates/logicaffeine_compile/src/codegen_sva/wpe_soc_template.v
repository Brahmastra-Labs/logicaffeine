// wpe_soc___NAME__ — the UNIVERSAL config-driven whole-program engine, LOADABLE OVER A UART WIRE.
// One fixed netlist runs ANY program that fits the caps: a host streams the program's flat image (per-field
// config memories, each length-prefixed) + its params over the wire; the loader FSM fills the on-chip config
// memories, INIT seeds the register file from the params, the interpret st-machine runs (== eval_wprog_config
// == the VM), and the 64-bit result + run-cycle count stream back over the wire — then it loops for the next
// program. Integer func units only (synthesizable); a real multi-cycle FPU is the float follow-on. Generated by
// emit_wprog_engine_soc_verilog; the interpret core is the SAME logic proven in emit_wprog_engine_verilog.
`timescale 1ns/1ps
module wpe_soc___NAME__ #(parameter MUL_TREE = 0, parameter CLKS_PER_BIT = 868, parameter WITH_FPU = 1, parameter CFG_BRAM = 0, parameter RDW_DETECT = 0) (
  input        clk,
  input        rst,
  input        uart_rx,
//__PROBE_ONLY_BEGIN__
  output        probe_running,
  output [6:0]  probe_st,
  output [15:0] probe_pc,
  output [15:0] probe_cell,
  output [15:0] probe_sp,
  output [15:0] probe_hp,
  output [31:0] probe_cycles,
//__PROBE_ONLY_END__
//__ONCHIP_ALL_BEGIN__
  output reg   uart_tx
//__ONCHIP_ALL_END__
//__OFFCHIP_ANY_BEGIN__
  output reg   uart_tx,
  output       psram_ce_n,
  output       psram_sclk,
  output [3:0] psram_sio_out,
  output [3:0] psram_sio_oe,
  input  [3:0] psram_sio_in
//__OFFCHIP_ANY_END__
);
  localparam CW = 20;
  localparam NREG=48, MAXBLK=16, MAXCELL=64, MAXWR=64, MAXARG=16, MAXLIV=48, MAXK=64, HEAP=128, DEPTH=24, MAXV=64;

  // ── config memories (filled by the loader; the SAME fields eval_wprog_config walks) ──
  reg [31:0] blk_livein_ptr [0:MAXBLK-1];
  reg [31:0] blk_n_livein   [0:MAXBLK-1];
  reg [31:0] blk_cell_ptr   [0:MAXBLK-1];
  reg [31:0] blk_n_cells    [0:MAXBLK-1];
  reg [31:0] blk_write_ptr  [0:MAXBLK-1];
  reg [31:0] blk_n_writes   [0:MAXBLK-1];
  reg [31:0] blk_term_kind  [0:MAXBLK-1];
  reg [31:0] blk_t0         [0:MAXBLK-1];
  reg [31:0] blk_t1         [0:MAXBLK-1];
  reg [31:0] blk_top        [0:MAXBLK-1];
  reg [31:0] blk_cdst       [0:MAXBLK-1];
  reg [31:0] blk_cargc      [0:MAXBLK-1];
  reg [31:0] blk_cargp      [0:MAXBLK-1];
//__ONCHIP_CELLS_BEGIN__
  reg [31:0] cell_kind      [0:MAXCELL-1];
  reg [31:0] cell_code      [0:MAXCELL-1];
  reg [31:0] cell_op0       [0:MAXCELL-1];
  reg [31:0] cell_op1       [0:MAXCELL-1];
  reg [31:0] cell_op2       [0:MAXCELL-1];
  reg [31:0] cell_op3       [0:MAXCELL-1];
//__ONCHIP_CELLS_END__
//__OFFCHIP_CELLS_BEGIN__
  // The config image lives off-chip as three lanes of one 64-bit word per cell — {code, kind}, {op1, op0},
  // {op3, op2} — each behind its own cache. The loader writes a 32-bit field at a time through `cwrite`.
  reg [2:0] cq_w;
  reg [31:0] cq_wa;
  reg [63:0] cq_wd;
  reg [1:0] cq_wm;
  // Each lane's hits for the current cell (`cq_rhit`) and the write address (`cq_whit`), registered beside the
  // address they are the hits of, so a lane's stall never waits on its tag lookup (codegen_sva::psram).
  reg [2:0] cq_rhit, cq_whit;
  task cwrite(input [5:0] f, input [15:0] e, input [31:0] v);
    begin cq_w <= 3'b001 << f[2:1]; cq_wa <= {16'd0, e}; cq_whit <= cq_hit_at({16'd0, e}); cq_wd <= {v, v}; cq_wm <= f[0] ? 2'b10 : 2'b01; end
  endtask
//__OFFCHIP_CELLS_END__
  reg [31:0] wr_reg         [0:MAXWR-1];
  reg [31:0] wr_op          [0:MAXWR-1];
  reg [31:0] arg_op         [0:MAXARG-1];
  reg [31:0] liv_reg        [0:MAXLIV-1];
  reg signed [63:0] konst   [0:MAXK-1];

  // ── engine state ──
  // The four 64-bit STATE memories (`file`, `v`, `heap`, `sfile`) are each declared as TWO 32-bit halves (`*_lo`/`*_hi`).
  // A single 64-bit-wide array maps to one RAMB36E1 in SDP-72 mode, whose parity-lane WRITE port (DIPBDIP) yosys
  // 0.33's synth_xilinx mis-wires to the SAME nets as DIPADIP — so the 8 parity bits a 64-bit word needs are never
  // stored, and any value ≥256 reads back corrupted (verified at gate level). Two 32-bit halves never spill into a
  // parity lane, so each maps to a clean ×32 RAMB with no parity write. The halves are recombined on read as a
  // signed 64-bit word (`{hi, lo}`) — bit-identical to the original array. `file0` maps CORRECTLY (it is flip-flops,
  // never a wide RAMB), so it is left as-is. `heap` was ALSO split after an on-chip readback of the real Artix-7
  // showed its high 32 bits mis-map: positive weights (high word 0) read back correct, but every NEGATIVE weight
  // (high word 0xFFFFFFFF) read back with its high word corrupted to a constant parity-spill mask — the identical
  // signature to file/v/sfile. The earlier gate-level model missed it because it only round-tripped positive words.
  reg [31:0] file_lo [0:NREG-1];
  reg [31:0] file_hi [0:NREG-1];
  reg signed [63:0] file0 [0:NREG-1];   // BLOCK-ENTRY snapshot of `file` — the write/terminator phases read this
                                        // under CFG_BRAM=0. Under CFG_BRAM=1 it is DEAD (never read/written): the
                                        // write phase reads block-entry `file` directly (cells never write `file`)
                                        // through the registered file_rd port and a read-before-write buffer.
  reg [31:0] v_lo [0:MAXV-1];
  reg [31:0] v_hi [0:MAXV-1];
//__ONCHIP_HEAP_BEGIN__
  // DEPTH-BANKED heap: the 32768-deep heap is split into TWO 16384-deep banks selected by heap-address bit 14
  // (in-bank index = bits [13:0]). A flat 32768-deep ×1 heap half mapped to a RAMB36E1 in ×1-width, 32768-deep
  // mode — the internal depth-cascade of the block's two 16K halves (address bit 15 tied high on the upper tiles)
  // is the least-fuzzed RAMB corner, which prjxray/openXC7 mis-encodes on the XC7A200T (a heap read >= the first
  // 16K reads back off by ≈1.5·N on silicon, though the gate-level netlist is ≡VM — the defect is BELOW the
  // netlist). A 16384-deep bank instead uses a clean 14-bit index and NO 32K depth-cascade — the better-fuzzed
  // primitive. Behaviorally IDENTICAL to a flat 32768 heap (bank-select bit 14 + [13:0] index reconstruct the
  // same word). Each half stays a 32-bit lane (the SDP-72 parity-mis-wire fix). HBANK0/HBANK1 keep small-HEAP
  // configs bit-identical: when HEAP<=16384 bit 14 is always 0, so bank1 is dead (stubbed to depth 1) and bank0
  // holds the whole heap through its [13:0] index (== the flat address), leaving those netlists unchanged.
  localparam HBANK0 = (HEAP > 16384) ? 16384 : HEAP;
  localparam HBANK1 = (HEAP > 16384) ? (HEAP - 16384) : 1;
  reg [31:0] heap_b0_lo [0:HBANK0-1];
  reg [31:0] heap_b0_hi [0:HBANK0-1];
  reg [31:0] heap_b1_lo [0:HBANK1-1];
  reg [31:0] heap_b1_hi [0:HBANK1-1];

  // ── BANK SELECT / IN-BANK INDEX ────────────────────────────────────────────────────────────────
  // These MUST be a comparison against HBANK0, not address bit 14. Bit-14 banking with a [13:0]
  // in-bank index addresses only 15 bits — it silently DROPS bit 15 — while HEAP is sized from the
  // program's measured footprint and routinely exceeds 32768 (a 32768-element Seq needs 32769 words,
  // and caps add margin on top). Any address >= 32768 therefore aliased to the bottom of bank 0, so
  // the LAST element of a 32768-element Seq read back `heap[0]` — the collection's own LENGTH.
  // MEASURED: heap 32768 was correct and heap 32769 returned length*length; see
  // `analytics_rtl_equals_vm_at_every_arg`.
  // Bank 0's index stays `a[13:0]`: it is used only when `!hsel(a)`, i.e. a < HBANK0 <= 16384, where
  // the low 14 bits ARE the address.
  function hsel(input [31:0] a); hsel = (a >= HBANK0); endfunction
  function [31:0] hb1_idx(input [31:0] a); hb1_idx = (a >= HBANK0) ? (a - HBANK0) : 32'd0; endfunction
//__ONCHIP_HEAP_END__
//__OFFCHIP_HEAP_BEGIN__
  // The heap lives off-chip behind its cache, which keeps the on-chip heap's port: `heap_rd` is
  // heap[heap_ra] one cycle after `hread` whenever the line is resident. Requests pulse (`hq_r`/`hq_w`)
  // the cycle after their task runs; the addresses and write data hold until the next one.
  reg hq_r, hq_w;
  // The cache's hits for `heap_ra` and `hq_wa`, registered beside each address as it is set (codegen_sva::psram).
  reg hq_rhit, hq_whit;
  reg [31:0] hq_wa;
  reg signed [63:0] hq_wd;
  wire signed [63:0] heap_rd;
//__OFFCHIP_HEAP_END__
  reg signed [63:0] hp;
//__ONCHIP_FRAMES_BEGIN__
  reg [31:0] sfile_lo [0:DEPTH*NREG-1];
  reg [31:0] sfile_hi [0:DEPTH*NREG-1];
//__ONCHIP_FRAMES_END__
//__OFFCHIP_FRAMES_BEGIN__
  // The frame stack lives off-chip behind its cache, with the on-chip stack's port: `sf_rd` is
  // sfile[sf_ra] one cycle after `sfread`. Requests pulse (`sq_r`/`sq_w`) like the heap's.
  reg sq_r, sq_w;
  // The cache's hits for `sf_ra` and `sq_wa`, registered beside each address as it is set.
  reg sq_rhit, sq_whit;
  reg [31:0] sq_wa;
  reg signed [63:0] sq_wd;
//__OFFCHIP_FRAMES_END__
  reg [15:0] sret [0:DEPTH-1];
  reg [15:0] sdst [0:DEPTH-1];
  reg [15:0] sp, pc, ci, wi, gi, ai;
  // Every move of the cell index `ci` goes through `ci_set`, so an off-chip config image's lanes see the hit of the
  // cell it moves to registered beside it: the cell `c_cellptr + ci` will be at `blk_cell_ptr[pc] + x`, since
  // `blk_cell_ptr_r` reloads from `blk_cell_ptr[pc]` every cycle.
  task ci_set(input [15:0] x);
    begin
      ci <= x;
//__OFFCHIP_CELLS_BEGIN__
      cq_rhit <= cq_hit_at(blk_cell_ptr[pc] + x);
//__OFFCHIP_CELLS_END__
    end
  endtask
  // Block-RAM read ports for the state plane: `heap` (and the recursion frame stack `sfile`) are read via a
  // REGISTERED read (`*_rd <= mem[*_ra]`) so yosys maps them to real RAMB (not flip-flops), slashing the FF
  // count that otherwise pushes the big engine past the board's hold-safe threshold. The 1-cycle read latency
  // is absorbed by dedicated wait-states (st 8/9 for a HeapRead; the frame save/restore loops pipeline it).
  reg [31:0] heap_ra;
  // Heap overflow. Heap addresses are data — pointers, indices, a preload's length — so no static fit-check
  // bounds them, and an access at or past HEAP would alias another word (a truncated bank index on die, the
  // region's index bits off it). `hwrite`/`hread` drop such an access and stop the run; the flag survives the
  // run's start so an over-long preload is refused too, and the result frame's terminator becomes __X_FRAME_END_HEAP__.
  reg heap_ovf;
  reg done_r;
//__ONCHIP_HEAP_BEGIN__
  // Depth-banked heap registered-read ports (one per bank) + the registered bank-select bit. `heap_rd` is the
  // combinational recombination the FSM consumes — see the read site in the always block for why per-bank ports
  // are required for a clean RAMB map. `heap_rd` is signed 64-bit exactly as the un-banked port was (≡VM).
  reg signed [63:0] heap_rd_b0, heap_rd_b1; reg heap_ra14_q;
  wire signed [63:0] heap_rd = heap_ra14_q ? heap_rd_b1 : heap_rd_b0;
  // Every heap write and every heap read issue goes through these two tasks, so the heap's backing store
  // is one place in the engine: the two banks above, read through `heap_rd` one cycle after `hread`.
  task hwrite(input [31:0] a, input [63:0] d);
    begin
      if (a >= HEAP) begin heap_ovf <= 1'b1; done_r <= 1'b1; end
      else if (hsel(a)) begin heap_b1_lo[hb1_idx(a)] <= d[31:0]; heap_b1_hi[hb1_idx(a)] <= d[63:32]; end
      else              begin heap_b0_lo[a[13:0]] <= d[31:0]; heap_b0_hi[a[13:0]] <= d[63:32]; end
    end
  endtask
  task hread(input [31:0] a);
    begin if (a >= HEAP) begin heap_ovf <= 1'b1; done_r <= 1'b1; end else heap_ra <= a; end
  endtask
//__ONCHIP_HEAP_END__
//__OFFCHIP_HEAP_BEGIN__
  // Every heap write and every heap read issue goes through these two tasks: each posts a request to the
  // heap cache, whose `heap_rd` answers one cycle after `hread` (after the stall, on a miss).
  task hwrite(input [31:0] a, input [63:0] d);
    begin if (a >= HEAP) begin heap_ovf <= 1'b1; done_r <= 1'b1; end else begin hq_wa <= a; hq_whit <= hq_hit_at(a); hq_wd <= d; hq_w <= 1'b1; end end
  endtask
  task hread(input [31:0] a);
    begin if (a >= HEAP) begin heap_ovf <= 1'b1; done_r <= 1'b1; end else begin heap_ra <= a; hq_rhit <= hq_hit_at(a); hq_r <= 1'b1; end end
  endtask
//__OFFCHIP_HEAP_END__
  reg [31:0] hclr;   // sequential heap-clear cursor (BRAM cannot be bulk-reset; zero it per program) — 32-bit so a
                     // HEAP larger than 65536 words still terminates P_CLR (a 16-bit cursor wrapped → infinite loop)
//__ONCHIP_FRAMES_BEGIN__
  reg [31:0] sf_ra; reg signed [63:0] sf_rd; reg [31:0] op4;   // frame-stack (sfile) block-RAM read port + arg temp
  // Every frame-stack write and read issue goes through these two tasks, so its backing store is one place.
  task sfwrite(input [31:0] a, input [63:0] d);
    begin sfile_lo[a] <= d[31:0]; sfile_hi[a] <= d[63:32]; end
  endtask
  task sfread(input [31:0] a);
    begin sf_ra <= a; end
  endtask
//__ONCHIP_FRAMES_END__
//__OFFCHIP_FRAMES_BEGIN__
  reg [31:0] sf_ra; wire signed [63:0] sf_rd; reg [31:0] op4;   // frame-stack port + arg temp
  task sfwrite(input [31:0] a, input [63:0] d);
    begin sq_wa <= a; sq_whit <= sq_hit_at(a); sq_wd <= d; sq_w <= 1'b1; end
  endtask
  task sfread(input [31:0] a);
    begin sf_ra <= a; sq_rhit <= sq_hit_at(a); sq_r <= 1'b1; end
  endtask
//__OFFCHIP_FRAMES_END__
  // CFG_BRAM=1 ONLY: the register file `file` and the per-block cell-value array `v` are BLOCK RAM with a
  // REGISTERED read (mirroring heap_rd/sf_rd). Every operand/write/terminator read that touched `file`/`v`
  // combinationally now ISSUES an address (file_ra / v_ra), waits one cycle for the registered read, then latches
  // file_rd / v_rd — dissolving the 128:1×64 operand mux star that the open router (nextpnr) could not legalize.
  // `file`/`v` are read-BEFORE-write within a block (cells never write `file`; each cell writes v[ci] only after
  // all earlier cells settled), so registered reads return the SAME values eval_wprog_config sees ⇒ ≡VM preserved.
  // These SCALAR ports stay declared under every backend (they're tiny, prune trivially when dead, and the shared
  // st3/st4 `if (CFG_BRAM) file_ra<=…` branches reference them). The `wbuf` MEMORY below — the array that the open
  // flow's ABC pass chews on for minutes as a dead cone — is what the emitter EXCISES for the flip-flop backends.
  reg [15:0] file_ra; reg signed [63:0] file_rd;   // register-file BRAM read port (CFG_BRAM=1)
  reg [15:0] v_ra;    reg signed [63:0] v_rd;       // cell-value BRAM read port (CFG_BRAM=1)
  reg [1:0]  rmode;   // the resolve mode of the operand currently in flight (0 file, 1 konst, 2 v) — selects the
                      // latch source after the 1-cycle BRAM read (konst resolves combinationally, no wait)
  reg signed [63:0] rk;   // the konst value for a mode-1 operand (latched at issue so the wait cycle is uniform)
//__CFGBRAM_ONLY_BEGIN__
  // Read-before-write buffer that REPLACES `file0` under CFG_BRAM=1 (EXCISED from the CFG_BRAM=0 netlist — a dead
  // NREG-deep memory otherwise wedges the open-flow ABC pass): the write phase FIRST reads every write's source
  // value out of the block-entry `file` (BRAM, no writes applied yet) into this FF buffer, THEN applies them all
  // as pure BRAM writes. This preserves the ATOMIC within-block write semantics (a swap `Set b..; Set a to old-b`
  // reads block-entry b, not the just-written b) WITHOUT a full-file snapshot copy. Sized to NREG: a block writes
  // each register at most once (fabric `write_order` dedupes), so per-block writes ≤ NREG.
  reg [15:0] wbuf_tgt [0:NREG-1];
  reg signed [63:0] wbuf_val [0:NREG-1];
//__CFGBRAM_ONLY_END__
  reg signed [63:0] dc_src, dc_new, dc_len, dc_j; reg [15:0] dc_ci;   // deep-copy (cell kind 6) multi-cycle state
  reg [6:0]  st;   // interpret sub-state (0..7 core; 8/9 HeapRead wait; 10-13 frame; 14-18 deep-copy; 19 ST_WF; 20 ST_BF; 21 ST_CF; 22 ST_OP; 23 ST_CMP; 24-31 = the CFG_BRAM=1 file/v BRAM read waits; 37-46 SHOW; 47-73 the TEXT cells — see the localparams below)
  // Config-in-BRAM cell fetch (CFG_BRAM=1): `cell_*` is BLOCK RAM with a REGISTERED read (mirroring heap_rd/sf_rd).
  // `cc_*_r` latches the CURRENT cell (address `c_cellptr + ci`, combinational off pc/ci) one cycle after ci/pc
  // last changed; the cell walk (st==0) reads `cc_*` which selects `cc_*_r` under CFG_BRAM, else the direct
  // combinational read (CFG_BRAM=0 stays behaviorally identical to today). ST_CF burns one cycle so `cc_*_r`
  // catches up whenever ci/pc changed while resuming the walk (see the `st <= CFG_BRAM ? ST_CF : 5'd0` sites).
  localparam ST_CF = 5'd21;
//__ONCHIP_CELLS_BEGIN__
  reg [31:0] cc_kind_r, cc_code_r, cc_op0_r, cc_op1_r, cc_op2_r, cc_op3_r;
//__ONCHIP_CELLS_END__
//__OFFCHIP_CELLS_BEGIN__
  wire [31:0] cc_kind_r, cc_code_r, cc_op0_r, cc_op1_r, cc_op2_r, cc_op3_r;
//__OFFCHIP_CELLS_END__
  // Config-in-BRAM WRITE fetch (CFG_BRAM=1): `wr_reg`/`wr_op` are BLOCK RAM with a REGISTERED read. `wr_*_r`
  // latch the CURRENT write record (address `c_wrptr + wi`, combinational off pc/wi) one cycle after wi/pc
  // last changed; st==1 reads `w_reg`/`w_op` which select `wr_*_r` under CFG_BRAM, else the direct combinational
  // read. ST_WF (st=19) burns one cycle so `wr_*_r` catches up whenever wi/pc changed while walking the writes.
  localparam ST_WF = 5'd19;
  reg [31:0] wr_reg_r, wr_op_r;
  // Config-in-BRAM BLOCK fetch (CFG_BRAM=1): the 13 `blk_*` arrays are BLOCK RAM with a REGISTERED read. The
  // `blk_*_r` regs latch the CURRENT block record (address `pc`, combinational) one cycle after pc last changed;
  // the `c_*` block wires select `blk_*_r` under CFG_BRAM, else the direct combinational read. Because the cell
  // fetch `cc_*_r` reads `cell_[c_cellptr + ci]` off the (now registered) `c_cellptr`, a pc change needs TWO
  // settle cycles: ST_BF (blk_*_r catches the new pc) → ST_CF (cc_*_r catches the new c_cellptr) → st0. Only the
  // pc-CHANGE sites (jump/branch/call/return + the P_CLR→P_RUN entry) route through ST_BF; a within-block ci
  // advance still routes through ST_CF alone (pc, hence c_*, is stable across a block's cell/write walk).
  localparam ST_BF = 5'd20;
  reg [31:0] blk_livein_ptr_r, blk_n_livein_r, blk_cell_ptr_r, blk_n_cells_r, blk_write_ptr_r,
             blk_n_writes_r, blk_term_kind_r, blk_t0_r, blk_t1_r, blk_top_r, blk_cdst_r, blk_cargc_r, blk_cargp_r;
  // SERIALIZED operand fetch (CFG_BRAM=1 only): the four cell operands are resolved ONE PER CYCLE through a
  // single shared `resolve` instance instead of four PARALLEL wide muxes in st==0. Four parallel 128:1×64 muxes
  // per cell were a net-dense hotspot the open router (nextpnr) could not legalize; folding them onto one mux
  // (indexed by `opi`) cuts the operand-mux nets ~4× so the big 200T engine routes. ST_OP fetches r0..r3 over
  // four cycles (nonblocking `<=`), then ST_CMP runs the SAME compute block st==0 ran, reading r0..r3 as the
  // now-registered pre-fetched values. All operands reference EARLIER cells in the SAME block (already written),
  // so serial fetch yields IDENTICAL values ⇒ ≡VM preserved. CFG_BRAM=0 keeps the original single-cycle path.
  localparam ST_OP = 5'd22;   // serial operand-fetch ISSUE (one operand per cycle, opi = 0..3): decode the mode,
                              // issue the file_ra/v_ra BRAM address (or latch the konst), → ST_OPD
  localparam ST_CMP = 5'd23;  // cell compute (r0..r3 pre-fetched/registered) — CFG_BRAM=1 only
  // ── CFG_BRAM=1 file/v BRAM-read states (24..36). Each BRAM read is a 3-phase ISSUE→WAIT→LATCH, mirroring the
  //    proven heap read (st0 issue heap_ra → st8 wait → st9 latch heap_rd): the registered `*_rd <= mem[*_ra]`
  //    at the top of the always block makes `file_rd`/`v_rd` valid the cycle AFTER `*_ra` is set, so the WAIT
  //    phase lets the address propagate before the LATCH phase consumes the data. ──
  localparam ST_OPD  = 6'd24;  // operand-fetch WAIT  (address propagating)
  localparam ST_OPW  = 6'd25;  // operand-fetch LATCH: latch r[opi] from file_rd/rk/v_rd; advance opi or → ST_CMP
  localparam ST_WR   = 6'd26;  // write READ pass ISSUE: read write[wi]'s source from block-entry file/v → ST_WRD
  localparam ST_WRD  = 6'd27;  // write READ pass WAIT
  localparam ST_WRW  = 6'd28;  // write READ pass LATCH: buffer (w_reg, value) into wbuf[wi]; advance wi → ST_WF
  localparam ST_TR   = 6'd29;  // terminator READ ISSUE: read branch-cond/return-value from block-entry file/v → ST_TRD
  localparam ST_TRD  = 6'd30;  // terminator READ WAIT
  localparam ST_TRW  = 6'd31;  // terminator READ LATCH: buffer into `retval` → ST_WA
  localparam ST_WA   = 6'd32;  // write APPLY pass: file[wbuf_tgt[k]] <= wbuf_val[k] (pure BRAM writes) → st2
  localparam ST_FSD  = 6'd33;  // frame-SAVE (st3) WAIT
  localparam ST_FSW  = 6'd34;  // frame-SAVE (st3) LATCH: sfile[..] <= file_rd; advance gi → st3
  localparam ST_AGD  = 6'd35;  // call-arg gather (st4) mode-2 WAIT
  localparam ST_AGW  = 6'd36;  // call-arg gather (st4) mode-2 LATCH: file[ai] <= v_rd; advance ai → st4
  // ── SHOW record streaming (cell kind 10): the engine's OUTPUT TAPE, sent over the byte channel the moment the
