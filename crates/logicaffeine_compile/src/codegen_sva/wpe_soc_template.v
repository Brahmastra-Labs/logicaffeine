__INTEGER_FUNC_F__  function signed [63:0] resolve(input [31:0] op, input [31:0] lptr);
    reg [31:0] ridx;
    begin
      // Split the chained memory read file[liv_reg[..]] via a local index: yosys's synth_xilinx
      // mis-synthesizes the nested array-indexed-by-array-element read at small cap sizes (verified in
      // gate-level sim), silently corrupting register-operand reads on silicon. The temp is semantically
      // identical (RTL ≡VM unchanged) but synthesizes correctly at every cap size.
      // The `file`/`v` reads are GATED behind `!CFG_BRAM`: under CFG_BRAM=1 `resolve` is called ONLY from the
      // dead (`else`) CFG_BRAM=0 branch of st==0, so its result is never used — but its combinational `file[]`/`v[]`
      // reads would add EXTRA read ports to those memories, and a memory with a registered read port (file_rd/v_rd)
      // PLUS a stray combinational read has no clean single-BRAM mapping (yosys: "no valid mapping found for memory
      // v"), forcing it to split `v`/`file` across a BRAM and a LUTRAM copy that fall out of sync → stale operand
      // reads on silicon. Constant-folding `!CFG_BRAM` to 0 removes those dead ports so `v`/`file` map to ONE BRAM.
      case (op[31:30])
        2'd0: begin ridx = liv_reg[lptr + op[15:0]]; resolve = CFG_BRAM ? 64'sd0 : {file_hi[ridx[15:0]], file_lo[ridx[15:0]]}; end
        2'd1: resolve = konst[op[15:0]];
        default: resolve = CFG_BRAM ? 64'sd0 : {v_hi[op[15:0]], v_lo[op[15:0]]};
      endcase
    end
  endfunction
