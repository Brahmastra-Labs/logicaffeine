//! The self-interpreter's operator dispatch, generated from the language's table of how each binary operator is
//! self-applied (`semantics::operator_overloads`).
//!
//! `core_interp.logos` holds the generated text between [`BEGIN`] and [`END`], and a lock holds it equal to
//! [`dispatch_source`], so the self-interpreter applies exactly the operators the table says it does, each the
//! language's own operator written on the values its operands carry. What comes out:
//! - `applyBinOp (op, lv, rv)`: a failing operand's failure, else the operator's own function, by its Core IR text;
//! - one function per operator the table types, `coreOp…`: a decision on the operands' `CVal` variants, overload by
//!   overload in the table's order, that stops at a guard that holds (`Fail with` its report, ahead of the operator, so
//!   a specializer that knows the guard holds emits the failure and never computes the operation) and applies the
//!   operator to the unwrapped values;
//!   an application no overload takes goes to `coreOpFamily`, the self-interpreter's own value families (sets,
//!   counters), which stops one no family takes with `coreOpRefusal`;
//! - `coreOpRefusal (op, lv, rv)`: the operator's refusal, in the tree-walker's words.
//!
//! A [`SelfApplied::Defined`] operator calls `core_interp`'s own `coreOp…`. Operator texts are told apart by their
//! length first and then by equality, as `optimize::core_builtins` tells builtins apart.
//!
//! The decompiler prints an operator by the same table: `decompile_source.logos` holds [`spelling_source`] between
//! [`SPELLING_BEGIN`] and [`SPELLING_END`], `opToStr`, each Core IR text as the program spells it. And each specializer
//! folds two values it knows by the same table: [`specializer_source`], `peFoldOperator`, between [`SPECIALIZER_BEGIN`]
//! and [`SPECIALIZER_END`] in each of the three dialects, so a specializer folds exactly what the language computes.
//! The online specializer's finishing pass reads the table's guards: [`guards_source`], `peGuardCondition`, between
//! [`GUARDS_BEGIN`] and [`GUARDS_END`] in `pe_source.logos`, so it drops a residual guard only where the operation after
//! it stops with that guard's report under that guard's condition.

use std::collections::BTreeMap;

use crate::ast::stmt::BinaryOpKind;
use crate::semantics::operator_overloads::{core_op_text, self_applied, surface_text, OpOverload, SelfApplied, ALL_OPERATORS};

/// The line that opens the generated text in `core_interp.logos`.
pub const BEGIN: &str = "# The operators: generated by optimize::core_operators from semantics::operator_overloads.";

/// The line that closes it.
pub const END: &str = "# The operators end.";

/// The line that opens the generated spellings in `decompile_source.logos`.
pub const SPELLING_BEGIN: &str = "# The operator spellings: generated by optimize::core_operators from semantics::operator_overloads.";

/// The line that closes them.
pub const SPELLING_END: &str = "# The operator spellings end.";

/// The `CVal` variants an operand is told apart by, with the binder name of the value each holds.
const VARIANTS: [(&str, &str); 11] = [
    ("VInt", "Int"),
    ("VFloat", "Real"),
    ("VText", "Text"),
    ("VBool", "Bool"),
    ("VSeq", "Seq"),
    ("VDuration", "Duration"),
    ("VDate", "Date"),
    ("VMoment", "Moment"),
    ("VSpan", "Span"),
    ("VTime", "Time"),
    ("VChar", "Char"),
];

/// The variant holding a value of type `ty`, `None` for `Any`.
fn variant_of(ty: &str) -> Option<&'static str> {
    match ty {
        "Int" => Some("VInt"),
        "Real" => Some("VFloat"),
        "Text" => Some("VText"),
        "Bool" => Some("VBool"),
        "Seq" => Some("VSeq"),
        "Duration" => Some("VDuration"),
        "Date" => Some("VDate"),
        "Moment" => Some("VMoment"),
        "Span" => Some("VSpan"),
        "Time" => Some("VTime"),
        "Char" => Some("VChar"),
        "Any" => None,
        other => panic!("the self-interpreter carries no `{other}` operand"),
    }
}

/// The construction of a `CVal` of type `answer` holding `value`.
fn built(answer: &str, value: &str) -> String {
    match answer {
        "Seq" => format!("a new VSeq with items {value}"),
        other => format!(
            "a new {} with value {value}",
            variant_of(other).unwrap_or_else(|| panic!("the self-interpreter builds no `{other}` answer"))
        ),
    }
}

/// Whether an operand of type `ty` takes an operand known to be in `variant` (`None`: in none the decision named).
fn takes(ty: &str, variant: Option<&str>) -> bool {
    match variant_of(ty) {
        None => true,
        Some(v) => variant == Some(v),
    }
}

/// The function an operator's applications go to.
fn function_of(op: BinaryOpKind) -> String {
    format!("coreOp{op:?}")
}

/// The operand at `side` (`left`/`right`), known to be in `variant`, as a value of type `ty`: its own value, or, for
/// `Any`, the text `Show` prints for it.
fn unwrapped(ty: &str, side: &str, variant: Option<&str>) -> String {
    match variant_of(ty) {
        None => format!("{side}Shown"),
        Some(_) => format!("{side}{}", binder(variant.expect("a typed operand is in a known variant"))),
    }
}

fn binder(variant: &str) -> &'static str {
    VARIANTS.iter().find(|(v, _)| *v == variant).map(|(_, b)| *b).expect("a known variant")
}

/// The operators the dispatch answers, by Core IR text: each text's operator (the first of [`ALL_OPERATORS`] that
/// the self-interpreter applies) and the function its applications go to.
fn answered() -> BTreeMap<&'static str, BinaryOpKind> {
    let mut texts = BTreeMap::new();
    for op in ALL_OPERATORS {
        if !matches!(self_applied(*op), SelfApplied::Awaits(_)) {
            texts.entry(core_op_text(*op)).or_insert(*op);
        }
    }
    texts
}

/// The generated text: `applyBinOp`, one function per operator the table types, and `coreOpRefusal`, between [`BEGIN`]
/// and [`END`].
pub fn dispatch_source() -> String {
    let texts = answered();
    let mut by_length: BTreeMap<usize, Vec<(&str, BinaryOpKind)>> = BTreeMap::new();
    for (text, op) in &texts {
        assert!(text.is_ascii() && !text.contains(['"', '{', '}']), "`{text}` is no operator text the dispatch can hold");
        by_length.entry(text.len()).or_default().push((text, *op));
    }
    let mut out = String::new();
    out.push_str(BEGIN);
    out.push('\n');
    out.push_str("## To applyBinOp (op: Text) and (lv: CVal) and (rv: CVal) -> CVal:\n");
    out.push_str("    If coreFails(lv):\n        Return lv.\n");
    out.push_str("    If coreFails(rv):\n        Return rv.\n");
    out.push_str("    Let opLength be length of op.\n");
    for (len, group) in &by_length {
        out.push_str(&format!("    If opLength equals {len}:\n"));
        for (text, op) in group {
            out.push_str(&format!("        If op equals \"{text}\":\n"));
            out.push_str(&format!("            Return {}(lv, rv).\n", function_of(*op)));
        }
    }
    out.push_str("    Return coreOpRefusal(op, lv, rv).\n");

    for (text, op) in &texts {
        if let SelfApplied::Overloads { overloads, .. } = self_applied(*op) {
            out.push('\n');
            out.push_str(&typed_function(*op, text, surface_text(*op), overloads));
        }
    }

    out.push_str("\n## To coreOpRefusal (op: Text) and (lv: CVal) and (rv: CVal) -> CVal:\n");
    out.push_str("    Let refusedLeft be coreTypeName(lv).\n");
    out.push_str("    Let refusedRight be coreTypeName(rv).\n");
    for (text, op) in &texts {
        if let SelfApplied::Overloads { refusal, .. } = self_applied(*op) {
            if refusal.is_empty() {
                continue;
            }
            out.push_str(&format!("    If op equals \"{text}\":\n"));
            for case in refusal {
                let message = case.report.replace("{1}", "{refusedLeft}").replace("{2}", "{refusedRight}");
                let mut pad = "        ".to_string();
                for (name, held) in [("refusedLeft", case.left), ("refusedRight", case.right)] {
                    if held != "*" {
                        out.push_str(&format!("{pad}If {name} equals \"{held}\":\n"));
                        pad.push_str("    ");
                    }
                }
                out.push_str(&format!("{pad}Return a new VError with msg \"{message}\".\n"));
            }
        }
    }
    for op in ALL_OPERATORS {
        if let SelfApplied::Awaits(why) = self_applied(*op) {
            assert!(!why.contains(['"', '{', '}']), "`{why}` is no reason a LOGOS text can hold");
            out.push_str(&format!("    If op equals \"{}\":\n", core_op_text(*op)));
            out.push_str(&format!(
                "        Return a new VError with msg \"the self-interpreter applies no `{}`: it awaits {why}\".\n",
                surface_text(*op)
            ));
        }
    }
    out.push_str("    Return a new VError with msg \"the self-interpreter applies no `{op}`\".\n");
    out.push_str(END);
    out.push('\n');
    out
}

/// The decompiler's `opToStr`: each operator's Core IR text as the program spells it, between [`SPELLING_BEGIN`] and
/// [`SPELLING_END`].
pub fn spelling_source() -> String {
    let mut by_length: BTreeMap<usize, BTreeMap<&'static str, &'static str>> = BTreeMap::new();
    for op in ALL_OPERATORS {
        let text = core_op_text(*op);
        by_length.entry(text.len()).or_default().entry(text).or_insert(surface_text(*op));
    }
    let mut out = String::new();
    out.push_str(SPELLING_BEGIN);
    out.push('\n');
    out.push_str("## To opToStr (op: Text) -> Text:\n");
    out.push_str("    Let opLength be length of op.\n");
    for (len, texts) in &by_length {
        out.push_str(&format!("    If opLength equals {len}:\n"));
        for (text, spelled) in texts {
            out.push_str(&format!("        If op equals \"{text}\":\n"));
            out.push_str(&format!("            Return \" {spelled} \".\n"));
        }
    }
    out.push_str("    Return \" {op} \".\n");
    out.push_str(SPELLING_END);
    out.push('\n');
    out
}

/// One operator's function: a decision on its operands' variants that applies the first overload taking them.
fn typed_function(op: BinaryOpKind, text: &str, spelling: &str, overloads: &[OpOverload]) -> String {
    let mut out = format!("## To {} (lv: CVal) and (rv: CVal) -> CVal:\n", function_of(op));
    out.push_str(&decide(text, spelling, overloads, &mut Vec::new(), 1));
    out
}

/// The decision at the operand after those `chosen` names (`Some` a variant, `None` one the decision named none of).
fn decide(text: &str, spelling: &str, overloads: &[OpOverload], chosen: &mut Vec<Option<&'static str>>, depth: usize) -> String {
    let pad = "    ".repeat(depth);
    let position = chosen.len();
    let fits = |o: &&OpOverload| o.params.iter().zip(chosen.iter()).all(|(ty, v)| takes(ty, *v));
    if position == 2 {
        return match overloads.iter().find(fits) {
            Some(overload) => leaf(spelling, overload, chosen, &pad),
            None => format!("{pad}Return coreOpFamily(\"{text}\", lv, rv).\n"),
        };
    }
    let mut variants: Vec<&'static str> = Vec::new();
    for o in overloads.iter().filter(fits) {
        if let Some(v) = variant_of(o.params[position]) {
            if !variants.contains(&v) {
                variants.push(v);
            }
        }
    }
    let operand = if position == 0 { "lv" } else { "rv" };
    let side = if position == 0 { "left" } else { "right" };
    if variants.is_empty() {
        chosen.push(None);
        let rest = decide(text, spelling, overloads, chosen, depth);
        chosen.pop();
        return rest;
    }
    let mut out = format!("{pad}Inspect {operand}:\n");
    for v in variants {
        out.push_str(&format!("{pad}    When {v} ({side}{}):\n", binder(v)));
        chosen.push(Some(v));
        out.push_str(&decide(text, spelling, overloads, chosen, depth + 2));
        chosen.pop();
    }
    out.push_str(&format!("{pad}    Otherwise:\n"));
    chosen.push(None);
    out.push_str(&decide(text, spelling, overloads, chosen, depth + 2));
    chosen.pop();
    out
}

/// An overload applied: its `Any` operands shown, each guard that holds stopping the run with its report, then the
/// operator on the unwrapped values.
fn leaf(spelling: &str, overload: &OpOverload, chosen: &[Option<&'static str>], pad: &str) -> String {
    let mut out = String::new();
    for (position, (operand, side)) in [("lv", "left"), ("rv", "right")].into_iter().enumerate() {
        if variant_of(overload.params[position]).is_none() {
            out.push_str(&format!("{pad}Let {side}Shown be valToText({operand}).\n"));
        }
    }
    let left = unwrapped(overload.params[0], "left", chosen[0]);
    let right = unwrapped(overload.params[1], "right", chosen[1]);
    for guard in overload.guards {
        let when = guard.when.replace("{left}", &left).replace("{right}", &right);
        out.push_str(&format!("{pad}If {when}:\n"));
        out.push_str(&format!("{pad}    Fail with \"{}\".\n", guard.report));
    }
    let value = format!("({left} {spelling} {right})");
    out.push_str(&format!("{pad}Return {}.\n", built(overload.answer, &value)));
    out
}

/// The line that opens each specializer's generated folding of operators, in `pe_source.logos`,
/// `pe_mini_source.logos` and `pe_bti_source.logos`.
pub const SPECIALIZER_BEGIN: &str =
    "# The specializer's operators: generated by optimize::core_operators from semantics::operator_overloads.";

/// The line that closes it.
pub const SPECIALIZER_END: &str = "# The specializer's operators end.";

/// The types a specializer holds a known value of as a constant: every type with a variant but a list's.
fn literal_types() -> Vec<&'static str> {
    VARIANTS.iter().map(|(_, ty)| *ty).filter(|ty| *ty != "Seq").collect()
}

/// The folds a specializer makes of an operator on two known values, by the pair of their types: each overload of
/// the table between literal types (an `Any` operand standing for each of them, the first overload taking a pair
/// winning, as the dispatch decides), the language's equality between two values of one type and between two numbers,
/// and the truth words between two truths. Each fold is the operator text, its guards and the answer built.
fn folds() -> BTreeMap<(usize, usize), Vec<(&'static str, Vec<String>, String)>> {
    let types = literal_types();
    let index = |ty: &str| types.iter().position(|t| *t == ty);
    let mut out: BTreeMap<(usize, usize), Vec<(&'static str, Vec<String>, String)>> = BTreeMap::new();
    let mut push = |l: usize, r: usize, text: &'static str, guards: Vec<String>, answer: String| {
        let folds = out.entry((l, r)).or_default();
        if !folds.iter().any(|(t, _, _)| *t == text) {
            folds.push((text, guards, answer));
        }
    };
    for (text, op) in answered() {
        let SelfApplied::Overloads { overloads, .. } = self_applied(op) else { continue };
        for o in overloads.iter() {
            let expand = |ty: &'static str| if ty == "Any" { types.clone() } else { vec![ty] };
            for lt in expand(o.params[0]) {
                for rt in expand(o.params[1]) {
                    let (Some(l), Some(r)) = (index(lt), index(rt)) else { continue };
                    if o.answer != "Any" && !types.contains(&o.answer) {
                        continue;
                    }
                    let (left, right) = (format!("fbLeft{lt}"), format!("fbRight{rt}"));
                    let guards = o.guards.iter().map(|g| g.when.replace("{left}", &left).replace("{right}", &right)).collect();
                    push(l, r, text, guards, built(o.answer, &format!("({left} {} {right})", surface_text(op))));
                }
            }
        }
    }
    for (i, lt) in types.iter().enumerate() {
        for (j, rt) in types.iter().enumerate() {
            let numbers = ["Int", "Real"].contains(lt) && ["Int", "Real"].contains(rt);
            if i == j || numbers {
                let (left, right) = (format!("fbLeft{lt}"), format!("fbRight{rt}"));
                push(i, j, "==", Vec::new(), format!("a new VBool with value ({left} equals {right})"));
                push(i, j, "!=", Vec::new(), format!("a new VBool with value ({left} is not {right})"));
            }
        }
    }
    if let Some(b) = index("Bool") {
        push(b, b, "&&", Vec::new(), "a new VBool with value (fbLeftBool and fbRightBool)".to_string());
        push(b, b, "||", Vec::new(), "a new VBool with value (fbLeftBool or fbRightBool)".to_string());
    }
    out
}

/// A specializer's folding of an operator on two known values: `peFoldOperator` with the dialect's `suffix` (`""`,
/// `"M"`, `"B"`), between [`SPECIALIZER_BEGIN`] and [`SPECIALIZER_END`]. Each fold applies the language's own operator
/// to the values, so a specializer folds exactly what the language computes; a tripped guard, and any application the
/// table types no fold of, answers `VNothing`, which the specializer leaves residual.
pub fn specializer_source(suffix: &str) -> String {
    let types = literal_types();
    let by_pair = folds();
    let mut out = String::new();
    out.push_str(SPECIALIZER_BEGIN);
    out.push('\n');
    out.push_str(&format!("## To peFoldOperator{suffix} (fbOp: Text) and (fbLeft: CVal) and (fbRight: CVal) -> CVal:\n"));
    out.push_str("    Inspect fbLeft:\n");
    for (l, left) in types.iter().enumerate() {
        let rights: Vec<(usize, &Vec<(&str, Vec<String>, String)>)> =
            by_pair.iter().filter(|((pl, _), _)| *pl == l).map(|((_, r), f)| (*r, f)).collect();
        if rights.is_empty() {
            continue;
        }
        out.push_str(&format!("        When {} (fbLeft{left}):\n", variant_of(left).expect("a literal type has a variant")));
        out.push_str("            Inspect fbRight:\n");
        for (r, folds) in rights {
            let right = types[r];
            out.push_str(&format!("                When {} (fbRight{right}):\n", variant_of(right).expect("a literal type has a variant")));
            for (text, guards, answer) in folds {
                out.push_str(&format!("                    If fbOp equals \"{text}\":\n"));
                for g in guards {
                    out.push_str(&format!("                        If {g}:\n                            Return a new VNothing.\n"));
                }
                out.push_str(&format!("                        Return {answer}.\n"));
            }
            out.push_str("                    Return a new VNothing.\n");
        }
        out.push_str("                Otherwise:\n                    Return a new VNothing.\n");
    }
    out.push_str("        Otherwise:\n            Return a new VNothing.\n");
    out.push_str("    Return a new VNothing.\n");
    out.push_str(SPECIALIZER_END);
    out.push('\n');
    out
}

/// The line that opens the finishing pass's generated reading of the guards, in `pe_source.logos`.
pub const GUARDS_BEGIN: &str = "# The specializer's guards: generated by optimize::core_operators from semantics::operator_overloads.";

/// The line that closes it.
pub const GUARDS_END: &str = "# The specializer's guards end.";

/// A guard's condition as the Core IR expression the finishing pass compares a residual guard with, over the operands
/// `gcLeftOperand` and `gcRightOperand`: `when` is an operand or a number, a comparison as the language spells it, and
/// an operand or a number.
fn guard_condition(when: &str) -> String {
    let side = |word: &str| match word {
        "{left}" => Some("gcLeftOperand".to_string()),
        "{right}" => Some("gcRightOperand".to_string()),
        _ if word.parse::<i64>().is_ok() => Some(format!("(a new CInt with value {word})")),
        _ if word.contains('.') && word.parse::<f64>().is_ok() => Some(format!("(a new CFloat with value {word})")),
        _ => None,
    };
    let comparisons = [BinaryOpKind::Eq, BinaryOpKind::NotEq, BinaryOpKind::Lt, BinaryOpKind::Gt, BinaryOpKind::LtEq, BinaryOpKind::GtEq];
    for op in comparisons {
        if let Some((left, right)) = when.split_once(&format!(" {} ", surface_text(op))) {
            if let (Some(left), Some(right)) = (side(left), side(right)) {
                return format!("a new CBinOp with op \"{}\" and left {left} and right {right}", core_op_text(op));
            }
        }
    }
    panic!("`{when}` is no guard the finishing pass reads: an operand or a number, a comparison, an operand or a number")
}

/// The finishing pass's reading of the table's guards: `peGuardCondition`, between [`GUARDS_BEGIN`] and
/// [`GUARDS_END`]. Given an operator's Core IR text, the types of its two operands and a failure's report, it answers
/// the condition, over the two operands, under which the overload the dispatch applies to operands of those types
/// stops with that report, and `__pe_no_unfold` when that overload holds no such guard.
pub fn guards_source() -> String {
    let types = literal_types();
    let mut out = String::new();
    out.push_str(GUARDS_BEGIN);
    out.push('\n');
    out.push_str("## To peGuardCondition (gcOp: Text) and (gcLeft: Text) and (gcRight: Text) and (gcReport: Text) and (gcLeftOperand: CExpr) and (gcRightOperand: CExpr) -> CExpr:\n");
    for (text, op) in answered() {
        let SelfApplied::Overloads { overloads, .. } = self_applied(op) else { continue };
        let mut cases = String::new();
        for left in &types {
            for right in &types {
                let chosen = [variant_of(left), variant_of(right)];
                let applied = overloads.iter().find(|o| o.params.iter().zip(chosen.iter()).all(|(ty, v)| takes(ty, *v)));
                let Some(overload) = applied.filter(|o| !o.guards.is_empty()) else { continue };
                cases.push_str(&format!("        If gcLeft equals \"{left}\" and gcRight equals \"{right}\":\n"));
                for guard in overload.guards {
                    assert!(!guard.report.contains(['"', '{', '}']), "`{}` is no report a LOGOS text can hold", guard.report);
                    cases.push_str(&format!("            If gcReport equals \"{}\":\n", guard.report));
                    cases.push_str(&format!("                Return {}.\n", guard_condition(guard.when)));
                }
            }
        }
        if !cases.is_empty() {
            out.push_str(&format!("    If gcOp equals \"{text}\":\n"));
            out.push_str(&cases);
        }
    }
    out.push_str("    Return a new CVar with name \"__pe_no_unfold\".\n");
    out.push_str(GUARDS_END);
    out.push('\n');
    out
}

