//! The self-interpreter's declared-type defaults, generated from the language's one table of them
//! (`interpreter::DECLARED_DEFAULTS`, the CRDT kinds' `CrdtKind::TYPE_NAMES`).
//!
//! A construction that leaves a struct's field out starts it at its declared type's default. `core_ir_scope` writes
//! each default an expression spells (a number, a text, an empty collection) into the construction; the Core IR
//! carries every other slot (a CRDT replica, nothing) as `CDeclaredDefault with typeName`, which a specializer keeps
//! residual and the decompiler leaves out, as the program did. `core_interp.logos` holds `coreDeclaredDefault (typeName)`
//! between [`BEGIN`] and [`END`], which a lock holds equal to [`defaults_source`]: each name the table gives a
//! value of its own answers that value, a name the self-interpreter carries no value of stops with what it awaits,
//! and every other name answers nothing, as `interpreter::declared_default` does.
//!
//! Names are told apart by their length first and then by equality: the language orders no `Text`, and a slot
//! decides among the few names of its length.

use std::collections::BTreeMap;

use crate::interpreter::{DeclaredDefault, DECLARED_DEFAULTS};
use crate::semantics::crdt::CrdtKind;

/// Whether the self-interpreter holds a replica of `kind`: the counters and the sequence, so far.
pub fn holds_replicas_of(kind: CrdtKind) -> bool {
    matches!(kind, CrdtKind::Counter | CrdtKind::PnCounter | CrdtKind::Seq)
}

/// The line that opens the generated text in `core_interp.logos`.
pub const BEGIN: &str = "# The declared defaults: generated by optimize::core_defaults from interpreter::DECLARED_DEFAULTS.";

/// The line that closes it.
pub const END: &str = "# The declared defaults end.";

/// What the self-interpreter awaits to hold a CRDT replica.
pub const CRDT_AWAITS: &str = "the CRDT family";

/// The `CVal` a slot of `default` starts at, as the self-interpreter builds it, `typeName` naming the slot's type. A
/// CRDT kind the self-interpreter holds starts at a template replica — its type name and an empty state — which the
/// evaluation of the slot stamps with a fresh replica id.
pub fn starting_value(default: DeclaredDefault) -> String {
    let awaits = |what: &str| format!("a new VError with msg \"the self-interpreter holds no `{{typeName}}`: it awaits {what}\"");
    match default {
        DeclaredDefault::Int => "a new VInt with value 0".to_string(),
        DeclaredDefault::Float => "a new VFloat with value 0.0".to_string(),
        DeclaredDefault::Bool => "a new VBool with value false".to_string(),
        DeclaredDefault::Text => "a new VText with value \"\"".to_string(),
        DeclaredDefault::Char => format!("a new VChar with value {}", logicaffeine_language::lexer::char_literal('\0')),
        DeclaredDefault::List => "a new VSeq with items a new Seq of CVal".to_string(),
        DeclaredDefault::Set => "a new VSet with items a new Seq of CVal".to_string(),
        DeclaredDefault::Map => "a new VMap with entries a new Map of Text to CVal".to_string(),
        DeclaredDefault::Crdt(kind) if holds_replicas_of(kind) => {
            format!("a new VCrdt with kind \"{}\" and state a new Map of Text to CVal", kind.value_type_name())
        }
        DeclaredDefault::Crdt(_) => awaits(CRDT_AWAITS),
        DeclaredDefault::Nothing => "a new VNothing".to_string(),
    }
}

/// Every declared type name with a default of its own, in the table's order: the scalar and collection types, then
/// the CRDT kinds.
pub fn named_defaults() -> impl Iterator<Item = (&'static str, DeclaredDefault)> {
    DECLARED_DEFAULTS
        .iter()
        .copied()
        .chain(CrdtKind::TYPE_NAMES.iter().map(|&(name, kind)| (name, DeclaredDefault::Crdt(kind))))
}

/// The generated text: `coreDeclaredDefault`, between [`BEGIN`] and [`END`].
pub fn defaults_source() -> String {
    let mut by_length: BTreeMap<usize, BTreeMap<String, Vec<&str>>> = BTreeMap::new();
    for (name, default) in named_defaults() {
        assert!(!name.contains(['"', '{', '}']), "`{name}` is no type name a LOGOS text can hold");
        by_length.entry(name.chars().count()).or_default().entry(starting_value(default)).or_default().push(name);
    }
    let mut out = String::new();
    out.push_str(BEGIN);
    out.push('\n');
    out.push_str("## To coreDeclaredDefault (typeName: Text) -> CVal:\n");
    out.push_str("    Let nameLength be length of typeName.\n");
    for (len, values) in &by_length {
        out.push_str(&format!("    If nameLength equals {len}:\n"));
        for (value, names) in values {
            let tests: Vec<String> = names.iter().map(|n| format!("(typeName equals \"{n}\")")).collect();
            out.push_str(&format!("        If {}:\n", tests.join(" or ")));
            out.push_str(&format!("            Return {value}.\n"));
        }
    }
    out.push_str(&format!("    Return {}.\n", starting_value(DeclaredDefault::Nothing)));
    out.push_str(END);
    out.push('\n');
    out
}

