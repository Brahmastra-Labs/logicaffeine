//! The self-interpreter's builtin dispatch, generated from the language's table of how each builtin is
//! self-interpreted (`semantics::builtin_overloads`).
//!
//! `core_interp.logos` holds the generated text between [`BEGIN`] and [`END`], and a lock holds it equal to
//! [`dispatch_source`], so the self-interpreter runs exactly the builtins the table says it does, each the
//! language's own builtin called on the values its arguments carry. What comes out:
//! - `coreBuiltinKnown (name)`: whether a call by `name` is to a builtin the self-interpreter runs;
//! - `coreBuiltin (name, args)`: the call, to a builtin's own function; a call to a builtin the table awaits stops
//!   with what it awaits, and a call to no builtin stops as the tree-walker stops it;
//! - `coreBuiltinAwaited (name)`: what the self-interpreter awaits to run the builtin `name`, empty for any other name;
//! - one function per builtin: a decision on its arguments' `CVal` variants that stops on the argument types the
//!   language refuses in words of its own (`BuiltinId::self_interpreted_stops`), then, overload by overload in the
//!   table's order, calls the builtin on the unwrapped values and wraps its answer, and stops a call no overload takes
//!   with the builtin's refusal. A [`SelfInterpreted::Defined`] builtin calls `core_interp`'s own `coreDefined…`.
//!
//! Names are told apart by their length first and then by equality: the language orders no `Text`, and a call
//! decides among the few names of its length.
//!
//! The online specializer folds a pure builtin on arguments it knows by the same table: `pe_source.logos` holds
//! [`specializer_source`] between [`SPECIALIZER_BEGIN`] and [`SPECIALIZER_END`], `peFoldBuiltin`, which calls the
//! builtin on the constants and holds its answer as a constant (bytes as a known list of `Int`s, both ways).

use std::collections::{BTreeMap, BTreeSet};

use crate::semantics::builtin_overloads::{Overload, SelfInterpreted, Stop, BYTE_ELEMENT_REFUSAL};
use crate::semantics::builtins::{BuiltinId, BUILTIN_NAMES, SYSTEM_NATIVES};

/// The line that opens the generated text in `core_interp.logos`.
pub const BEGIN: &str = "# The builtins: generated by optimize::core_builtins from semantics::builtin_overloads.";

/// The line that closes it.
pub const END: &str = "# The builtins end.";

/// The `CVal` variant a value of a carried type sits in, its one field `value` holding the value.
fn carried(ty: &str) -> &'static str {
    match ty {
        "Int" => "VInt",
        "Real" => "VFloat",
        "Text" => "VText",
        "Bool" => "VBool",
        "Bytes" => "VSeq",
        "Duration" => "VDuration",
        "Date" => "VDate",
        "Moment" => "VMoment",
        "Span" => "VSpan",
        "Time" => "VTime",
        "Char" => "VChar",
        other => panic!("the self-interpreter carries no `{other}` value"),
    }
}

/// The variants an argument is told apart by.
const VARIANTS: [&str; 11] = ["VInt", "VFloat", "VText", "VBool", "VSeq", "VDuration", "VDate", "VMoment", "VSpan", "VTime", "VChar"];

/// Whether an argument in `variant` is taken by a parameter of type `ty`: its own variant, or an `Int` for a `Real`.
fn takes(ty: &str, variant: &str) -> bool {
    carried(ty) == variant || (ty == "Real" && variant == "VInt")
}

/// The expression for the argument at `position`, bound from `variant`, as a value of type `ty`.
fn unwrapped(ty: &str, variant: &str, position: usize) -> String {
    let binder = format!("{}{position}", variant_binder(variant));
    if ty == "Real" && variant == "VInt" {
        format!("({binder} + 0.0)")
    } else {
        binder
    }
}

fn variant_binder(variant: &str) -> &'static str {
    match variant {
        "VInt" => "int",
        "VFloat" => "real",
        "VText" => "text",
        "VBool" => "bool",
        "VSeq" => "seq",
        "VDuration" => "duration",
        "VDate" => "date",
        "VMoment" => "moment",
        "VSpan" => "span",
        "VTime" => "time",
        "VChar" => "char",
        other => panic!("no binder for `{other}`"),
    }
}

/// The function a builtin's calls go to.
fn function_of(id: BuiltinId) -> String {
    match id.self_interpreted() {
        SelfInterpreted::Defined => format!("coreDefined{id:?}"),
        _ => format!("coreBuiltin{id:?}"),
    }
}

/// Every name a call reaches a builtin by: the builtins' own names, and the standard library's system natives,
/// which a call reaches when the program defines no function of that name.
fn named() -> impl Iterator<Item = (&'static str, BuiltinId)> {
    BUILTIN_NAMES.iter().map(|(name, id)| (*name, *id)).chain(SYSTEM_NATIVES.iter().map(|(name, _, id)| (*name, *id)))
}

/// Every name the self-interpreter answers, with the function its calls go to, by name.
fn answered() -> BTreeMap<&'static str, String> {
    let mut names: BTreeMap<&'static str, String> = BTreeMap::new();
    for (name, id) in named() {
        if !matches!(id.self_interpreted(), SelfInterpreted::Awaits(_)) {
            names.insert(name, function_of(id));
        }
    }
    names
}

/// The generated text: the dispatch and one function per builtin the table types, between [`BEGIN`] and [`END`].
pub fn dispatch_source() -> String {
    let names = answered();
    let mut by_length: BTreeMap<usize, Vec<(&str, &String)>> = BTreeMap::new();
    for (name, function) in &names {
        by_length.entry(name.chars().count()).or_default().push((name, function));
    }
    let mut out = String::new();
    out.push_str(BEGIN);
    out.push('\n');
    out.push_str("## To coreBuiltinKnown (name: Text) -> Bool:\n");
    out.push_str("    Let nameLength be length of name.\n");
    for (len, group) in &by_length {
        out.push_str(&format!("    If nameLength equals {len}:\n"));
        let tests: Vec<String> = group.iter().map(|(n, _)| format!("(name equals \"{n}\")")).collect();
        out.push_str(&format!("        Return {}.\n", tests.join(" or ")));
    }
    out.push_str("    Return false.\n\n");

    out.push_str("## To coreBuiltin (name: Text) and (args: Seq of CVal) -> CVal:\n");
    out.push_str("    Let nameLength be length of name.\n");
    for (len, group) in &by_length {
        out.push_str(&format!("    If nameLength equals {len}:\n"));
        for (name, function) in group {
            out.push_str(&format!("        If name equals \"{name}\":\n"));
            out.push_str(&format!("            Return {function}(args).\n"));
        }
    }
    out.push_str("    Let awaited be coreBuiltinAwaited(name).\n");
    out.push_str("    If awaited is not \"\":\n");
    out.push_str("        Return a new VError with msg \"the self-interpreter applies no `{name}`: it awaits {awaited}\".\n");
    out.push_str("    Return a new VError with msg \"Unknown function: {name}\".\n\n");

    let mut awaited: BTreeMap<usize, BTreeMap<&str, BTreeSet<&str>>> = BTreeMap::new();
    for (name, id) in named() {
        if let SelfInterpreted::Awaits(why) = id.self_interpreted() {
            assert!(!why.is_empty() && !why.contains(['"', '{', '}']), "`{why}` is no reason a LOGOS text can hold");
            awaited.entry(name.chars().count()).or_default().entry(why).or_default().insert(name);
        }
    }
    out.push_str("## To coreBuiltinAwaited (name: Text) -> Text:\n");
    out.push_str("    Let nameLength be length of name.\n");
    for (len, reasons) in &awaited {
        out.push_str(&format!("    If nameLength equals {len}:\n"));
        for (why, group) in reasons {
            let tests: Vec<String> = group.iter().map(|n| format!("(name equals \"{n}\")")).collect();
            out.push_str(&format!("        If {}:\n", tests.join(" or ")));
            out.push_str(&format!("            Return \"{why}\".\n"));
        }
    }
    out.push_str("    Return \"\".\n");

    let mut typed: Vec<BuiltinId> =
        named().map(|(_, id)| id).filter(|id| matches!(id.self_interpreted(), SelfInterpreted::Overloads { .. })).collect();
    typed.sort_by_key(|id| format!("{id:?}"));
    typed.dedup();
    for id in typed {
        let SelfInterpreted::Overloads { overloads, refusal } = id.self_interpreted() else {
            unreachable!()
        };
        let callee = named().find(|(_, b)| *b == id).map(|(n, _)| n).expect("a typed builtin has a name");
        out.push('\n');
        out.push_str(&typed_function(id, callee, overloads, id.self_interpreted_stops(), refusal));
    }
    out.push_str(END);
    out.push('\n');
    out
}

/// The line that opens the specializer's generated builtins in `pe_source.logos`.
pub const SPECIALIZER_BEGIN: &str = "# The specializer's builtins: generated by optimize::core_builtins from semantics::builtin_overloads.";

/// The line that closes them.
pub const SPECIALIZER_END: &str = "# The specializer's builtins end.";

/// The Core IR constant that holds a value of a literal type, `None` for a type the specializer holds no constant of.
fn constant_of(ty: &str) -> Option<&'static str> {
    Some(match ty {
        "Int" => "CInt",
        "Real" => "CFloat",
        "Text" => "CText",
        "Bool" => "CBool",
        "Duration" => "CDuration",
        "Date" => "CDate",
        "Moment" => "CMoment",
        "Span" => "CSpan",
        "Time" => "CTime",
        "Char" => "CChar",
        "Bytes" => "CList",
        _ => return None,
    })
}

/// The builtins the specializer folds: each pure builtin the self-interpreter runs by overloads whose argument and
/// answer types are all ones the specializer holds a constant of. A pure builtin answers every argument its overloads
/// take, so the specializer calls it on known arguments and holds its answer as a constant, as it folds an operator.
fn folded() -> Vec<(&'static str, BuiltinId, &'static [Overload])> {
    let mut out: Vec<(&'static str, BuiltinId, &'static [Overload])> = Vec::new();
    for (name, id) in named() {
        let SelfInterpreted::Overloads { overloads, .. } = id.self_interpreted() else { continue };
        let literal = overloads.iter().all(|o| o.params.iter().chain(std::iter::once(&o.answer)).all(|t| constant_of(t).is_some()));
        let pure = matches!(id.effect(), crate::semantics::builtins::BuiltinEffect::Pure);
        if pure && literal && !out.iter().any(|(n, _, _)| *n == name) {
            out.push((name, id, overloads));
        }
    }
    out.sort_by_key(|(n, _, _)| *n);
    out
}

/// The specializer's folding of a builtin on known arguments: `peFoldBuiltin (name, args)` and one function per folded
/// builtin, between [`SPECIALIZER_BEGIN`] and [`SPECIALIZER_END`]. A call on arguments that are not the constants an
/// overload takes answers `__pe_no_unfold`, which leaves the call residual.
pub fn specializer_source() -> String {
    let builtins = folded();
    let mut by_length: BTreeMap<usize, Vec<(&str, BuiltinId)>> = BTreeMap::new();
    for (name, id, _) in &builtins {
        by_length.entry(name.chars().count()).or_default().push((name, *id));
    }
    let no = "a new CVar with name \"__pe_no_unfold\"";
    let mut out = String::new();
    out.push_str(SPECIALIZER_BEGIN);
    out.push('\n');
    out.push_str("## To peFoldBuiltin (fbName: Text) and (fbArgs: Seq of CExpr) -> CExpr:\n");
    out.push_str("    Let fbLength be length of fbName.\n");
    for (len, group) in &by_length {
        out.push_str(&format!("    If fbLength equals {len}:\n"));
        for (name, id) in group {
            out.push_str(&format!("        If fbName equals \"{name}\":\n"));
            out.push_str(&format!("            Return peFoldBuiltin{id:?}(fbArgs).\n"));
        }
    }
    out.push_str(&format!("    Return {no}.\n"));
    for (name, id, overloads) in &builtins {
        let arity = overloads.first().map_or(0, |o| o.params.len());
        out.push_str(&format!("\n## To peFoldBuiltin{id:?} (fbArgs: Seq of CExpr) -> CExpr:\n"));
        out.push_str(&format!("    If length of fbArgs is not {arity}:\n        Return {no}.\n"));
        for position in 1..=arity {
            out.push_str(&format!("    Let fbArg{position} be item {position} of fbArgs.\n"));
        }
        out.push_str(&fold_decision(name, overloads, arity, 1, &mut Vec::new(), 1, no));
    }
    out.push_str(SPECIALIZER_END);
    out.push('\n');
    out
}

/// The constants an argument of type `ty` is told apart by: its own, for a `Real` an `Int` too, widened, and for
/// `Bytes` an empty list as well as a list.
fn constants_taking(ty: &str) -> Vec<&'static str> {
    let mut held = vec![constant_of(ty).expect("a folded builtin's types are constants")];
    if ty == "Real" {
        held.push("CInt");
    }
    if ty == "Bytes" {
        held.push("CNewSeq");
    }
    held
}

/// The statements that read the known list argument at `position` as bytes, `fbBytes{position}`, leaving the call
/// residual when an item is not a known `Int`.
fn fold_bytes_of(position: usize, list: &str, pad: &str, no: &str) -> String {
    let mut out = format!("{pad}Let mutable fbBytes{position} be a new Seq of Int.\n");
    if list == "CList" {
        out.push_str(&format!("{pad}Repeat for fbByte{position} in fbList{position}:\n"));
        out.push_str(&format!("{pad}    Inspect fbByte{position}:\n"));
        out.push_str(&format!("{pad}        When CInt (fbByteInt{position}):\n"));
        out.push_str(&format!("{pad}            Push fbByteInt{position} to fbBytes{position}.\n"));
        out.push_str(&format!("{pad}        Otherwise:\n{pad}            Return {no}.\n"));
    }
    out
}

/// The fold's decision at argument `position`, `chosen` holding the constants of the arguments before it.
fn fold_decision(
    callee: &str,
    overloads: &[Overload],
    arity: usize,
    position: usize,
    chosen: &mut Vec<&'static str>,
    depth: usize,
    no: &str,
) -> String {
    let pad = "    ".repeat(depth);
    let takes_constant = |ty: &str, c: &str| constants_taking(ty).contains(&c);
    let fits = |o: &&Overload, chosen: &[&'static str]| o.params.iter().zip(chosen.iter()).all(|(ty, c)| takes_constant(ty, c));
    if position > arity {
        let overload = overloads.iter().find(|o| fits(o, chosen)).expect("a decided path names an overload that takes it");
        let mut out = String::new();
        let mut args: Vec<String> = Vec::new();
        for (i, (ty, c)) in overload.params.iter().zip(chosen.iter()).enumerate() {
            let binder = format!("fb{}{}", &c[1..], i + 1);
            if *ty == "Bytes" {
                out.push_str(&fold_bytes_of(i + 1, c, &pad, no));
                args.push(format!("fbBytes{}", i + 1));
            } else if *ty == "Real" && *c == "CInt" {
                args.push(format!("({binder} + 0.0)"));
            } else {
                args.push(binder);
            }
        }
        let call = format!("{callee}({})", args.join(", "));
        if overload.answer == "Bytes" {
            out.push_str(&format!("{pad}Let fbAnswered be {call}.\n"));
            out.push_str(&format!("{pad}Let mutable fbAnsweredItems be a new Seq of CExpr.\n"));
            out.push_str(&format!("{pad}Repeat for fbAnsweredByte in fbAnswered:\n"));
            out.push_str(&format!("{pad}    Push a new CInt with value fbAnsweredByte to fbAnsweredItems.\n"));
            out.push_str(&format!("{pad}Return a new CList with items fbAnsweredItems.\n"));
        } else {
            let answer = constant_of(overload.answer).expect("a folded builtin's answer is a constant");
            out.push_str(&format!("{pad}Return a new {answer} with value {call}.\n"));
        }
        return out;
    }
    let mut constants: Vec<&'static str> = Vec::new();
    for o in overloads.iter().filter(|o| fits(o, chosen)) {
        for c in constants_taking(o.params[position - 1]) {
            if !constants.contains(&c) {
                constants.push(c);
            }
        }
    }
    let mut out = format!("{pad}Inspect fbArg{position}:\n");
    for c in constants {
        let binder = if c == "CNewSeq" { format!("fbEmpty{position}") } else { format!("fb{}{position}", &c[1..]) };
        out.push_str(&format!("{pad}    When {c} ({binder}):\n"));
        chosen.push(c);
        out.push_str(&fold_decision(callee, overloads, arity, position + 1, chosen, depth + 2, no));
        chosen.pop();
    }
    out.push_str(&format!("{pad}    Otherwise:\n{pad}        Return {no}.\n"));
    out
}

/// One builtin's function: a decision on its arguments' variants that stops on the types the language refuses in its
/// own words (`stops`) and calls the first overload taking the rest.
fn typed_function(id: BuiltinId, callee: &str, overloads: &[Overload], stops: &[Stop], refusal: &str) -> String {
    let arity = overloads.first().map_or(0, |o| o.params.len());
    assert!(
        overloads.iter().all(|o| o.params.len() == arity) && stops.iter().all(|s| s.params.len() == arity),
        "{id:?}: every overload and stop of a typed builtin takes the same number of arguments"
    );
    let mut out = format!("## To coreBuiltin{id:?} (args: Seq of CVal) -> CVal:\n");
    for position in 1..=arity {
        out.push_str(&format!("    Let arg{position} be item {position} of args.\n"));
    }
    out.push_str(&decide(callee, overloads, stops, refusal, arity, 1, &mut Vec::new(), 1));
    out
}

/// Whether arguments in the variants `chosen` so far fit `params`.
fn fits(params: &[&str], chosen: &[&'static str]) -> bool {
    params.iter().zip(chosen.iter()).all(|(ty, v)| takes(ty, v))
}

/// The decision at argument `position`, `chosen` holding the variants of the arguments before it.
#[allow(clippy::too_many_arguments)]
fn decide(
    callee: &str,
    overloads: &[Overload],
    stops: &[Stop],
    refusal: &str,
    arity: usize,
    position: usize,
    chosen: &mut Vec<&'static str>,
    depth: usize,
) -> String {
    let pad = "    ".repeat(depth);
    if position > arity {
        if let Some(stop) = stops.iter().find(|s| fits(s.params, chosen)) {
            return format!("{pad}Return a new VError with msg \"{}\".\n", stop.report);
        }
        let overload = overloads.iter().find(|o| fits(o.params, chosen)).expect("a decided path names an overload that takes it");
        let mut out = String::new();
        let mut args: Vec<String> = Vec::new();
        for (i, (ty, v)) in overload.params.iter().zip(chosen.iter()).enumerate() {
            if *ty == "Bytes" {
                out.push_str(&bytes_of(i + 1, &pad));
                args.push(format!("bytes{}", i + 1));
            } else {
                args.push(unwrapped(ty, v, i + 1));
            }
        }
        let call = format!("{callee}({})", args.join(", "));
        if overload.answer == "Bytes" {
            out.push_str(&format!("{pad}Let answered be {call}.\n"));
            out.push_str(&format!("{pad}Let mutable answeredItems be a new Seq of CVal.\n"));
            out.push_str(&format!("{pad}Repeat for answeredByte in answered:\n"));
            out.push_str(&format!("{pad}    Push a new VInt with value answeredByte to answeredItems.\n"));
            out.push_str(&format!("{pad}Return a new VSeq with items answeredItems.\n"));
        } else {
            out.push_str(&format!("{pad}Return a new {} with value {call}.\n", carried(overload.answer)));
        }
        return out;
    }
    let mut variants: Vec<&'static str> = Vec::new();
    let candidates = overloads
        .iter()
        .filter(|o| fits(o.params, chosen))
        .map(|o| o.params[position - 1])
        .chain(stops.iter().filter(|s| fits(s.params, chosen)).map(|s| s.params[position - 1]));
    for ty in candidates {
        for v in VARIANTS {
            if takes(ty, v) && !variants.contains(&v) {
                variants.push(v);
            }
        }
    }
    let mut out = format!("{pad}Inspect arg{position}:\n");
    for v in variants {
        out.push_str(&format!("{pad}    When {v} ({}{position}):\n", variant_binder(v)));
        chosen.push(v);
        out.push_str(&decide(callee, overloads, stops, refusal, arity, position + 1, chosen, depth + 2));
        chosen.pop();
    }
    out.push_str(&format!("{pad}    Otherwise:\n"));
    out.push_str(&refuse(refusal, arity, depth + 2));
    out
}

/// The statements that read the list argument at `position` as bytes, `bytes{position}`, stopping on an item that is not
/// an `Int` with [`BYTE_ELEMENT_REFUSAL`].
fn bytes_of(position: usize, pad: &str) -> String {
    let refusal = BYTE_ELEMENT_REFUSAL.replace("{n}", &format!("{{byteAt{position}}}"));
    let mut out = String::new();
    out.push_str(&format!("{pad}Let mutable bytes{position} be a new Seq of Int.\n"));
    out.push_str(&format!("{pad}Let mutable byteAt{position} be 0.\n"));
    out.push_str(&format!("{pad}Repeat for byte{position} in seq{position}:\n"));
    out.push_str(&format!("{pad}    Set byteAt{position} to byteAt{position} + 1.\n"));
    out.push_str(&format!("{pad}    Inspect byte{position}:\n"));
    out.push_str(&format!("{pad}        When VInt (byteInt{position}):\n"));
    out.push_str(&format!("{pad}            Push byteInt{position} to bytes{position}.\n"));
    out.push_str(&format!("{pad}        Otherwise:\n"));
    out.push_str(&format!("{pad}            Return a new VError with msg \"{refusal}\".\n"));
    out
}

/// The statements that stop a call with `refusal`, each `{n}` naming the type of argument `n`.
fn refuse(refusal: &str, arity: usize, depth: usize) -> String {
    let pad = "    ".repeat(depth);
    let mut out = String::new();
    let mut message = refusal.to_string();
    for position in 1..=arity {
        let slot = format!("{{{position}}}");
        if message.contains(&slot) {
            out.push_str(&format!("{pad}Let got{position} be coreTypeName(arg{position}).\n"));
            message = message.replace(&slot, &format!("{{got{position}}}"));
        }
    }
    out.push_str(&format!("{pad}Return a new VError with msg \"{message}\".\n"));
    out
}

