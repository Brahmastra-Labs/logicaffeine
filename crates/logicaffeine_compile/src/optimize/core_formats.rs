//! The self-interpreter's formatting of a number to a precision, generated so it formats exactly as the language
//! does (`semantics::format`): each precision through the language's own interpolation hole, `{x:.N}`.
//!
//! An interpolation's spec is data the self-interpreter reads (`CFormattedPart with expr and spec`), while the
//! language spells a precision in a hole with its digits written out. So `core_interp.logos` holds
//! `coreFormatPrecision (value, digits)` between [`BEGIN`] and [`END`], a branch per precision up to [`PRECISIONS`],
//! which a lock holds equal to [`precision_source`]; a precision past them stops with what the self-interpreter
//! awaits, never with other digits. `pe_source.logos` holds the specializer's counterpart,
//! [`specializer_precision_source`].

/// The line that opens the generated text in `core_interp.logos`.
pub const BEGIN: &str = "# The precisions: generated by optimize::core_formats from semantics::format.";

/// The line that closes it.
pub const END: &str = "# The precisions end.";

/// The most digits after the point the self-interpreter formats a number to.
pub const PRECISIONS: usize = 32;

/// The generated text: `coreFormatPrecision`, between [`BEGIN`] and [`END`].
pub fn precision_source() -> String {
    let mut out = String::new();
    out.push_str(BEGIN);
    out.push('\n');
    out.push_str("## To coreFormatPrecision (fpValue: CVal) and (fpDigits: Int) -> CVal:\n");
    out.push_str("    Inspect fpValue:\n");
    for (variant, binder) in [("VInt", "fpInt"), ("VFloat", "fpReal")] {
        out.push_str(&format!("        When {variant} ({binder}):\n"));
        for digits in 0..=PRECISIONS {
            out.push_str(&format!("            If fpDigits equals {digits}:\n"));
            out.push_str(&format!("                Return a new VText with value \"{{{binder}:.{digits}}}\".\n"));
        }
    }
    out.push_str("        Otherwise:\n");
    out.push_str("            Return a new VText with value valToText(fpValue).\n");
    out.push_str(&format!(
        "    Return a new VError with msg \"the self-interpreter applies no `.{{fpDigits}}`: it awaits a precision of at most {PRECISIONS} digits\".\n"
    ));
    out.push_str(END);
    out.push('\n');
    out
}

/// The line that opens the generated text in `pe_source.logos`.
pub const SPECIALIZER_BEGIN: &str = "# The specializer's precisions: generated by optimize::core_formats from semantics::format.";

/// The line that closes it.
pub const SPECIALIZER_END: &str = "# The specializer's precisions end.";

/// The specializer's `pePrecision (e, digits)` between [`SPECIALIZER_BEGIN`] and [`SPECIALIZER_END`]: a known number
/// formatted to a precision as the language formats it, as a text literal, so a hole with a spec on a value the
/// specializer knows folds as every other known hole does; anything else is left to the residual.
pub fn specializer_precision_source() -> String {
    let mut out = String::new();
    out.push_str(SPECIALIZER_BEGIN);
    out.push('\n');
    out.push_str("## To pePrecision (ppExpr: CExpr) and (ppDigits: Int) -> CExpr:\n");
    out.push_str("    Inspect ppExpr:\n");
    for (variant, binder) in [("CInt", "ppInt"), ("CFloat", "ppReal")] {
        out.push_str(&format!("        When {variant} ({binder}):\n"));
        for digits in 0..=PRECISIONS {
            out.push_str(&format!("            If ppDigits equals {digits}:\n"));
            out.push_str(&format!("                Return a new CText with value \"{{{binder}:.{digits}}}\".\n"));
        }
    }
    out.push_str("        Otherwise:\n");
    out.push_str("            Let ppSkip be true.\n");
    out.push_str("    Return a new CVar with name \"__pe_no_unfold\".\n");
    out.push_str(SPECIALIZER_END);
    out.push('\n');
    out
}

