#!/usr/bin/env python3
"""Write K4's Dahlia port, kernel.fuse: Keccak-f[1600] over 25 lane registers.

Dahlia has no constant arrays, so the 24 rounds unroll with their round constants and rotation offsets as
literals. Each round is five unordered (`;`) steps whose statements never read a register another one in the
same step writes: the column parities, the theta mix, rho and pi into the scratch lanes, chi back into the
state, then iota. Run from this directory: `python3 gen_kernel_fuse.py > kernel.fuse`.
"""

RC = [
    0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
    0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
    0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
    0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
    0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
    0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
]
# rho offsets r[x][y] for lane index x + 5y
RHO = [0, 1, 62, 28, 27, 36, 44, 6, 55, 20, 3, 10, 43, 25, 39, 41, 45, 15, 21, 8, 18, 2, 61, 56, 14]
ONES = "(18446744073709551615 as ubit<64>)"


def lit(v):
    return "(%d as ubit<64>)" % v


def rotl(x, n):
    if n == 0:
        return x
    return "((%s << %s) | (%s >> %s))" % (x, lit(n), x, lit(64 - n))


def main():
    out = ["// K4 keccak_f1600 for Calyx through Dahlia, generated by gen_kernel_fuse.py: the 25 lanes read from",
           "// s_in, 24 unrolled rounds over lane registers, the result written to s_out.",
           "decl s_in: ubit<64>[25];", "decl s_out: ubit<64>[25];"]
    for i in range(25):
        out.append("---")
        out.append("let a%d: ubit<64> = s_in[(%d as ubit<5>)];" % (i, i))
    out.append("---")
    out.append("; ".join("let c%d: ubit<64> = %s" % (x, lit(0)) for x in range(5)) + ";")
    out.append("---")
    out.append("; ".join("let d%d: ubit<64> = %s" % (x, lit(0)) for x in range(5)) + ";")
    out.append("---")
    out.append("; ".join("let b%d: ubit<64> = %s" % (i, lit(0)) for i in range(25)) + ";")
    for r in range(24):
        out.append("---")
        out.append("; ".join("c%d := a%d ^ a%d ^ a%d ^ a%d ^ a%d" % (x, x, x + 5, x + 10, x + 15, x + 20) for x in range(5)) + ";")
        out.append("---")
        out.append("; ".join("d%d := c%d ^ %s" % (x, (x + 4) % 5, rotl("c%d" % ((x + 1) % 5), 1)) for x in range(5)) + ";")
        out.append("---")
        out.append("; ".join("a%d := a%d ^ d%d" % (i, i, i % 5) for i in range(25)) + ";")
        out.append("---")
        stmts = []
        for x in range(5):
            for y in range(5):
                src = x + 5 * y
                dst = y + 5 * ((2 * x + 3 * y) % 5)
                stmts.append("b%d := %s" % (dst, rotl("a%d" % src, RHO[src])))
        out.append("; ".join(stmts) + ";")
        out.append("---")
        stmts = []
        for y in range(5):
            for x in range(5):
                i = x + 5 * y
                n1 = (x + 1) % 5 + 5 * y
                n2 = (x + 2) % 5 + 5 * y
                stmts.append("a%d := b%d ^ ((b%d ^ %s) & b%d)" % (i, i, n1, ONES, n2))
        out.append("; ".join(stmts) + ";")
        out.append("---")
        out.append("a0 := a0 ^ %s;" % lit(RC[r]))
    for i in range(25):
        out.append("---")
        out.append("s_out[(%d as ubit<5>)] := a%d;" % (i, i))
    print("\n".join(out))


if __name__ == "__main__":
    main()
