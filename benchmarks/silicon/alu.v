// The LOGOS general integer ALU datapath — the combinational functional unit that executes the
// arithmetic / bitwise / signed-comparison instructions straight off a WIRE OPCODE BYTE. The `case`
// labels ARE the stable `binisa::opcode` numbers (one source of truth with the wire format), so the
// ALU decodes the exact bytes the network carries. Each operation is proven correct by our OWN
// certified SAT — `codegen_sva::rtl::tests::the_general_alu_datapath_is_proven_correct_by_our_sat`
// (Add/Sub mutual inverse, Mul distributes, Xor self-inverse, De Morgan for And/Or/Not, signed-<
// antisymmetry + trichotomy, Eq⟺(a−b==0)). Comparisons are SIGNED (VM i64 semantics), yielding 0/1.
// Generated by `emit_alu_datapath_verilog(32)`.
module alu(input [7:0] opcode, input [31:0] a, input [31:0] b, output reg [31:0] y);
  always @(*) begin
    case (opcode)
      8'd8:  y = a + b;                                  // Add
      8'd9:  y = a + b;                                  // AddAssign (in-place adder)
      8'd10: y = a - b;                                  // Sub
      8'd11: y = a * b;                                  // Mul
      // Div / ExactDiv / Mod / FloorDiv (12/13/15/14) are NOT here — division is sequential, so the
      // soft-core issues those to the shared iterative shared_divider. They fall through to y=0 here.
      // DivPow2 (signed a / 2^b, round toward zero): negative-bias then arithmetic shift; b is the exponent
      8'd16: y = a[31] ? ($signed($signed(a) + ((32'd1 << b[4:0]) - 32'd1)) >>> b[4:0]) : ($signed(a) >>> b[4:0]);
      8'd19: y = a ^ b;                                  // BitXor
      8'd20: y = a & b;                                  // BitAnd
      8'd21: y = a | b;                                  // BitOr
      8'd24: y = ~a;                                     // Not (bitwise)
      8'd22: y = a << b[4:0];                            // Shl (logical, count mod 32)
      8'd23: y = $signed(a) >>> b[4:0];                  // Shr (ARITHMETIC, count mod 32)
      8'd25: y = ($signed(a) <  $signed(b)) ? 1 : 0;     // Lt   (signed)
      8'd26: y = ($signed(a) >  $signed(b)) ? 1 : 0;     // Gt   (signed)
      8'd27: y = ($signed(a) <= $signed(b)) ? 1 : 0;     // LtEq (signed)
      8'd28: y = ($signed(a) >= $signed(b)) ? 1 : 0;     // GtEq (signed)
      8'd29,
      8'd30: y = (a == b) ? 1 : 0;                       // Eq / ApproxEq (integer sub-domain ⇒ exact equality)
      8'd31: y = (a != b) ? 1 : 0;                       // NotEq
      // The WORD32 ring ℤ/2³² arithmetic (Word32Add/Sub/Mul, ops 226/227/228 — SHA-256's `s0+s1+…` chain).
      // On this 32-bit datapath a+b / a-b / a*b already wrap mod 2³² (Verilog truncates to the 32-bit `y`),
      // which IS the ring op; the result Shows UNSIGNED via ShowWord32 (op 221). Reuses the existing
      // adder/subtractor/multiplier — no new hardware, only three decode labels. Distinct from the SIGNED
      // Add/Sub/Mul (8/10/11) ONLY in how the value is later rendered. Before this, they hit `default: y=0`
      // — the $50M silent-zero hole that `fifty_million_dollar_test.rs` now makes impossible.
      8'd226: y = a + b;                                 // Word32Add
      8'd227: y = a - b;                                 // Word32Sub
      8'd228: y = a * b;                                 // Word32Mul (low 32 bits of the product)
      default: y = 32'd0;
    endcase
  end
endmodule
