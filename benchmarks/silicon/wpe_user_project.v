  psram_arbiter #(.N(5)) mem_arb (
    .clk(clk), .rst(rst), .c_valid(mc_valid), .c_ready(mc_ready), .c_we(mc_we), .c_addr(mc_addr), .c_len(mc_len),
    .c_wdata(mc_wdata), .e_valid(me_valid), .e_ready(me_ready), .e_we(me_we), .e_addr(me_addr), .e_len(me_len),
    .e_wdata(me_wdata));
  psram_edge mem_edge (
    .clk(clk), .rst(rst), .req_valid(me_valid), .req_ready(me_ready), .req_we(me_we), .req_addr(me_addr),
    .req_len(me_len), .wdata(me_wdata), .wdata_take(me_take), .rdata(me_rdata), .rdata_valid(me_rvalid),
    .ce_n(psram_ce_n), .sclk(psram_sclk), .sio_out(psram_sio_out), .sio_oe(psram_sio_oe), .sio_in(psram_sio_in));
  always @(posedge clk) begin
    // A received byte waits out a stall (the loader's stalls are shorter than a byte); request pulses clear.
    rx_valid <= rx_valid & mstall; tx_start <= 1'b0;
    // Each cache hit refreshed for the address it holds, across fills and resets; a task that sets an address this
    // cycle sets its hit after this.
    hq_r <= 1'b0; hq_w <= 1'b0;
    hq_rhit <= hq_hit_at(heap_ra); hq_whit <= hq_hit_at(hq_wa);
    sq_r <= 1'b0; sq_w <= 1'b0;
    sq_rhit <= sq_hit_at(sf_ra); sq_whit <= sq_hit_at(sq_wa);
    cq_w <= 3'b000;
    cq_rhit <= cq_hit_at(blk_cell_ptr[pc] + ci); cq_whit <= cq_hit_at(cq_wa);
    rx_d1 <= uart_rx; rx_d2 <= rx_d1;
    // The register-file/cell-value block-RAM registered reads exist ONLY under CFG_BRAM=1 (their consumers are the
    // ST_OP/ST_WR/ST_TR/ST_FS/ST_AG fetch wait-states). This whole read is EXCISED from the CFG_BRAM=0 netlist
    // (the emitter drops the region between the markers) so those backends stay byte-identical to before + synth
    // fast; under CFG_BRAM=1 `file`/`v` are block RAM and these are their registered read ports.
    file_rd <= {file_hi[file_ra], file_lo[file_ra]};
    v_rd    <= {v_hi[v_ra], v_lo[v_ra]};
    // CFG_BRAM: registered read of the CURRENT cell (config image in block RAM), consumed in st==0 via cc_*.
    // CFG_BRAM: registered read of the CURRENT write record (config image in block RAM), consumed in st==1 via w_*.
    wr_reg_r  <= wr_reg[c_wrptr + wi];      wr_op_r   <= wr_op[c_wrptr + wi];
    // CFG_BRAM: registered read of the CURRENT block record (13 blk_* arrays in block RAM), consumed via c_*.
    blk_livein_ptr_r <= blk_livein_ptr[pc]; blk_n_livein_r <= blk_n_livein[pc]; blk_cell_ptr_r <= blk_cell_ptr[pc];
    blk_n_cells_r <= blk_n_cells[pc];       blk_write_ptr_r <= blk_write_ptr[pc]; blk_n_writes_r <= blk_n_writes[pc];
    blk_term_kind_r <= blk_term_kind[pc];   blk_t0_r <= blk_t0[pc];              blk_t1_r <= blk_t1[pc];
    blk_top_r <= blk_top[pc];               blk_cdst_r <= blk_cdst[pc];          blk_cargc_r <= blk_cargc[pc];
    blk_cargp_r <= blk_cargp[pc];

    if (rst) begin
      r_state<=R_IDLE; t_state<=T_IDLE; uart_tx<=1'b1;
      ph<=P_CNT; mi<=6'd0; cnt<=16'd0; entry<=16'd0; bcnt<=2'd0; bidx<=4'd0; acc<=64'd0;
      np<=16'd0; pentry<=16'd0; hpre<=16'd0; send_ph<=4'd0; done_r<=1'b0; run_cycles<=32'd0; sp_ovf<=1'b0; heap_ovf<=1'b0;
      r_cnt<=0; r_bit<=3'd0; t_cnt<=0; t_bit<=3'd0;
    end else begin
      // ── UART RX ──
      case (r_state)
        R_IDLE:  if (~rx_d2) begin r_state<=R_START; r_cnt<=0; end
        R_START: if (r_cnt==(CLKS_PER_BIT-1)/2) begin
                   if (~rx_d2) begin r_cnt<=0; r_bit<=3'd0; r_state<=R_DATA; end else r_state<=R_IDLE;
                 end else r_cnt<=r_cnt+1'b1;
        R_DATA:  if (r_cnt==CLKS_PER_BIT-1) begin
                   r_cnt<=0; r_shift<={rx_d2, r_shift[7:1]};
                   if (r_bit==3'd7) r_state<=R_STOP; else r_bit<=r_bit+1'b1;
                 end else r_cnt<=r_cnt+1'b1;
        R_STOP:  if (r_cnt==CLKS_PER_BIT-1) begin r_cnt<=0; rx_valid<=1'b1; rx_data<=r_shift; r_state<=R_IDLE; end
                 else r_cnt<=r_cnt+1'b1;
      endcase
      // ── UART TX ──
      case (t_state)
        T_IDLE:  if (tx_start) begin t_shift<=tx_data; t_state<=T_START; t_cnt<=0; uart_tx<=1'b0; end
        T_START: if (t_cnt==CLKS_PER_BIT-1) begin t_cnt<=0; t_bit<=3'd0; t_state<=T_DATA; uart_tx<=t_shift[0]; end
                 else t_cnt<=t_cnt+1'b1;
        T_DATA:  if (t_cnt==CLKS_PER_BIT-1) begin t_cnt<=0;
                   if (t_bit==3'd7) begin t_state<=T_STOP; uart_tx<=1'b1; end
                   else begin t_bit<=t_bit+1'b1; uart_tx<=t_shift[t_bit+1]; end
                 end else t_cnt<=t_cnt+1'b1;
        T_STOP:  if (t_cnt==CLKS_PER_BIT-1) begin t_cnt<=0; t_state<=T_IDLE; uart_tx<=1'b1; end
                 else t_cnt<=t_cnt+1'b1;
      endcase
      // ── loader / init / run / send ──
      if (!mstall) case (ph)
        P_CNT: if (rx_valid) begin
                 cnt <= {cnt[7:0], rx_data};
                 if (bcnt==2'd1) begin
                   bcnt<=2'd0; entry<=16'd0; bidx<=4'd0;
                   if ({cnt[7:0], rx_data}==16'd0) begin
                     if (mi==6'd23) ph<=P_NP; else mi<=mi+6'd1;
                   end else ph<=P_DAT;
                 end else bcnt<=2'd1;
               end
        P_DAT: if (rx_valid) begin
                 acc <= {acc[55:0], rx_data};
                 if (bidx == width-4'd1) begin
                   bidx<=4'd0;
                   case (mi)
                     6'd0:  blk_livein_ptr[entry] <= {acc[23:0], rx_data};
                     6'd1:  blk_n_livein[entry]   <= {acc[23:0], rx_data};
                     6'd2:  blk_cell_ptr[entry]   <= {acc[23:0], rx_data};
                     6'd3:  blk_n_cells[entry]    <= {acc[23:0], rx_data};
                     6'd4:  blk_write_ptr[entry]  <= {acc[23:0], rx_data};
                     6'd5:  blk_n_writes[entry]   <= {acc[23:0], rx_data};
                     6'd6:  blk_term_kind[entry]  <= {acc[23:0], rx_data};
                     6'd7:  blk_t0[entry]         <= {acc[23:0], rx_data};
                     6'd8:  blk_t1[entry]         <= {acc[23:0], rx_data};
                     6'd9:  blk_top[entry]        <= {acc[23:0], rx_data};
                     6'd10: blk_cdst[entry]       <= {acc[23:0], rx_data};
                     6'd11: blk_cargc[entry]      <= {acc[23:0], rx_data};
                     6'd12: blk_cargp[entry]      <= {acc[23:0], rx_data};
                     6'd13, 6'd14, 6'd15, 6'd16, 6'd17, 6'd18: cwrite(mi - 6'd13, entry, {acc[23:0], rx_data});
                     6'd19: wr_reg[entry]         <= {acc[23:0], rx_data};
                     6'd20: wr_op[entry]          <= {acc[23:0], rx_data};
                     6'd21: arg_op[entry]         <= {acc[23:0], rx_data};
                     6'd22: liv_reg[entry]        <= {acc[23:0], rx_data};
                     6'd23: konst[entry]          <= {acc[55:0], rx_data};
                     default: ;
                   endcase
                   if (entry+16'd1 == cnt) begin
                     entry<=16'd0;
                     if (mi==6'd23) ph<=P_NP; else begin mi<=mi+6'd1; ph<=P_CNT; end
                   end else entry<=entry+16'd1;
                 end else bidx<=bidx+4'd1;
               end
        P_NP:  if (rx_valid) begin
                 np <= {np[7:0], rx_data};
                 if (bcnt==2'd1) begin
                   bcnt<=2'd0; pentry<=16'd0; bidx<=4'd0;
                   ph <= ({np[7:0], rx_data}==16'd0) ? P_GO : P_PAR;
                 end else bcnt<=2'd1;
               end
        P_PAR: if (rx_valid) begin
                 acc <= {acc[55:0], rx_data};
                 if (bidx==4'd7) begin
                   bidx<=4'd0;
                   param_buf[pentry] <= {acc[55:0], rx_data};
                   if (pentry+16'd1 == np) ph<=P_GO; else pentry<=pentry+16'd1;
                 end else bidx<=bidx+4'd1;
               end
        // The go phase is also the heap-preload dispatcher: `0x5A` runs; `0x48` ('H') introduces an OPTIONAL
        // heap PRE-LOAD segment (the streamed weight blob) that a non-streamed program never sends — so the
        // wire format is byte-identical to before for every existing program.
        P_GO:  if (rx_valid) begin
                 if (rx_data==8'h5A) ph<=P_INIT;
                 else if (rx_data==8'h48) begin hpre<=16'd0; bcnt<=2'd0; ph<=P_HN; end
               end
        // ── heap PRE-LOAD: count (u16) then `hpre` u64 words into heap[0..hpre-1], then back to P_GO for the
        //    trailing `0x5A`. The DATA-segment model — weights arrive over the wire and land in the heap state
        //    plane, so `loaded()` (heap pointer 0) reads them; the bump allocator (`hp`) is seeded past them at
        //    INIT and P_CLR zeroes only the runtime region so the weights survive. ──
        P_HN:  if (rx_valid) begin
                 hpre <= {hpre[7:0], rx_data};
                 if (bcnt==2'd1) begin
                   bcnt<=2'd0; pentry<=16'd0; bidx<=4'd0; acc<=64'd0;
                   ph <= ({hpre[7:0], rx_data}==16'd0) ? P_GO : P_HD;
                 end else bcnt<=2'd1;
               end
        P_HD:  if (rx_valid) begin
                 acc <= {acc[55:0], rx_data};
                 if (bidx==4'd7) begin
                   bidx<=4'd0;
                   splitw = {acc[55:0], rx_data};   // blocking: sampled by both halves this cycle
                   hwrite({16'd0, pentry}, splitw);
                   if (pentry+16'd1 == hpre) ph<=P_GO; else pentry<=pentry+16'd1;
                 end else bidx<=bidx+4'd1;
               end
        P_INIT: begin
                 // Seed the register file from the streamed params. CFG_BRAM=0: `file` is flip-flops, so seed all
                 // NREG entries in ONE cycle (a parallel FF load — the proven path). CFG_BRAM=1: `file` is BLOCK
                 // RAM, which has a SINGLE write port — a parallel all-entry write is not RAMB-mappable (yosys:
                 // "no valid mapping found for memory file"), so route through P_FINIT to seed one file[j] per
                 // cycle (mirroring P_CLR's serial heap clear). Both paths leave file[j] = param_buf[j] for j<np,
                 // 0 otherwise — identical seeded state.
                 if (!CFG_BRAM) for (j=0;j<NREG;j=j+1) begin
                   splitw = (j < np) ? param_buf[j] : 64'sd0;   // blocking: sampled by both halves this iteration
                   file_lo[j] <= splitw[31:0];
                   file_hi[j] <= splitw[63:32];
                 end
                 hp<=$signed({48'd0, hpre}); sp<=16'd0; pc<=16'd0; ci<=16'd0; wi<=16'd0; gi<=16'd0; ai<=16'd0;
                 st<=4'd0; done_r<=1'b0; result_r<=64'sd0; run_cycles<=32'd0; send_ph<=4'd0; sp_ovf<=1'b0;
                 opi<=3'd0;
                 dr_bit<=7'd0; dr_code<=32'd0; dr_ci<=16'd0; dr_a<=64'd0; dr_x<=64'd0;
                 dr_rem<=64'd0; dr_quo<=64'd0; dr_neg_q<=1'b0; dr_neg_a<=1'b0;
                 mu_a<=64'd0; mu_b<=64'd0; pw_cnt<=64'sd0;
                 fav<=64'd0; fbv<=64'd0; fsub_r<=1'b0; fp_sel<=3'd0; cl_ready<=1'b0;
                 fas_start<=1'b0; fmul_start<=1'b0; fdiv_start<=1'b0; fsqrt_start<=1'b0; fconv_start<=1'b0;
                 if (CFG_BRAM) begin entry<=16'd0; ph<=P_FINIT; end   // serial file seed, then P_CLR
                 else begin hclr<=hpre; ph<=P_CLR; end
               end
        // CFG_BRAM=1 ONLY: seed the block-RAM register file one word per cycle (a BRAM has one write port), then
        // fall into the heap clear. Reuses the idle loader cursor `entry` (unused between P_INIT and the next
        // program's P_CNT). Unreachable under CFG_BRAM=0 (P_INIT jumps straight to P_CLR there).
        P_FINIT: begin
                 if (entry < NREG) begin
                   splitw = (entry < np) ? param_buf[entry] : 64'sd0;
                   file_lo[entry] <= splitw[31:0];
                   file_hi[entry] <= splitw[63:32];
                   entry <= entry + 16'd1;
                 end
                 else begin hclr<=hpre; ph<=P_CLR; end
               end
        P_CLR: begin
                 // BRAM cannot be bulk-reset — zero it one word per cycle so a fresh program starts on a clean
                 // heap (alloc-then-read-zero benchmarks depend on it). Config/param memories were already loaded.
                 if (hclr < HEAP) begin
                   hwrite(hclr, 64'd0);
                   hclr <= hclr + 32'd1;
                 end
                 else begin ph <= P_RUN; if (CFG_BRAM) st <= ST_CF; end   // one settle cycle so cc_*_r holds cell[0] before the first st0
               end
        P_RUN: if (!done_r && !heap_ovf) begin
                 if (!(st >= ST_SH && st <= ST_SHD)) run_cycles <= run_cycles + 32'd1;   // a Show's serial stall is I/O, not compute
                 case (st)
                   3'd0: begin
                     if (ci < c_ncells[15:0]) begin
                       if (CFG_BRAM) begin
                         // SERIAL PATH: don't resolve the four operands in one cycle (four parallel wide muxes =
                         // the net-dense hotspot the router can't legalize). Fetch them one-per-cycle in ST_OP
                         // through a SINGLE shared `resolve`, then run the compute in ST_CMP off registered r0..r3.
                         opi <= 3'd0; st <= ST_OP;
                       end else begin
                       r0 = resolve(cc_op0, c_livptr); r1 = resolve(cc_op1, c_livptr);
                       r2 = resolve(cc_op2, c_livptr); r3 = resolve(cc_op3, c_livptr);
                       if (cc_kind==32'd2 && cc_code <= 32'd3) begin
                         // A Div/Mod/FloorDiv/Pow func cell: latch operands and STALL into the sequential
                         // datapath (st==6).
                         dr_ci <= ci; dr_code <= cc_code;
                         if (cc_code == 32'd3) begin
                           // Pow: the accumulator mu_a starts at 1 and multiplies by the base mu_b = r0 for
                           // max(exponent,0) iterations.
                           mu_a <= 64'd1; mu_b <= r0; pw_cnt <= (r1 < 64'sd0) ? 64'sd0 : r1; pw_live <= (r1 > 64'sd0);
                           st <= 3'd6;
                         end else if (r1 == 64'sd0) begin
                           v_lo[ci] <= 32'd0; v_hi[ci] <= 32'd0; ci_set(ci + 16'd1);   // divide-by-zero trap → 0 (no stall, matches VM)
                           if (CFG_BRAM) st <= ST_CF;
                         end else begin
                           dr_a <= r0[63] ? (-r0) : r0;   // |dividend|  (INT_MIN negates to its own bit pattern = 2^63)
                           dr_x <= r1[63] ? (-r1) : r1;   // |divisor|
                           dr_neg_q <= r0[63] ^ r1[63];   // quotient negative iff operand signs differ
                           dr_neg_a <= r0[63];            // remainder takes the dividend's sign
                           dr_rem <= 64'd0; dr_quo <= 64'd0; dr_bit <= 7'd63;
                           st <= 3'd6;
                         end
                       end else if ((cc_kind==32'd0 && cc_code[3:0]==4'd2) || (cc_kind==32'd2 && (cc_code==32'd4 || cc_code==32'd12))) begin
                         // An integer multiply (Mul, MulHiU, MulOvfS): latch operands and STALL while the 64x64
                         // compressor tree runs (ST_MU..ST_MUW).
                         dr_ci <= ci; mu_a <= r0; mu_b <= r1;
                         mu_kind <= (cc_kind==32'd0) ? 2'd0 : (cc_code==32'd4) ? 2'd1 : 2'd2;
                         st <= ST_MU;
                       end else if (WITH_FPU && cc_kind==32'd2 && cc_code >= 32'd5 && cc_code != 32'd12) begin
                         // A FLOAT func cell (codes 5..20, ApproxEqF/11 excepted): latch operands + STALL into
                         // st==7 (the sequential FPU for add/sub/mul/div/sqrt/convert; combinational compare/pop).
                         dr_ci <= ci; dr_code <= cc_code; fav <= r0; fbv <= r1;
                         case (cc_code)
                           32'd5: begin fas_start  <= 1'b1; fsub_r <= 1'b0; fp_sel <= 3'd0; end   // FAdd
                           32'd6: begin fas_start  <= 1'b1; fsub_r <= 1'b1; fp_sel <= 3'd0; end   // FSub
                           32'd7: begin fmul_start <= 1'b1;                 fp_sel <= 3'd1; end   // FMul
                           32'd8: begin fdiv_start <= 1'b1;                 fp_sel <= 3'd2; end   // FDiv
                           32'd9: begin fsqrt_start<= 1'b1;                 fp_sel <= 3'd3; end   // FSqrt
                           32'd10, 32'd13: begin fconv_start <= 1'b1;       fp_sel <= 3'd5; end   // FFloor / IntToF
                           default:                                          fp_sel <= 3'd4;      // cmp / popcount
                         endcase
                         st <= 3'd7;
                       end else if (cc_kind==32'd3) begin
                         // HeapRead: drive the block-RAM read address, then wait out its registered-read latency
                         // (st 8 -> 9) before committing the value. Keeps ≡VM; the heap is no longer flip-flops.
                         hread(r0[63] ? 32'd0 : r0[31:0]); st <= 4'd8;   // clamp negative index to 0 (== eval a.max(0))
                       end else if (cc_kind==32'd6) begin
                         // DEEP-COPY (value semantics / COW): read the length header heap[src], copy header+elements
                         // to a fresh block at hp, return the new pointer — a multi-cycle heap-to-heap copy (st
                         // 14-18), bit-identical to eval_wprog_config kind 6. Without this the copy resolved to a
                         // bare hp pointer into cleared heap → quicksort/heap_sort read zeros (result 0).
                         dc_ci <= ci; dc_src <= r0[63] ? 64'sd0 : r0; dc_new <= hp;
                         hread(r0[63] ? 32'd0 : r0[31:0]); st <= 5'd14;
                       end else if (cc_kind==32'd7) begin
                         // TEXT CONCAT (TC_*): a fresh char-list = bytes(op0) ++ bytes(op1); code bits say which operands are Text
                         tt_ci <= ci; tt_val <= r0; tt_val2 <= r1; tt_istext <= cc_code[0]; tt_istext2 <= cc_code[1]; st <= TC_ST;
                       end else if (cc_kind==32'd8) begin
                         // TEXT CHAR-AT (CA_*): `item i of text` → a fresh 1-char Text
                         tt_ci <= ci; tt_val <= r0; tt_val2 <= r1; st <= CA_RD;
                       end else if (cc_kind==32'd9) begin
                         // TEXT EQUALITY (TE_*): byte-for-byte compare → 0/1 (code 0 = eq, 1 = ne)
                         tt_ci <= ci; tt_val <= r0; tt_val2 <= r1; tt_code <= cc_code[7:0]; st <= TE_LA;
                       end else if (cc_kind==32'd10) begin
                         // SHOW: stream a tagged record over the byte channel NOW (ST_SH..ST_SHD), then commit the value as
                         // this cell's result — the engine's output tape, ≡ eval_wprog_config_run.
                         dr_ci <= ci; sh_val <= r0; sh_tag <= cc_code[7:0]; sh_bi <= 4'd0; st <= ST_SH;
                       end else begin
                         cellval = (cc_kind==32'd0) ? alu_f(cc_code[3:0], r0, r1) :
                                   (cc_kind==32'd1) ? (cmp_f(cc_code[3:0], r0, r1) ? r2 : r3) :
                                   (cc_kind==32'd2) ? func_f(cc_code[7:0], r0, r1) :
                                   (cc_kind==32'd4) ? r1 : hp;
                         v_lo[ci] <= cellval[31:0]; v_hi[ci] <= cellval[63:32];
                         if (cc_kind==32'd4) begin   // depth-banked HeapWrite: clamp negative index to 0 (== eval a.max(0)); bank = address bit 14, in-bank index = [13:0]
                           hwrite(r0[63] ? 32'd0 : r0[31:0], r1);
                           if (r0 >= hp) hp <= r0 + 64'sd1;
                         end
                         if (cc_kind==32'd5) hp <= hp + r0;
                         ci_set(ci + 16'd1);
                         if (CFG_BRAM) st <= ST_CF;   // one cycle for cc_*_r to catch the advanced ci before st0 recomputes
                       end
                       end   // close the CFG_BRAM=0 (else) branch of st==0
                     end else begin
                       // Cells done → enter the write phase. CFG_BRAM=0: snapshot the block-entry register file
                       // into file0 (cells wrote only v[]/heap, never file), then st1 reads it via resolve0 for
                       // ATOMIC writes. CFG_BRAM=1: `file0` is dead — `file` STILL holds block-entry values here
                       // (cells never write it), so the write READ pass (ST_WF→ST_WR→ST_WRW) reads write sources
                       // out of block-entry `file`/`v` through the registered ports into `wbuf`, the terminator
                       // read (ST_TR/ST_TRW) buffers the branch-cond/return-value from the SAME block-entry file,
                       // and ONLY THEN the APPLY pass (ST_WA) commits `file[wbuf_tgt] <= wbuf_val` — so writes are
                       // atomic (read-before-write) with no full-file snapshot copy.
                       if (CFG_BRAM) begin wi <= 16'd0; wk <= 16'd0; st <= ST_WF; end
                       else begin
                         for (j = 0; j < NREG; j = j + 1) file0[j] <= {file_hi[j], file_lo[j]};
                         wi <= 16'd0; st <= 3'd1;
                       end
                     end
                   end
                   3'd1: begin
                     // CFG_BRAM=0 combinational atomic-write phase (unchanged). CFG_BRAM=1 never reaches st==1 —
                     // its write phase runs through ST_WF→ST_WR→ST_WRW (read pass) + ST_WA (apply pass) instead.
                     if (wi < c_nwr[15:0]) begin
                       wtgt = w_reg[15:0];
                       splitw = resolve0(w_op, c_livptr);   // read block-entry snapshot (atomic writes)
                       file_lo[wtgt] <= splitw[31:0];
                       file_hi[wtgt] <= splitw[63:32];
                       wi <= wi + 16'd1;
                     end else st <= 3'd2;
                   end
                   3'd2: begin
                     // Terminator decision. CFG_BRAM=0 reads the branch-cond/return-value combinationally via
                     // resolve0 (file0 = block-entry snapshot). CFG_BRAM=1 has ALREADY buffered that operand into
                     // `retval` during ST_TR/ST_TRW (from block-entry `file`, before ST_WA clobbered it), so it
                     // just uses `retval` here — and its writes were applied by ST_WA, so `file` is now post-write
                     // for the frame save (st3), matching the CFG_BRAM=0 ordering exactly.
                     ci_set(16'd0);
                     case (c_tk)
                       32'd0: begin pc <= c_t0[15:0]; st <= CFG_BRAM ? ST_BF : 5'd0; end
                       32'd1: begin
                         if (CFG_BRAM) begin pc <= (retval != 64'sd0) ? c_t0[15:0] : c_t1[15:0]; st <= ST_BF; end
                         else begin pc <= (resolve0(c_top, c_livptr) != 64'sd0) ? c_t0[15:0] : c_t1[15:0]; st <= 5'd0; end
                       end
                       32'd2: begin
                         if (CFG_BRAM) begin
                           if (sp == 16'd0) begin result_r <= retval; done_r <= 1'b1; end
                           else begin gi <= 16'd0; st <= 3'd5; end   // retval already buffered by ST_TRW
                         end else begin
                           if (sp == 16'd0) begin result_r <= resolve0(c_top, c_livptr); done_r <= 1'b1; end
                           else begin retval <= resolve0(c_top, c_livptr); gi <= 16'd0; st <= 3'd5; end
                         end
                       end
                       default: begin gi <= 16'd0; st <= 3'd3; end
                     endcase
                   end
                   3'd3: begin
                     // Frame save: copy the (post-write) register file to the block-RAM frame stack. CFG_BRAM=0
                     // reads `file[gi]` combinationally; CFG_BRAM=1 issues the file BRAM read (file_ra<=gi) and
                     // commits `sfile[..] <= file_rd` one cycle later in ST_FSW.
                     if (gi < NREG) begin
                       if (CFG_BRAM) begin file_ra <= gi; st <= ST_FSD; end
                       else begin sfwrite(sp*NREG + gi, {file_hi[gi], file_lo[gi]}); gi <= gi + 16'd1; end
                     end else if (sp + 16'd1 > DEPTH) begin
                       // Pushing here would index past sret/sdst/sfile (slot `sp` exists only for sp < DEPTH, so the
                       // stack holds exactly DEPTH frames — the same number the model's peak_depth is checked against).
                       // Stop and REPORT rather than wrap into
                       // a wrong answer: the result frame's terminator becomes 0xE1, which every existing host
                       // already rejects as a bad end byte, so an over-deep program fails loudly everywhere.
                       sp_ovf <= 1'b1; done_r <= 1'b1;
                     end else begin sret[sp] <= c_t1[15:0]; sdst[sp] <= c_cdst[15:0]; sp <= sp + 16'd1; ai <= 16'd0; st <= 3'd4; end
                   end
                   3'd4: begin
                     // Gather call args into the callee frame. A mode-0 arg reads the CALLER's saved register out
                     // of the block-RAM frame stack (sfile) — inlined here (resolve_arg is gone) so its read goes
                     // through the registered sf_rd port. mode-1 (konst) resolves combinationally. mode-2 (v)
                     // resolves combinationally under CFG_BRAM=0, but under CFG_BRAM=1 `v` is block RAM, so it
                     // issues v_ra<=op and commits `file[ai] <= v_rd` a cycle later in ST_AGW.
                     if (ai < NREG) begin
                       if (ai < c_cargc[15:0]) begin
                         op4 = arg_op[c_cargp + ai];
                         case (op4[31:30])
                           2'd0: begin sfread((sp-16'd1)*NREG + liv_reg[c_livptr + op4[15:0]][15:0]); st <= 4'd12; end
                           2'd1: begin splitw = konst[op4[15:0]]; file_lo[ai] <= splitw[31:0]; file_hi[ai] <= splitw[63:32]; ai <= ai + 16'd1;
                           end
                           default: begin
                             if (CFG_BRAM) begin v_ra <= op4[15:0]; st <= ST_AGD; end
                             else begin file_lo[ai] <= v_lo[op4[15:0]]; file_hi[ai] <= v_hi[op4[15:0]]; ai <= ai + 16'd1; end
                           end
                         endcase
                       end else begin file_lo[ai] <= 32'd0; file_hi[ai] <= 32'd0; ai <= ai + 16'd1;
                       end
                     end else begin pc <= c_t0[15:0]; st <= CFG_BRAM ? ST_BF : 5'd0; end
                   end
                   3'd5: begin
                     // Restore the caller frame from the block-RAM stack (pipelined: st 5 issues the read address,
                     // st 10 waits the registered-read latency, st 11 commits file[gi]).
                     if (gi < NREG) begin sfread((sp-16'd1)*NREG + gi); st <= 4'd10; end
                     else begin rtgt = sdst[sp-1]; file_lo[rtgt] <= retval[31:0]; file_hi[rtgt] <= retval[63:32]; pc <= sret[sp-1]; sp <= sp - 16'd1; st <= CFG_BRAM ? ST_BF : 5'd0;
                     end
                   end
                   // sfile restore read-latency wait (st 10) + commit (st 11).
                   4'd10: st <= 4'd11;
                   4'd11: begin file_lo[gi] <= sf_rd[31:0]; file_hi[gi] <= sf_rd[63:32]; gi <= gi + 16'd1; st <= 4'd5;
                   end
                   // sfile mode-0 call-arg read-latency wait (st 12) + commit (st 13).
                   4'd12: st <= 4'd13;
                   4'd13: begin file_lo[ai] <= sf_rd[31:0]; file_hi[ai] <= sf_rd[63:32]; ai <= ai + 16'd1; st <= 4'd4;
                   end
                   3'd6: begin
                     // Sequential integer functional-unit datapath (see the dr_*/pw_* declarations): the divider takes
                     // a cycle per dividend bit and a finalize cycle (ST_DRF), Pow a multiplier trip (ST_MU..ST_MUW) per
                     // step; the unit writes v[dr_ci] and resumes the cell walk (st==0) when it finishes.
                     if (dr_code == 32'd3) begin
                       // Pow — repeat-multiply (wrapping 64-bit product), pw_cnt times.
                       if (pw_live) begin
                         mu_kind <= 2'd3;                                  // one step on the multiplier, back here after
                         pw_cnt <= ~inc64(~pw_cnt);                        // pw_cnt - 1 through the prefix increment
                         pw_live <= (pw_cnt != 64'sd1);
                         st <= ST_MU;
                       end else begin
                         v_lo[dr_ci] <= mu_a[31:0]; v_hi[dr_ci] <= mu_a[63:32]; ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0;
                       end
                     end else begin
                       // Restoring divide — bring down the next dividend bit (dr_a shifts left a bit per step, so it is
                       // always bit 63), subtract the divisor when no borrow says the remainder is smaller, and shift the
                       // quotient bit in. The last step hands the magnitudes to ST_DRF.
                       dr_new_rem = {dr_rem[62:0], dr_a[63]};
                       dr_diff = sub65(dr_new_rem, dr_x);
                       if (!dr_diff[64]) dr_new_rem = dr_diff[63:0];
                       dr_new_quo = {dr_quo[62:0], !dr_diff[64]};
                       dr_rem <= dr_new_rem; dr_quo <= dr_new_quo; dr_a <= dr_a << 1;
                       if (dr_bit == 7'd0) st <= ST_DRF;
                       else dr_bit <= dr_bit - 7'd1;
                     end
                   end
                   ST_DRF: begin
                     // Re-sign the magnitude result to match the VM: -v is inc64(~v), and a negative floor quotient
                     // with a remainder is -q - 1 = ~q.
                     case (dr_code)
                       32'd0: dr_res = dr_neg_q ? inc64(~dr_quo) : dr_quo;                                      // Div
                       32'd1: dr_res = dr_neg_a ? inc64(~dr_rem) : dr_rem;                                      // Mod
                       default: dr_res = dr_neg_q ? ((dr_rem != 64'd0) ? ~dr_quo : inc64(~dr_quo)) : dr_quo;   // FloorDiv
                     endcase
                     v_lo[dr_ci] <= dr_res[31:0]; v_hi[dr_ci] <= dr_res[63:32]; ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0;
                   end
                   ST_MU:  st <= ST_MU2;
                   ST_MU2: st <= ST_MU3;
                   ST_MU3: begin
                     mu_p <= mu_tree_p;
                     mu_corr <= mu_corr_w;
                     st <= ST_MUW;
                   end
                   ST_MUW: begin
                     if (mu_kind == 2'd3) begin
                       mu_a <= mu_prod[63:0]; st <= 3'd6;       // a Pow step: back to its loop
                     end else begin
                       // MulOvfS: the signed product overflows i64 when its high word is not the low word's sign:
                       // {hi, sign} neither all ones nor all zeros.
                       mu_hi = mu_prod[127:64] - mu_corr_r;
                       cellval = (mu_kind == 2'd0) ? mu_prod[63:0] :
                                 (mu_kind == 2'd1) ? mu_prod[127:64] :
                                 (((&{mu_hi, mu_prod[63]}) || !(|{mu_hi, mu_prod[63]})) ? 64'sd0 : 64'sd1);
                       v_lo[dr_ci] <= cellval[31:0]; v_hi[dr_ci] <= cellval[63:32]; ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0;
                     end
                   end
                   3'd7: begin
                     // FLOAT functional-unit stall. Clear the 1-cycle start pulses (the FPU sampled them last
                     // edge). fp_sel==4 = a combinational op (compare/popcount) on the registered operands (fav/fbv):
                     // its result registers in cl_y on the first cycle and the second writes it, so neither the
                     // compare nor the count shares a cycle with the register-file write; otherwise wait for the
                     // unit's done.
                     fas_start <= 1'b0; fmul_start <= 1'b0; fdiv_start <= 1'b0; fsqrt_start <= 1'b0; fconv_start <= 1'b0;
                     if (fp_sel == 3'd4) begin
                       if (!cl_ready) begin
                         case (dr_code)
                           32'd14:  cl_y <= {6'd0, fp_lt};            // FLt   a<b
                           32'd15:  cl_y <= {6'd0, fp_lt};            // FGt   (operands swapped -> b<a)
                           32'd16:  cl_y <= {6'd0, fp_lt | fp_eq};    // FLe
                           32'd17:  cl_y <= {6'd0, fp_lt | fp_eq};    // FGe   (swapped)
                           32'd18:  cl_y <= {6'd0, fp_eq};            // FEq
                           32'd19:  cl_y <= {6'd0, ~fp_eq};           // FNe   (NaN: fp_eq=0 -> 1, matches Rust)
                           32'd20:  cl_y <= $countones(fav);          // PopCount
                           default: cl_y <= 7'd0;                     // ApproxEqF(11) deferred (fit rejects it)
                         endcase
                         cl_ready <= 1'b1;
                       end else begin
                         v_lo[dr_ci] <= {25'd0, cl_y}; v_hi[dr_ci] <= 32'd0; cl_ready <= 1'b0;
                         ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0;
                       end
                     end else begin
                       case (fp_sel)
                         3'd0: if (fp_as_done   && !fas_start)   begin v_lo[dr_ci] <= fp_as_y[31:0];   v_hi[dr_ci] <= fp_as_y[63:32];   ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0; end
                         3'd1: if (fp_mul_done  && !fmul_start)  begin v_lo[dr_ci] <= fp_mul_y[31:0];  v_hi[dr_ci] <= fp_mul_y[63:32];  ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0; end
                         3'd2: if (fp_div_done  && !fdiv_start)  begin v_lo[dr_ci] <= fp_div_y[31:0];  v_hi[dr_ci] <= fp_div_y[63:32];  ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0; end
                         3'd3: if (fp_sqrt_done && !fsqrt_start) begin v_lo[dr_ci] <= fp_sqrt_y[31:0]; v_hi[dr_ci] <= fp_sqrt_y[63:32]; ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0; end
                         3'd5: if (fp_conv_done && !fconv_start) begin v_lo[dr_ci] <= fp_conv_y[31:0]; v_hi[dr_ci] <= fp_conv_y[63:32]; ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0; end
                         default: st <= CFG_BRAM ? ST_CF : 5'd0;
                       endcase
                     end
                   end
                   // HeapRead block-RAM read-latency wait: st 8 lets the new `heap_ra` propagate through the
                   // registered read; st 9 commits `heap_rd` (= heap[r0]) into v[ci] and resumes the cell walk.
                   4'd8: st <= 4'd9;
                   4'd9: begin v_lo[ci] <= heap_rd[31:0]; v_hi[ci] <= heap_rd[63:32]; ci_set(ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0;
                   end
                   // Deep-copy (cell kind 6): st 14 waits the length-header read; st 15 latches len (clamped ≥0);
                   // st 16 issues each element read, or when done bumps hp past the fresh block (1 header + len
                   // elements + SEQ_RESERVE=2048 headroom, matching eval) and returns the new pointer; st 17/18 are
                   // the per-element read-latency wait + write (one heap read port + one write port, no overlap).
                   5'd14: st <= 5'd15;
                   5'd15: begin dc_len <= (heap_rd < 64'sd0) ? 64'sd0 : heap_rd; dc_j <= 64'sd0; st <= 5'd16;
                   end
                   5'd16: begin
                     if (dc_j <= dc_len) begin hread(dc_src + dc_j); st <= 5'd17; end
                     else begin
                       hp <= dc_new + dc_len + 64'sd1 + 64'sd2048;
                       v_lo[dc_ci] <= dc_new[31:0]; v_hi[dc_ci] <= dc_new[63:32]; ci_set(dc_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0;
                     end
                   end
                   5'd17: st <= 5'd18;
                   5'd18: begin
                     // depth-banked deep-copy write: dc_new+dc_j is a heap pointer (always >= 0); bank = bit 14, index = [13:0]
                     splitw = dc_new + dc_j;
                     hwrite(splitw[31:0], heap_rd);
                     dc_j <= dc_j + 64'sd1; st <= 5'd16;
                   end
                   // CFG_BRAM serial operand-fetch (ST_OP issue → ST_OPW latch): resolve ONE operand per BRAM
                   // read through a SINGLE shared read port (file_ra/v_ra) instead of four PARALLEL wide operand
                   // muxes in st==0 — the density fix that lets the big 200T engine route. `file`/`v` are now
                   // BLOCK RAM (registered read), so ST_OP ISSUES the address and ST_OPW LATCHES a cycle later.
                   // r0..r3 are latched NONBLOCKING, so all four are valid the cycle AFTER opi==3's latch (the
                   // ST_CMP compute cycle). Operands reference EARLIER cells in this SAME block (already written)
                   // and register operands read the block-entry `file` (cells never write `file`) ⇒ ≡VM unchanged.
                   ST_OP: begin
                     // ISSUE the operand `opi` selects. mode 0 (register): index the file BRAM at the physical
                     // register `liv_reg[lptr+op]` (liv_reg is FF → combinational). mode 2 (v cell-ref): index the
                     // v BRAM. mode 1 (konst): latch the constant now (no BRAM read; ST_OPW passes it through).
                     op4 = (opi == 3'd0) ? cc_op0 : (opi == 3'd1) ? cc_op1 : (opi == 3'd2) ? cc_op2 : cc_op3;
                     rmode = op4[31:30];
                     case (op4[31:30])
                       2'd0: file_ra <= liv_reg[c_livptr + op4[15:0]][15:0];
                       2'd1: rk <= konst[op4[15:0]];
                       default: v_ra <= op4[15:0];
                     endcase
                     st <= ST_OPD;
                   end
                   // WAIT one cycle for the file_ra/v_ra address to propagate through the registered read.
                   ST_OPD: st <= ST_OPW;
                   // LATCH the operand fetched in ST_OP into r[opi]; then advance opi or enter ST_CMP.
                   ST_OPW: begin
                     opres = (rmode == 2'd0) ? file_rd : (rmode == 2'd1) ? rk : v_rd;
                     case (opi)
                       3'd0: r0 <= opres;
                       3'd1: r1 <= opres;
                       3'd2: r2 <= opres;
                       default: r3 <= opres;
                     endcase
                     if (opi == 3'd3) st <= ST_CMP; else begin opi <= opi + 3'd1; st <= ST_OP; end
                   end
                   // CFG_BRAM cell compute (ST_CMP): the EXACT compute block st==0 ran under CFG_BRAM=0, but r0..r3
                   // are now the pre-fetched REGISTERED operands (no inline resolve). Reached only under CFG_BRAM,
                   // so every `if (CFG_BRAM) st<=ST_CF` / `st<=CFG_BRAM?ST_CF:5'd0` resume routes back through ST_CF
                   // → st==0 → ST_OP for the next cell, exactly as the single-cycle path resumed to st==0 before.
                   ST_CMP: begin
                       if (cc_kind==32'd2 && cc_code <= 32'd3) begin
                         // A Div/Mod/FloorDiv/Pow func cell: latch operands and STALL into the sequential
                         // datapath (st==6).
                         dr_ci <= ci; dr_code <= cc_code;
                         if (cc_code == 32'd3) begin
                           // Pow: the accumulator mu_a starts at 1 and multiplies by the base mu_b = r0 for
                           // max(exponent,0) iterations.
                           mu_a <= 64'd1; mu_b <= r0; pw_cnt <= (r1 < 64'sd0) ? 64'sd0 : r1; pw_live <= (r1 > 64'sd0);
                           st <= 3'd6;
                         end else if (r1 == 64'sd0) begin
                           v_lo[ci] <= 32'd0; v_hi[ci] <= 32'd0; ci_set(ci + 16'd1);   // divide-by-zero trap → 0 (no stall, matches VM)
                           if (CFG_BRAM) st <= ST_CF;
                         end else begin
                           dr_a <= r0[63] ? (-r0) : r0;   // |dividend|  (INT_MIN negates to its own bit pattern = 2^63)
                           dr_x <= r1[63] ? (-r1) : r1;   // |divisor|
                           dr_neg_q <= r0[63] ^ r1[63];   // quotient negative iff operand signs differ
                           dr_neg_a <= r0[63];            // remainder takes the dividend's sign
                           dr_rem <= 64'd0; dr_quo <= 64'd0; dr_bit <= 7'd63;
                           st <= 3'd6;
                         end
                       end else if ((cc_kind==32'd0 && cc_code[3:0]==4'd2) || (cc_kind==32'd2 && (cc_code==32'd4 || cc_code==32'd12))) begin
                         // An integer multiply (Mul, MulHiU, MulOvfS): latch operands and STALL while the 64x64
                         // compressor tree runs (ST_MU..ST_MUW).
                         dr_ci <= ci; mu_a <= r0; mu_b <= r1;
                         mu_kind <= (cc_kind==32'd0) ? 2'd0 : (cc_code==32'd4) ? 2'd1 : 2'd2;
                         st <= ST_MU;
                       end else if (WITH_FPU && cc_kind==32'd2 && cc_code >= 32'd5 && cc_code != 32'd12) begin
                         // A FLOAT func cell (codes 5..20, ApproxEqF/11 excepted): latch operands + STALL into
                         // st==7 (the sequential FPU for add/sub/mul/div/sqrt/convert; combinational compare/pop).
                         dr_ci <= ci; dr_code <= cc_code; fav <= r0; fbv <= r1;
                         case (cc_code)
                           32'd5: begin fas_start  <= 1'b1; fsub_r <= 1'b0; fp_sel <= 3'd0; end   // FAdd
                           32'd6: begin fas_start  <= 1'b1; fsub_r <= 1'b1; fp_sel <= 3'd0; end   // FSub
                           32'd7: begin fmul_start <= 1'b1;                 fp_sel <= 3'd1; end   // FMul
                           32'd8: begin fdiv_start <= 1'b1;                 fp_sel <= 3'd2; end   // FDiv
                           32'd9: begin fsqrt_start<= 1'b1;                 fp_sel <= 3'd3; end   // FSqrt
                           32'd10, 32'd13: begin fconv_start <= 1'b1;       fp_sel <= 3'd5; end   // FFloor / IntToF
                           default:                                          fp_sel <= 3'd4;      // cmp / popcount
                         endcase
                         st <= 3'd7;
                       end else if (cc_kind==32'd3) begin
                         // HeapRead: drive the block-RAM read address, then wait out its registered-read latency
                         // (st 8 -> 9) before committing the value. Keeps ≡VM; the heap is no longer flip-flops.
                         hread(r0[63] ? 32'd0 : r0[31:0]); st <= 4'd8;   // clamp negative index to 0 (== eval a.max(0))
                       end else if (cc_kind==32'd6) begin
                         // DEEP-COPY (value semantics / COW): read the length header heap[src], copy header+elements
                         // to a fresh block at hp, return the new pointer — a multi-cycle heap-to-heap copy (st
                         // 14-18), bit-identical to eval_wprog_config kind 6. Without this the copy resolved to a
                         // bare hp pointer into cleared heap → quicksort/heap_sort read zeros (result 0).
                         dc_ci <= ci; dc_src <= r0[63] ? 64'sd0 : r0; dc_new <= hp;
                         hread(r0[63] ? 32'd0 : r0[31:0]); st <= 5'd14;
                       end else if (cc_kind==32'd7) begin
                         // TEXT CONCAT (TC_*): a fresh char-list = bytes(op0) ++ bytes(op1); code bits say which operands are Text
                         tt_ci <= ci; tt_val <= r0; tt_val2 <= r1; tt_istext <= cc_code[0]; tt_istext2 <= cc_code[1]; st <= TC_ST;
                       end else if (cc_kind==32'd8) begin
                         // TEXT CHAR-AT (CA_*): `item i of text` → a fresh 1-char Text
                         tt_ci <= ci; tt_val <= r0; tt_val2 <= r1; st <= CA_RD;
                       end else if (cc_kind==32'd9) begin
                         // TEXT EQUALITY (TE_*): byte-for-byte compare → 0/1 (code 0 = eq, 1 = ne)
                         tt_ci <= ci; tt_val <= r0; tt_val2 <= r1; tt_code <= cc_code[7:0]; st <= TE_LA;
                       end else if (cc_kind==32'd10) begin
                         // SHOW: stream a tagged record over the byte channel NOW (ST_SH..ST_SHD), then commit the value as
                         // this cell's result — the engine's output tape, ≡ eval_wprog_config_run.
                         dr_ci <= ci; sh_val <= r0; sh_tag <= cc_code[7:0]; sh_bi <= 4'd0; st <= ST_SH;
                       end else begin
                         cellval = (cc_kind==32'd0) ? alu_f(cc_code[3:0], r0, r1) :
                                   (cc_kind==32'd1) ? (cmp_f(cc_code[3:0], r0, r1) ? r2 : r3) :
                                   (cc_kind==32'd2) ? func_f(cc_code[7:0], r0, r1) :
                                   (cc_kind==32'd4) ? r1 : hp;
                         v_lo[ci] <= cellval[31:0]; v_hi[ci] <= cellval[63:32];
                         if (cc_kind==32'd4) begin   // depth-banked HeapWrite: clamp negative index to 0 (== eval a.max(0)); bank = address bit 14, in-bank index = [13:0]
                           hwrite(r0[63] ? 32'd0 : r0[31:0], r1);
                           if (r0 >= hp) hp <= r0 + 64'sd1;
                         end
                         if (cc_kind==32'd5) hp <= hp + r0;
                         ci_set(ci + 16'd1);
                         if (CFG_BRAM) st <= ST_CF;   // one cycle for cc_*_r to catch the advanced ci before st0 recomputes
                       end
                   end
                   // CFG_BRAM cell-fetch wait: burn one cycle so the registered read cc_*_r catches up to the new
                   // ci/pc before st==0 recomputes off it. Only reached under CFG_BRAM (the resume/advance sites
                   // route here instead of directly to st0); no other effect.
                   // ── SHOW record streaming (kind 10) — see the ST_SH* localparams ──
                   ST_SH:   if (!tx_busy) begin tx_data <= 8'hA7; tx_start <= 1'b1; st <= ST_SHT; end
                   ST_SHT:  if (!tx_busy) begin
                              tx_data <= sh_tag; tx_start <= 1'b1;
                              if (sh_tag == 8'd2) begin hread(sh_val[63] ? 32'd0 : sh_val[31:0]); st <= ST_SHL; end
                              else st <= ST_SHV;
                            end
                   ST_SHV:  if (!tx_busy) begin
                              tx_data <= sh_val[(7 - sh_bi) * 8 +: 8]; tx_start <= 1'b1;
                              if (sh_bi == 4'd7) st <= ST_SHD; else sh_bi <= sh_bi + 4'd1;
                            end
                   ST_SHL:  st <= ST_SHLW;
                   ST_SHLW: begin sh_len <= heap_rd[63] ? 32'd0 : heap_rd[31:0]; sh_j <= 32'd0; sh_bi <= 4'd0; st <= ST_SHLN; end
                   ST_SHLN: if (!tx_busy) begin
                              tx_data <= sh_len[(3 - sh_bi) * 8 +: 8]; tx_start <= 1'b1;
                              if (sh_bi == 4'd3) st <= ST_SHB; else sh_bi <= sh_bi + 4'd1;
                            end
                   ST_SHB:  if (sh_j < sh_len) begin hread((sh_val[63] ? 32'd0 : sh_val[31:0]) + 32'd1 + sh_j); st <= ST_SHBW; end
                            else st <= ST_SHD;
                   ST_SHBW: st <= ST_SHBS;
                   ST_SHBS: if (!tx_busy) begin tx_data <= heap_rd[7:0]; tx_start <= 1'b1; sh_j <= sh_j + 32'd1; st <= ST_SHB; end
                   ST_SHD:  begin v_lo[dr_ci] <= sh_val[31:0]; v_hi[dr_ci] <= sh_val[63:32]; ci_set(dr_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 5'd0; end
                   // ── TEXT CONCAT (kind 7) — see the TC_* localparams ──
                   TC_ST:   begin tt_new <= hp; tt_len <= 64'sd0; tt_slot <= 1'b0; st <= TC_SLOT; end
                   TC_SLOT: if (tt_curtext) begin hread(tt_ptr); st <= TC_TLW; end
                            else begin tt_neg <= tt_cur[63]; dd_bin <= tt_cur[63] ? (-tt_cur) : tt_cur; dd_bcd <= 80'd0; dd_i <= 7'd0; st <= TC_DD; end
                   TC_TLW:  st <= TC_TLEN;
                   TC_TLEN: begin tt_srclen <= (heap_rd < 64'sd0) ? 64'sd0 : heap_rd; tt_j <= 64'sd0; st <= TC_TB; end
                   TC_TB:   if (tt_j < tt_srclen) begin hread(tt_ptr + 32'd1 + tt_j[31:0]); st <= TC_TBW; end
                            else st <= TC_NEXT;
                   TC_TBW:  st <= TC_TWR;
                   TC_TWR:  begin
                     splitw = tt_new + 64'sd1 + tt_len; splitv = heap_rd;
                     hwrite(splitw[31:0], splitv);
                     tt_len <= tt_len + 64'sd1; tt_j <= tt_j + 64'sd1; st <= TC_TB;
                            end
                   TC_DD:   if (dd_i < 7'd64) begin {dd_bcd, dd_bin} <= {dd_adjust(dd_bcd), dd_bin} << 1; dd_i <= dd_i + 7'd1; end
                            else begin dd_k <= dd_digits(dd_bcd) - 5'd1; st <= TC_SIGN; end
                   TC_SIGN: if (tt_neg) begin
                     splitw = tt_new + 64'sd1 + tt_len; splitv = 64'sd45;
                     hwrite(splitw[31:0], splitv);
                     tt_len <= tt_len + 64'sd1; st <= TC_DIG;
                            end else st <= TC_DIG;
                   TC_DIG:  begin
                     splitw = tt_new + 64'sd1 + tt_len; splitv = {56'd0, 8'd48 + {4'd0, dd_bcd[dd_k*4 +: 4]}};
                     hwrite(splitw[31:0], splitv);
                     tt_len <= tt_len + 64'sd1;
                     if (dd_k == 5'd0) st <= TC_NEXT; else dd_k <= dd_k - 5'd1;
                            end
                   TC_NEXT: if (!tt_slot) begin tt_slot <= 1'b1; st <= TC_SLOT; end else st <= TC_FIN;
                   TC_FIN:  begin
                     splitw = tt_new; splitv = tt_len;
                     hwrite(splitw[31:0], splitv);
                     hp <= tt_new + 64'sd1 + tt_len;
                     v_lo[tt_ci] <= tt_new[31:0]; v_hi[tt_ci] <= tt_new[63:32]; ci_set(tt_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 7'd0;
                            end
                   // ── TEXT CHAR-AT (kind 8) ──
                   CA_RD:   begin hread((tt_val[63] ? 32'd0 : tt_val[31:0]) + (tt_val2[63] ? 32'd0 : tt_val2[31:0])); tt_new <= hp; st <= CA_RDW; end
                   CA_RDW:  st <= CA_HDR;
                   CA_HDR:  begin tt_val2 <= heap_rd;
                     splitw = tt_new; splitv = 64'sd1;
                     hwrite(splitw[31:0], splitv);
                     st <= CA_BYTE;
                            end
                   CA_BYTE: begin
                     splitw = tt_new + 64'sd1; splitv = tt_val2;
                     hwrite(splitw[31:0], splitv);
                     hp <= tt_new + 64'sd2;
                     v_lo[tt_ci] <= tt_new[31:0]; v_hi[tt_ci] <= tt_new[63:32]; ci_set(tt_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 7'd0;
                            end
                   // ── TEXT EQUALITY (kind 9) ──
                   TE_LA:   begin hread(tt_val[63] ? 32'd0 : tt_val[31:0]); st <= TE_LAW; end
                   TE_LAW:  st <= TE_LB;
                   TE_LB:   begin tt_srclen <= heap_rd; hread(tt_val2[63] ? 32'd0 : tt_val2[31:0]); st <= TE_LBW; end
                   TE_LBW:  st <= TE_LEN;
                   TE_LEN:  if (heap_rd != tt_srclen) begin tt_len <= 64'sd0; st <= TE_FIN; end
                            else begin tt_j <= 64'sd0; st <= TE_A; end
                   TE_A:    if (tt_j < tt_srclen) begin hread((tt_val[63] ? 32'd0 : tt_val[31:0]) + 32'd1 + tt_j[31:0]); st <= TE_AW; end
                            else begin tt_len <= 64'sd1; st <= TE_FIN; end
                   TE_AW:   st <= TE_B;
                   TE_B:    begin tt_new <= heap_rd; hread((tt_val2[63] ? 32'd0 : tt_val2[31:0]) + 32'd1 + tt_j[31:0]); st <= TE_BW; end
                   TE_BW:   st <= TE_CMP;
                   TE_CMP:  if (heap_rd != tt_new) begin tt_len <= 64'sd0; st <= TE_FIN; end
                            else begin tt_j <= tt_j + 64'sd1; st <= TE_A; end
                   TE_FIN:  begin
                     splitv = (tt_code == 8'd0) ? tt_len : (tt_len ^ 64'sd1);
                     v_lo[tt_ci] <= splitv[31:0]; v_hi[tt_ci] <= splitv[63:32]; ci_set(tt_ci + 16'd1); st <= CFG_BRAM ? ST_CF : 7'd0;
                            end
                   ST_CF: st <= 5'd0;
                   // CFG_BRAM write-fetch wait: burn one cycle so the registered read wr_*_r catches up to the new
                   // wi (or pc, on write-phase entry) before ST_WR reads w_reg/w_op. Only reached under CFG_BRAM
                   // (write-phase entry + each wi advance route here); its predecessor st==1 is CFG_BRAM=0 only.
                   // This whole write/terminator/frame BRAM-read block (ST_WF…ST_AGW) is EXCISED from the
                   // CFG_BRAM=0 netlist (unreachable there) so the flip-flop backends synth fast + unchanged.
                   ST_WF: st <= ST_WR;
                   // ── CFG_BRAM=1 WRITE READ pass: buffer every write's SOURCE value out of the block-entry
                   //    register file/v into `wbuf` BEFORE any write is applied (read-before-write atomicity). ──
                   ST_WR: begin
                     if (wi < c_nwr[15:0]) begin
                       // Issue the BRAM read for write[wi]'s source operand (w_op). mode 0 = a register (index the
                       // file BRAM at the physical register liv_reg[..]); mode 2 = a v cell-ref; mode 1 = a konst.
                       rmode = w_op[31:30];
                       case (w_op[31:30])
                         2'd0: file_ra <= liv_reg[c_livptr + w_op[15:0]][15:0];
                         2'd1: rk <= konst[w_op[15:0]];
                         default: v_ra <= w_op[15:0];
                       endcase
                       st <= ST_WRD;
                     end else begin
                       // All write sources buffered — now read the TERMINATOR operand from the STILL block-entry
                       // `file` (before ST_WA clobbers it), matching resolve0 in the CFG_BRAM=0 path.
                       st <= ST_TR;
                     end
                   end
                   // WAIT one cycle for the write-source address to propagate through the registered read.
                   ST_WRD: st <= ST_WRW;
                   // WRITE READ pass LATCH: the write source is valid now → buffer (target register, value). The
                   // target `w_reg` is stable (wr_*_r held wi across ST_WF/ST_WR/ST_WRD/ST_WRW). Advance wi,
                   // re-settle wr_*_r via ST_WF. `wbuf` is indexed by wi (≤ NREG: fabric write_order dedupes).
                   ST_WRW: begin
                     wbuf_tgt[wi] <= w_reg[15:0];
                     wbuf_val[wi] <= (rmode == 2'd0) ? file_rd : (rmode == 2'd1) ? rk : v_rd;
                     wi <= wi + 16'd1; st <= ST_WF;
                   end
                   // ── CFG_BRAM=1 TERMINATOR READ: buffer the branch-cond / return-value from block-entry `file`
                   //    (before ST_WA applies the writes) into `retval`, so st==2 decides on the block-entry state
                   //    exactly as resolve0 (file0) does under CFG_BRAM=0. Jump/Call read no operand here. ──
                   ST_TR: begin
                     case (c_tk)
                       32'd1, 32'd2: begin   // Branch (cond) or Return (value): read c_top from block-entry file/v
                         rmode = c_top[31:30];
                         case (c_top[31:30])
                           2'd0: file_ra <= liv_reg[c_livptr + c_top[15:0]][15:0];
                           2'd1: rk <= konst[c_top[15:0]];
                           default: v_ra <= c_top[15:0];
                         endcase
                         st <= ST_TRD;
                       end
                       default: st <= ST_WA;   // Jump (0) / Call (default): no terminator operand read
                     endcase
                   end
                   // WAIT one cycle for the terminator-operand address to propagate through the registered read.
                   ST_TRD: st <= ST_TRW;
                   // TERMINATOR READ LATCH: the branch-cond / return-value is valid now → buffer into `retval`,
                   // then run the write APPLY pass (ST_WA). st==2 consumes `retval`.
                   ST_TRW: begin
                     retval <= (rmode == 2'd0) ? file_rd : (rmode == 2'd1) ? rk : v_rd;
                     st <= ST_WA;
                   end
                   // ── CFG_BRAM=1 WRITE APPLY pass: commit every buffered write as a PURE BRAM write (no
                   //    interleaved reads), preserving the atomic within-block write semantics. → st==2. ──
                   ST_WA: begin
                     if (wk < c_nwr[15:0]) begin
                       wtgt = wbuf_tgt[wk]; splitw = wbuf_val[wk];
                       file_lo[wtgt] <= splitw[31:0];
                       file_hi[wtgt] <= splitw[63:32];
                       wk <= wk + 16'd1;
                     end else st <= 3'd2;
                   end
                   // FRAME-SAVE (st3) WAIT one cycle for file_ra=gi to propagate through the registered read.
                   ST_FSD: st <= ST_FSW;
                   // FRAME-SAVE (st3) LATCH: file_rd = file[gi] (post-write) is valid now → store into the frame
                   // stack and advance gi; st3 issues the next gi's read.
                   ST_FSW: begin sfwrite(sp*NREG + gi, file_rd); gi <= gi + 16'd1; st <= 3'd3;
                   end
                   // CALL-ARG gather (st4) mode-2 WAIT one cycle for v_ra=op to propagate through the registered read.
                   ST_AGD: st <= ST_AGW;
                   // CALL-ARG gather (st4) mode-2 LATCH: v_rd = v[op] is valid now → seed the callee register and
                   // advance ai; st4 issues the next arg.
                   ST_AGW: begin file_lo[ai] <= v_rd[31:0]; file_hi[ai] <= v_rd[63:32]; ai <= ai + 16'd1; st <= 3'd4;
                   end
                   // CFG_BRAM block-fetch wait: after a pc change (jump/branch/call/return) burn one cycle so the
                   // registered blk_*_r catch the new pc, THEN fall through ST_CF so cc_*_r catches the new
                   // c_cellptr — two settle cycles total before st==0 recomputes off the new block. Only reached
                   // under CFG_BRAM (the pc-change sites route here); no other effect.
                   ST_BF: st <= ST_CF;
                 endcase
               end else ph <= P_SEND;
        P_SEND: if (!tx_busy) begin
                  case (send_ph)
                    4'd0:  begin tx_data<=8'hA5;                 tx_start<=1'b1; send_ph<=4'd1;  end
                    4'd1:  begin tx_data<=result_r[63:56];       tx_start<=1'b1; send_ph<=4'd2;  end
                    4'd2:  begin tx_data<=result_r[55:48];       tx_start<=1'b1; send_ph<=4'd3;  end
                    4'd3:  begin tx_data<=result_r[47:40];       tx_start<=1'b1; send_ph<=4'd4;  end
                    4'd4:  begin tx_data<=result_r[39:32];       tx_start<=1'b1; send_ph<=4'd5;  end
                    4'd5:  begin tx_data<=result_r[31:24];       tx_start<=1'b1; send_ph<=4'd6;  end
                    4'd6:  begin tx_data<=result_r[23:16];       tx_start<=1'b1; send_ph<=4'd7;  end
                    4'd7:  begin tx_data<=result_r[15:8];        tx_start<=1'b1; send_ph<=4'd8;  end
                    4'd8:  begin tx_data<=result_r[7:0];         tx_start<=1'b1; send_ph<=4'd9;  end
                    4'd9:  begin tx_data<=run_cycles[31:24];     tx_start<=1'b1; send_ph<=4'd10; end
                    4'd10: begin tx_data<=run_cycles[23:16];     tx_start<=1'b1; send_ph<=4'd11; end
                    4'd11: begin tx_data<=run_cycles[15:8];      tx_start<=1'b1; send_ph<=4'd12; end
                    4'd12: begin tx_data<=run_cycles[7:0];       tx_start<=1'b1; send_ph<=4'd13; end
                    4'd13: begin tx_data<= sp_ovf ? 8'hE1 : heap_ovf ? 8'hE2 : 8'h5A; tx_start<=1'b1;
                             // loop back for the NEXT program over the wire (stale config tail is never indexed)
                             ph<=P_CNT; mi<=6'd0; cnt<=16'd0; entry<=16'd0; bcnt<=2'd0; bidx<=4'd0;
                             np<=16'd0; pentry<=16'd0; send_ph<=4'd0; done_r<=1'b0; sp_ovf<=1'b0; heap_ovf<=1'b0; end
                    default: ;
                  endcase
                end
        P_DONE: ;
      endcase
    end
  end
endmodule
// fpu.v — a synthesizable IEEE-754 double-precision (binary64 / f64) floating-point unit,
// proven BIT-EXACT to Rust `f64` in iverilog (tb_fpu_*.v, generated FROM Rust f64 vectors).
//
// The four float benchmarks (nbody, mandelbrot, spectral_norm, pi_leibniz) need f64: a constant
// like 9.54791938424326609 has 17 significant figures and only survives in binary64. Every op here
// is round-to-nearest-ties-to-even with correct ±0 / ±Inf / quiet-NaN / subnormal handling, matching
// Rust's `f64` operator semantics exactly (Rust uses the platform's IEEE-754 hardware, which is what
// we reproduce here). NO `real` / `$bitstoreal` appears in this module — those are testbench-only;
// this DUT is pure synthesizable logic. div/sqrt are multi-cycle digit-recurrence; add/sub/mul/convert
// are ALSO multi-cycle (an FSM registers each stage) — a start/done handshake, correctly rounded. No
// stage holds more than one carry chain, barrel shift, leading-one search or multiplier: carries are
// parallel-prefix, leading-one searches halve their word level by level, stickies test the shifted-out
// bits with no (1 << s) - 1 mask. Every register boundary is between IDENTICAL arithmetic expressions,
// so the RESULT stays bit-for-bit what the combinational form produced.
//
// Interface — a single fpu module selects the op by a 3-bit code:
//   OP_ADD=0 OP_SUB=1 OP_MUL=2 OP_DIV=3 OP_SQRT=4 OP_LT=5 OP_EQ=6
// Arithmetic ops (add/sub/mul/div/sqrt) run a bounded FSM: `start` pulses to issue, `done` rises when
// `y` is valid. Comparisons (lt/eq) stay combinational (no shifters). For comparisons the numeric
// result low bit is the boolean; `result[0]` and `cmp` both carry it.

// ─────────────────────────────────────────────────────────────────────────────────────────────────
// fp_addsub — multi-cycle IEEE-754 binary64 add/sub, round-to-nearest-ties-even. start/done handshake.
//   sub=0 -> a+b ; sub=1 -> a-b  (a - b == a + (-b), so we just flip b's sign)
// The datapath is the SAME as the classic single-cycle form, split across the FSM below so each wide
// shifter, the 128-bit add, the leading-one search and the rounding increment is its own small cone instead
// of one 128-bit-wide nest. Bit-exact to the combinational reference.
// ─────────────────────────────────────────────────────────────────────────────────────────────────
module fp_addsub(
  input         clk,
  input         rst,
  input         start,
  input  [63:0] a,
  input  [63:0] b_in,
  input         sub,      // 0: add, 1: subtract
  output reg [63:0] y,
  output reg    done
);
  localparam [63:0] QNAN = 64'h7FF8000000000000;

  // One cone per state, none holding more than one carry chain, barrel shift or leading-one search:
  // DECODE (specials, the magnitude compare), ALIGN (the smaller operand's shift and its sticky), ADD (the 128-bit
  // add or subtract), LZC (the leading one), NORM (the normalizing shift and its sticky), ROUND (round to nearest
  // even and pack a normal result), and for a subnormal result SUBN (canonicalize), SUBR (denormalize) and SUBP
  // (round and pack).
  reg  [3:0] state;
  localparam IDLE = 4'd0, DECODE = 4'd1, ALIGN = 4'd2, ADD = 4'd3, LZC = 4'd4, NORM = 4'd5, ROUND = 4'd6,
             SUBN = 4'd7, SUBR = 4'd8, SUBP = 4'd9;

  // latched inputs (captured at issue; the shared operand ports fav/fbv stay stable while we stall)
  reg  [63:0] a_l, b_l;

  // flip the sign of the second operand for subtraction
  wire [63:0] b = sub ? {~b_l[63], b_l[62:0]} : b_l;

  wire        sa = a_l[63], sb = b[63];
  wire [10:0] ea = a_l[62:52], eb = b[62:52];
  wire [51:0] ma = a_l[51:0],  mb = b[51:0];

  wire a_is_zero  = (ea == 11'd0)    && (ma == 52'd0);
  wire b_is_zero  = (eb == 11'd0)    && (mb == 52'd0);
  wire a_is_inf   = (ea == 11'h7FF)  && (ma == 52'd0);
  wire b_is_inf   = (eb == 11'h7FF)  && (mb == 52'd0);
  wire a_is_nan   = (ea == 11'h7FF)  && (ma != 52'd0);
  wire b_is_nan   = (eb == 11'h7FF)  && (mb != 52'd0);
  wire a_is_sub   = (ea == 11'd0)    && (ma != 52'd0);  // subnormal (nonzero, exp field 0)
  wire b_is_sub   = (eb == 11'd0)    && (mb != 52'd0);

  // effective (unbiased-friendly) exponent: subnormals use exp=1, hidden bit 0; normals hidden bit 1
  wire [11:0] xa = a_is_sub ? 12'd1 : {1'b0, ea};
  wire [11:0] xb = b_is_sub ? 12'd1 : {1'b0, eb};
  wire        ha = (ea != 11'd0);
  wire        hb = (eb != 11'd0);
  wire [52:0] siga = {ha, ma};
  wire [52:0] sigb = {hb, mb};

  reg  [11:0] exp_l;        // exponent of the larger-magnitude operand
  reg  [52:0] sig_big, sig_small;
  reg         sgn_big, sgn_small;
  reg  [11:0] shamt;
  reg  [127:0] small_ext;   // the smaller operand aligned, its sticky folded into bit 0
  reg  [127:0] sum_ext;     // the exact aligned sum
  reg          res_sign;
  reg          op_is_sub;
  reg  [11:0] norm_exp;
  reg  [11:0] lead;         // position of the leading 1
  reg  [127:0] norm_sig_r;  // leading 1 at bit 55: [55:3] the significand, [2:0] guard/round/sticky
  reg  [11:0] rexp_r;       // the rounded exponent, for a subnormal result

  // A word's bits below `s`, as one flag: the bits shifted to the top and tested, so no (1 << s) - 1 mask and no
  // borrow chain. Zero when s is zero.
  function below(input [127:0] x, input [11:0] s);
    begin
      below = (s == 12'd0) ? 1'b0 : ((x << (12'd128 - s)) != 128'd0);
    end
  endfunction

  // The highest set bit of a nonzero 128-bit word, by halving: seven levels, not a 128-long priority chain.
  function [11:0] lead_one(input [127:0] x);
    reg [63:0] h6; reg [31:0] h5; reg [15:0] h4; reg [7:0] h3; reg [3:0] h2; reg [1:0] h1; reg [6:0] z;
    begin
      z[6] = ~|x[127:64]; h6 = z[6] ? x[63:0]   : x[127:64];
      z[5] = ~|h6[63:32]; h5 = z[5] ? h6[31:0]  : h6[63:32];
      z[4] = ~|h5[31:16]; h4 = z[4] ? h5[15:0]  : h5[31:16];
      z[3] = ~|h4[15:8];  h3 = z[3] ? h4[7:0]   : h4[15:8];
      z[2] = ~|h3[7:4];   h2 = z[2] ? h3[3:0]   : h3[7:4];
      z[1] = ~|h2[3:2];   h1 = z[1] ? h2[1:0]   : h2[3:2];
      z[0] = ~h1[1];
      lead_one = {5'd0, ~z};
    end
  endfunction

  // a ± b over 128 bits as a Kogge-Stone prefix add, the subtract's +1 entering as bit 0's carry.
  function [127:0] addsub128(input [127:0] x, input [127:0] yy, input s);
    reg [127:0] yb, g, p, p0; integer d;
    begin
      yb = s ? ~yy : yy;
      p0 = x ^ yb;
      g = (x & yb) | (p0 & {127'd0, s});
      p = p0;
      for (d = 1; d < 128; d = d * 2) begin
        g = g | (p & (g << d));
        p = p & (p << d);
      end
      addsub128 = p0 ^ {g[126:0], s};
    end
  endfunction

  // v + cin through a parallel-prefix AND: log2(64) levels. cin is the scan's bit 0, so bit i flips on cin and
  // every bit below it, and cin reaches the bits through the scan's tree rather than one net to all 64.
  function [63:0] inc64(input [63:0] v, input cin);
    reg [63:0] p; integer d;
    begin
      p = {v[62:0], cin};
      for (d = 1; d < 64; d = d * 2) p = p & ((p << d) | ((64'd1 << d) - 64'd1));
      inc64 = v ^ p;
    end
  endfunction

  integer i;
  reg [127:0] big_ext, small_w, norm_sig, win;
  reg [63:0] rounded, rr;
  reg [52:0] final_sig;
  reg [11:0] rexp, final_exp, shr, rshift;
  reg guard, roundb, sticky, lsb, round_up, g2, r2, s2, l2, up2;

  initial begin state = IDLE; done = 1'b0; y = 64'd0; end

  always @(posedge clk) begin
    if (rst) begin state <= IDLE; done <= 1'b0; y <= 64'd0; end
    else case (state)
      IDLE: if (start) begin
        done <= 1'b0; a_l <= a; b_l <= b_in; state <= DECODE;
      end
      DECODE: begin
        if (a_is_nan || b_is_nan) begin
          y <= QNAN; done <= 1'b1; state <= IDLE;
        end
        else if (a_is_inf && b_is_inf) begin
          if (sa == sb) y <= {sa, 11'h7FF, 52'd0}; else y <= QNAN;
          done <= 1'b1; state <= IDLE;
        end
        else if (a_is_inf) begin y <= {sa, 11'h7FF, 52'd0}; done <= 1'b1; state <= IDLE; end
        else if (b_is_inf) begin y <= {sb, 11'h7FF, 52'd0}; done <= 1'b1; state <= IDLE; end
        else if (a_is_zero && b_is_zero) begin
          if (sa == sb) y <= {sa, 63'd0}; else y <= 64'd0;
          done <= 1'b1; state <= IDLE;
        end
        else if (a_is_zero) begin y <= b; done <= 1'b1; state <= IDLE; end
        else if (b_is_zero) begin y <= a_l; done <= 1'b1; state <= IDLE; end
        else begin
          if (xa > xb || (xa == xb && siga >= sigb)) begin
            exp_l     <= xa;
            sig_big   <= siga;   sgn_big   <= sa;
            sig_small <= sigb;   sgn_small <= sb;
            shamt     <= xa - xb;
          end else begin
            exp_l     <= xb;
            sig_big   <= sigb;   sgn_big   <= sb;
            sig_small <= siga;   sgn_small <= sa;
            shamt     <= xb - xa;
          end
          state <= ALIGN;
        end
      end
      ALIGN: begin
        // The small operand, its LSB at bit 64, shifted right by shamt in a 128-bit lane; with 64 bits of room a
        // shift up to 64 keeps every bit, and what falls off folds into a sticky bit 0.
        small_w = {11'd0, sig_small, 64'd0};
        if (shamt >= 12'd128) begin
          small_ext <= {127'd0, |sig_small};
        end else begin
          small_ext <= (small_w >> shamt) | {127'd0, below(small_w, shamt)};
        end
        op_is_sub <= (sgn_big != sgn_small);
        res_sign  <= sgn_big;
        state <= ADD;
      end
      ADD: begin
        big_ext = {11'd0, sig_big, 64'd0};
        sum_ext <= addsub128(big_ext, small_ext, op_is_sub);
        state <= LZC;
      end
      LZC: begin
        if (sum_ext == 128'd0) begin
          y <= 64'd0; done <= 1'b1; state <= IDLE;      // exact cancellation -> +0 (RNE)
        end else begin
          lead  <= lead_one(sum_ext);
          state <= NORM;
        end
      end
      NORM: begin
        norm_exp <= exp_l + lead - 12'd116;              // biased exponent of the leading 1
        if (lead >= 12'd55)
          norm_sig_r <= (sum_ext >> (lead - 12'd55)) | {127'd0, below(sum_ext, lead - 12'd55)};
        else
          norm_sig_r <= sum_ext << (12'd55 - lead);
        state <= ROUND;
      end
      ROUND: begin
        norm_sig = norm_sig_r;
        guard  = norm_sig[2];
        roundb = norm_sig[1];
        sticky = norm_sig[0];
        lsb    = norm_sig[3];
        round_up = guard & (roundb | sticky | lsb);
        rounded = inc64({11'd0, norm_sig[55:3]}, round_up);
        rexp = norm_exp;
        if (rounded[53]) begin
          final_sig = rounded[53:1];
          rexp      = rexp + 12'd1;
        end else begin
          final_sig = rounded[52:0];
        end
        if ($signed(rexp) >= 12'sd2047) begin
          y <= {res_sign, 11'h7FF, 52'd0};              // overflow -> inf
          done <= 1'b1; state <= IDLE;
        end else if ($signed(rexp) <= 12'sd0) begin
          rexp_r <= rexp;
          state <= SUBN;                                // a subnormal result rounds from the exact sum
        end else begin
          final_exp = rexp;
          y <= {res_sign, final_exp[10:0], final_sig[51:0]};
          done <= 1'b1; state <= IDLE;
        end
      end
      SUBN: begin
        // The exact sum canonicalized so its leading 1 sits at bit 55, bits below the window folded into sticky.
        // The canonical window goes to norm_sig_r, free once ROUND has read it.
        if (lead >= 12'd55) begin
          shr = lead - 12'd55;
          norm_sig_r <= (sum_ext >> shr) | {127'd0, below(sum_ext, shr)};
        end else begin
          norm_sig_r <= sum_ext << (12'd55 - lead);
        end
        state <= SUBR;
      end
      SUBR: begin
        // Shift the window right by 1 - exponent, folding the discarded bits into sticky.
        // The denormalized window goes to sum_ext, free once SUBN has read it.
        rshift = 12'd1 - rexp_r;
        if (rshift >= 12'd128)
          sum_ext <= {127'd0, |norm_sig_r};
        else if (rshift != 12'd0)
          sum_ext <= (norm_sig_r >> rshift) | {127'd0, below(norm_sig_r, rshift)};
        else
          sum_ext <= norm_sig_r;
        state <= SUBP;
      end
      SUBP: begin
        win = sum_ext;
        g2 = win[2]; r2 = win[1]; s2 = win[0]; l2 = win[3];
        up2 = g2 & (r2 | s2 | l2);
        rr = inc64({11'd0, win[55:3]}, up2);
        if (rr[52]) y <= {res_sign, 11'd1, rr[51:0]};
        else        y <= {res_sign, 11'd0, rr[51:0]};
        done <= 1'b1; state <= IDLE;
      end
      default: state <= IDLE;
    endcase
  end
endmodule

// ─────────────────────────────────────────────────────────────────────────────────────────────────
// fp_mul — multi-cycle IEEE-754 binary64 multiply, round-to-nearest-ties-even. start/done handshake.
// Same datapath as the single-cycle form, split across the FSM (DECODE: specials + leading-zero counts;
// PRENORM: the pre-normalizing shifts; MUL and MUL2: the 53×53 product's compressor tree (fp_csa_mul), its first
// four levels and then the rest; PRODUCT: its final add + top-bit normalize; ROUND: normal RNE round + pack, or the
// subnormal grid shift; SUBP: the subnormal round + pack). Bit-exact to the combinational reference.
// ─────────────────────────────────────────────────────────────────────────────────────────────────
module fp_mul(
  input         clk,
  input         rst,
  input         start,
  input  [63:0] a,
  input  [63:0] b,
  output reg [63:0] y,
  output reg    done
);
  localparam [63:0] QNAN = 64'h7FF8000000000000;
  parameter integer MUL_TREE = 0;   // 1: the significand product as a compressor tree (an ASIC build)

  reg  [3:0] state;
  localparam IDLE = 4'd0, DECODE = 4'd1, MUL = 4'd2, ROUND = 4'd3, PRENORM = 4'd4, PRODUCT = 4'd5, SUBP = 4'd6,
             MUL2 = 4'd7;

  // latched inputs (captured at issue; the shared operand ports stay stable while we stall)
  reg  [63:0] a_l, b_l;

  wire        sa = a_l[63], sb = b_l[63];
  wire [10:0] ea = a_l[62:52], eb = b_l[62:52];
  wire [51:0] ma = a_l[51:0],  mb = b_l[51:0];
  wire        rs = sa ^ sb;                 // result sign

  wire a_is_zero = (ea == 11'd0)   && (ma == 52'd0);
  wire b_is_zero = (eb == 11'd0)   && (mb == 52'd0);
  wire a_is_inf  = (ea == 11'h7FF) && (ma == 52'd0);
  wire b_is_inf  = (eb == 11'h7FF) && (mb == 52'd0);
  wire a_is_nan  = (ea == 11'h7FF) && (ma != 52'd0);
  wire b_is_nan  = (eb == 11'h7FF) && (mb != 52'd0);

  // significands with implicit bit
  wire        ha = (ea != 11'd0);
  wire        hb = (eb != 11'd0);
  wire [52:0] siga = {ha, ma};
  wire [52:0] sigb = {hb, mb};

  reg  [105:0] prod;               // 53 x 53 = up to 106 bits
  reg  signed [13:0] exp_sum;      // combined unbiased exponent (wide, signed)
  reg  [13:0] lza, lzb;            // leading-zero adjustments for subnormals
  reg  [52:0] sa_sh, sb_sh;        // pre-normalized significands (leading 1 at bit 52), registered
  reg  [105:0] norm;
  reg  signed [13:0] e;
  reg  [55:0] mant;                // 53-bit + GRS
  reg  g, r, s, l, up;
  reg  [63:0] rnd;
  reg  [52:0] fsig;
  reg  signed [13:0] fe;
  reg  [13:0] rsh;
  reg  [127:0] wide;
  reg  g2,r2,s2,l2,up2;
  reg  [63:0] rr;
  reg  signed [13:0] bexp;
  reg          rs_l;               // result sign, registered for the ROUND stage
  reg  [13:0]  lza_r, lzb_r;       // leading-zero counts, for PRENORM
  reg  [63:0]  wide_r;             // a subnormal product on its grid (at most 56 bits), for SUBP

  // The 53×53 significand product, two clocks deep: sa_sh and sb_sh, written in PRENORM and held through PRODUCT,
  // enter it at MUL and its product is read in PRODUCT. MUL_TREE (an ASIC build) makes it a compressor tree, its
  // first four levels registered at the end of MUL and the rest at the end of MUL2 before a Kogge-Stone add; otherwise
  // (an FPGA build) it is the `*` a DSP block takes, registered twice.
  wire [105:0] tree_p;
  generate
    if (MUL_TREE) begin : tree
      fp_csa_mul #(.AW(53), .BW(53), .CUT(4), .FINAL(1)) product_tree(.clk(clk), .a(sa_sh), .b(sb_sh), .p(tree_p));
    end else begin : dsp
      // One register: the operands hold through MUL2, so the product is stable when PRODUCT reads it.
      reg [105:0] p1;
      always @(posedge clk) p1 <= sa_sh * sb_sh;
      assign tree_p = p1;
    end
  endgenerate

  // The highest set bit of a nonzero word, by halving: six levels, not a priority chain.
  function [5:0] lead_one64(input [63:0] m);
    reg [31:0] h5; reg [15:0] h4; reg [7:0] h3; reg [3:0] h2; reg [1:0] h1; reg [5:0] z;
    begin
      z[5] = ~|m[63:32];  h5 = z[5] ? m[31:0]  : m[63:32];
      z[4] = ~|h5[31:16]; h4 = z[4] ? h5[15:0] : h5[31:16];
      z[3] = ~|h4[15:8];  h3 = z[3] ? h4[7:0]  : h4[15:8];
      z[2] = ~|h3[7:4];   h2 = z[2] ? h3[3:0]  : h3[7:4];
      z[1] = ~|h2[3:2];   h1 = z[1] ? h2[1:0]  : h2[3:2];
      z[0] = ~h1[1];
      lead_one64 = ~z;
    end
  endfunction

  // Leading zeros of a 53-bit significand, 53 when it is zero.
  function [13:0] clz53(input [52:0] v);
    begin
      clz53 = (v == 53'd0) ? 14'd53 : 14'd52 - {8'd0, lead_one64({11'd0, v})};
    end
  endfunction

  // v + cin through a parallel-prefix AND: log2(64) levels. cin is the scan's bit 0, so bit i flips on cin and
  // every bit below it, and cin reaches the bits through the scan's tree rather than one net to all 64.
  function [63:0] inc64(input [63:0] v, input cin);
    reg [63:0] p; integer d;
    begin
      p = {v[62:0], cin};
      for (d = 1; d < 64; d = d * 2) p = p & ((p << d) | ((64'd1 << d) - 64'd1));
      inc64 = v ^ p;
    end
  endfunction

  // A word's bits below `s` as one flag: shifted to the top and tested, no (1 << s) - 1 mask, no borrow chain.
  function below(input [127:0] x, input [13:0] s);
    begin
      below = (s == 14'd0) ? 1'b0 : ((x << (14'd128 - s)) != 128'd0);
    end
  endfunction


  initial begin state = IDLE; done = 1'b0; y = 64'd0; end

  always @(posedge clk) begin
    if (rst) begin state <= IDLE; done <= 1'b0; y <= 64'd0; end
    else case (state)
      IDLE: if (start) begin
        done <= 1'b0; a_l <= a; b_l <= b; state <= DECODE;
      end
      DECODE: begin
        rs_l <= rs;
        if (a_is_nan || b_is_nan) begin y <= QNAN; done <= 1'b1; state <= IDLE; end
        else if ((a_is_inf && b_is_zero) || (b_is_inf && a_is_zero)) begin y <= QNAN; done <= 1'b1; state <= IDLE; end
        else if (a_is_inf || b_is_inf) begin y <= {rs, 11'h7FF, 52'd0}; done <= 1'b1; state <= IDLE; end
        else if (a_is_zero || b_is_zero) begin y <= {rs, 63'd0}; done <= 1'b1; state <= IDLE; end
        else begin
          // unbiased exponents; leading-zero counts (this stage isolates the two clz53 cones + pre-shift).
          lza_r <= clz53(siga);
          lzb_r <= clz53(sigb);
          state <= PRENORM;
        end
      end
      PRENORM: begin
        lza = lza_r;
        lzb = lzb_r;
        exp_sum <= (ea != 0 ? $signed({3'd0, ea}) - 14'sd1023 : -14'sd1022)
                 + (eb != 0 ? $signed({3'd0, eb}) - 14'sd1023 : -14'sd1022)
                 - $signed(lza) - $signed(lzb);
        sa_sh <= (siga << lza);   // leading 1 at bit 52
        sb_sh <= (sigb << lzb);
        state <= MUL;
      end
      MUL: begin
        // ── the 53×53 product's compressor tree, its first four levels (registered inside product_tree) ──
        state <= MUL2;
      end
      MUL2: begin
        // ── its remaining levels (registered inside product_tree) ──
        state <= PRODUCT;
      end
      PRODUCT: begin
        // ── the tree's last two words added + top-bit normalize ──
        prod = tree_p;
        if (prod[105]) begin
          norm <= prod;
          e    <= exp_sum + 14'sd1; // leading at 105 means value in [2,4) relative -> exp+1
        end else begin
          norm <= prod << 1;        // shift so leading 1 sits at bit 105
          e    <= exp_sum;
        end
        state <= ROUND;
      end
      ROUND: begin
        // Now norm[105] == 1 and its (would-be normal) biased exponent is `e`. Decide underflow BEFORE
        // rounding — rounding the exact product exactly once avoids the double-rounding bug.
        if (e < -14'sd1022) begin
          // ── subnormal / underflow: the EXACT product shifted onto the subnormal grid, SUBP rounds it once ──
          rsh = (-14'sd1022) - e;                    // extra right-shift into the subnormal grid (>= 1)
          wide = (norm >> (14'd105 - 14'd55)) | {127'd0, below(norm, 14'd105 - 14'd55)};  // norm[105]->bit55
          if (rsh >= 14'd128)       wide_r <= {63'd0, |wide};
          else if (rsh != 14'd0)    wide_r <= (wide >> rsh) | {127'd0, below(wide, rsh)};
          else                      wide_r <= wide;
          state <= SUBP;
        end else begin
          // ── normal path: round the 53-bit significand ──
          mant = {norm[105:53], (norm[52]), (norm[51]), (|norm[50:0])};  // 53 + g + r + s = 56 bits
          g = mant[2]; r = mant[1]; s = mant[0]; l = mant[3];
          up = g & (r | s | l);
          rnd = inc64({11'd0, mant[55:3]}, up);
          if (rnd[53]) begin fsig = rnd[53:1]; fe = e + 14'sd1; end
          else         begin fsig = rnd[52:0]; fe = e; end
          if (fe > 14'sd1023) begin
            y <= {rs_l, 11'h7FF, 52'd0};                          // overflow -> inf
          end else if (fe < -14'sd1022) begin
            y <= {rs_l, 11'd1, fsig[51:0]};
          end else begin
            bexp = fe + 14'sd1023;
            y <= {rs_l, bexp[10:0], fsig[51:0]};
          end
          done <= 1'b1; state <= IDLE;
        end
      end
      SUBP: begin
        g2 = wide_r[2]; r2 = wide_r[1]; s2 = wide_r[0]; l2 = wide_r[3];
        up2 = g2 & (r2 | s2 | l2);
        rr = inc64({11'd0, wide_r[55:3]}, up2);
        if (rr[52]) y <= {rs_l, 11'd1, rr[51:0]};   // rounded up to the smallest normal
        else        y <= {rs_l, 11'd0, rr[51:0]};
        done <= 1'b1; state <= IDLE;
      end
    endcase
  end
endmodule

// fp_csa_mul — an unsigned AW×BW multiplier as a tree of 3:2 compressors over its BW partial-product rows. The
// compressor outputs register after CUT levels (CUT = 0 or beyond the tree's depth: no register inside it), the last
// two words register again when FINAL is set, and those two words resolve through a Kogge-Stone add. `p` is the
// product of the operands sampled as many clocks earlier as there are registers on its path.
module fp_csa_mul #(parameter integer AW = 53, parameter integer BW = 53, parameter integer CUT = 4,
                 parameter integer FINAL = 1) (
  input                clk,
  input  [AW-1:0]      a,
  input  [BW-1:0]      b,
  output [AW+BW-1:0]   p
);
  localparam integer W = AW + BW;

  // The words entering tree level `level`: each level turns every three words into two and passes the rest.
  function integer words(input integer level);
    integer n, l;
    begin
      n = BW;
      for (l = 0; l < level; l = l + 1) n = 2 * (n / 3) + (n % 3);
      words = n;
    end
  endfunction

  function integer depth(input integer unused);
    integer n, l;
    begin
      n = BW; l = 0;
      while (n > 2) begin n = 2 * (n / 3) + (n % 3); l = l + 1; end
      depth = l;
    end
  endfunction

  localparam integer L = depth(0);

  // Level-major bus: level `l` holds its words at word slots l*BW .. l*BW + words(l) - 1.
  wire [W*BW*(L+1)-1:0] lv;

  genvar i, l, g;
  generate
    for (i = 0; i < BW; i = i + 1) begin : row
      assign lv[i*W +: W] = b[i] ? ({{BW{1'b0}}, a} << i) : {W{1'b0}};
    end
    for (l = 0; l < L; l = l + 1) begin : level
      localparam integer N = words(l);
      localparam integer G = N / 3;
      for (g = 0; g < G; g = g + 1) begin : compress
        wire [W-1:0] x = lv[((l*BW) + 3*g) * W +: W];
        wire [W-1:0] y = lv[((l*BW) + 3*g + 1) * W +: W];
        wire [W-1:0] z = lv[((l*BW) + 3*g + 2) * W +: W];
        wire [W-1:0] xy = x ^ y;
        wire [W-1:0] s = xy ^ z;
        wire [W-1:0] c = ((x & y) | (z & xy)) << 1;
        if (l + 1 == CUT) begin : registered
          reg [W-1:0] sr, cr;
          always @(posedge clk) begin sr <= s; cr <= c; end
          assign lv[(((l+1)*BW) + 2*g) * W +: W] = sr;
          assign lv[(((l+1)*BW) + 2*g + 1) * W +: W] = cr;
        end else begin : wired
          assign lv[(((l+1)*BW) + 2*g) * W +: W] = s;
          assign lv[(((l+1)*BW) + 2*g + 1) * W +: W] = c;
        end
      end
      for (g = 0; g < N % 3; g = g + 1) begin : carry_over
        if (l + 1 == CUT) begin : registered
          reg [W-1:0] r;
          always @(posedge clk) r <= lv[((l*BW) + 3*G + g) * W +: W];
          assign lv[(((l+1)*BW) + 2*G + g) * W +: W] = r;
        end else begin : wired
          assign lv[(((l+1)*BW) + 2*G + g) * W +: W] = lv[((l*BW) + 3*G + g) * W +: W];
        end
      end
    end
  endgenerate

  wire [W-1:0] s_word = lv[(L*BW) * W +: W];
  wire [W-1:0] c_word;
  generate
    if (BW == 1) begin : one_row
      assign c_word = {W{1'b0}};
    end else begin : two_rows
      assign c_word = lv[(L*BW + 1) * W +: W];
    end
  endgenerate
  reg  [W-1:0] s_r, c_r;
  always @(posedge clk) begin s_r <= s_word; c_r <= c_word; end
  wire [W-1:0] s_in = FINAL ? s_r : s_word;
  wire [W-1:0] c_in = FINAL ? c_r : c_word;

  // The Kogge-Stone add of the last two words: group generate and propagate doubled in span each level.
  function [W-1:0] prefix_add(input [W-1:0] u, input [W-1:0] v);
    reg [W-1:0] gg, pp, p0; integer d;
    begin
      gg = u & v; p0 = u ^ v; pp = p0;
      for (d = 1; d < W; d = d * 2) begin
        gg = gg | (pp & (gg << d));
        pp = pp & (pp << d);
      end
      prefix_add = p0 ^ (gg << 1);
    end
  endfunction

  assign p = prefix_add(s_in, c_in);
endmodule

// ─────────────────────────────────────────────────────────────────────────────────────────────────
// fp_cmp — combinational IEEE-754 binary64 less-than / equal (returns 1 bit each).
//   lt: a < b (false if either is NaN, -0 == +0)
//   eq: a == b (false if either is NaN, -0 == +0)
// ─────────────────────────────────────────────────────────────────────────────────────────────────
module fp_cmp(
  input  [63:0] a,
  input  [63:0] b,
  output        lt,
  output        eq
);
  wire [10:0] ea = a[62:52], eb = b[62:52];
  wire [51:0] ma = a[51:0],  mb = b[51:0];
  wire a_is_nan = (ea == 11'h7FF) && (ma != 52'd0);
  wire b_is_nan = (eb == 11'h7FF) && (mb != 52'd0);
  wire any_nan  = a_is_nan || b_is_nan;

  wire a_is_zero = (a[62:0] == 63'd0);   // ±0 : exp and frac all zero
  wire b_is_zero = (b[62:0] == 63'd0);
  wire both_zero = a_is_zero && b_is_zero;   // -0 == +0

  wire sa = a[63], sb = b[63];

  // Map to a monotonic ordering key (the classic "flip" trick): for a two's-complement view of the
  // bit pattern, positives keep order; negatives are reversed. Convert to an unsigned key where the
  // numeric order matches: if sign bit set -> ~bits ; else -> bits | 0x8000...0000.
  wire [63:0] ka = a[63] ? ~a : (a | 64'h8000000000000000);
  wire [63:0] kb = b[63] ? ~b : (b | 64'h8000000000000000);

  assign eq = any_nan ? 1'b0 : (both_zero ? 1'b1 : (a == b));
  assign lt = any_nan ? 1'b0 : (both_zero ? 1'b0 : (ka < kb));
endmodule

// ─────────────────────────────────────────────────────────────────────────────────────────────────
// fp_div — multi-cycle IEEE-754 binary64 divide, digit-recurrence (restoring), correctly rounded.
//   start/done handshake. Computes a/b with a 55-bit quotient (53 + guard/round) plus a sticky
//   from the final nonzero remainder, then RNE-rounds; each recurrence step's subtract is a parallel-prefix
//   subtract, and a subnormal quotient takes its grid shift and its rounding in stages of their own.
// ─────────────────────────────────────────────────────────────────────────────────────────────────
module fp_div(
  input         clk,
  input         rst,
  input         start,
  input  [63:0] a,
  input  [63:0] b,
  output reg [63:0] y,
  output reg    done
);
  localparam [63:0] QNAN = 64'h7FF8000000000000;

  reg  [3:0] state;
  // The exponent datapath is PIPELINED (SETUP→SETUP2→SETUP3 and FIN→FIN2) so no single cycle carries a
  // long combinational exponent tail. On silicon that tail was the last-settling node of a deep cone (clz +
  // barrel-shift + wide signed add in SETUP; 128-bit shifters + round + biased-exponent add in FIN), and it
  // dropped a carry — the mantissa (settling earlier in the same cone) stayed exact while the exponent came
  // out 2^32 small. Registering between the clz/shift/add sub-steps keeps every cone short, matching the
  // already-silicon-correct fp_mul, at the cost of a few extra cycles (the unit already runs ~70).
  localparam IDLE = 4'd0, SETUP = 4'd1, SETUP2 = 4'd2, SETUP3 = 4'd3, RUN = 4'd4, FIN = 4'd5, FIN2 = 4'd6,
             FINS = 4'd7, FINP = 4'd8;

  // latched operand decode
  reg  sa, sb, rs;
  reg  [10:0] ea, eb;
  reg  [51:0] ma, mb;
  reg  special;                 // special-case result already computed
  reg  [63:0] special_y;
  reg  signed [13:0] exp_res;   // unbiased result exponent (of the leading quotient bit)

  // digit-recurrence datapath: divide two normalized 53-bit significands.
  reg  [55:0] num;              // remainder / working numerator, gets shifted left each step
  reg  [52:0] den;              // divisor significand (leading 1 at bit 52)
  reg  [55:0] quo;              // quotient bits accumulate here (56 = 53 + 3 GRS)
  reg  [6:0]  cnt;              // step counter
  reg  [72:0] diff;
  reg  [105:0] shl_a, shl_b;    // normalized significands (leading 1 at bit 52) — temporaries
  reg  signed [13:0] bexp;      // biased exponent temporary

  reg  signed [13:0] lza, lzb;

  // The highest set bit of a nonzero word, by halving: six levels, not a priority chain.
  function [5:0] lead_one64(input [63:0] m);
    reg [31:0] h5; reg [15:0] h4; reg [7:0] h3; reg [3:0] h2; reg [1:0] h1; reg [5:0] z;
    begin
      z[5] = ~|m[63:32];  h5 = z[5] ? m[31:0]  : m[63:32];
      z[4] = ~|h5[31:16]; h4 = z[4] ? h5[15:0] : h5[31:16];
      z[3] = ~|h4[15:8];  h3 = z[3] ? h4[7:0]  : h4[15:8];
      z[2] = ~|h3[7:4];   h2 = z[2] ? h3[3:0]  : h3[7:4];
      z[1] = ~|h2[3:2];   h1 = z[1] ? h2[1:0]  : h2[3:2];
      z[0] = ~h1[1];
      lead_one64 = ~z;
    end
  endfunction

  // Leading zeros of a 53-bit significand, 53 when it is zero.
  function [13:0] clz53(input [52:0] v);
    begin
      clz53 = (v == 53'd0) ? 14'd53 : 14'd52 - {8'd0, lead_one64({11'd0, v})};
    end
  endfunction

  // v + cin through a parallel-prefix AND: log2(64) levels. cin is the scan's bit 0, so bit i flips on cin and
  // every bit below it, and cin reaches the bits through the scan's tree rather than one net to all 64.
  function [63:0] inc64(input [63:0] v, input cin);
    reg [63:0] p; integer d;
    begin
      p = {v[62:0], cin};
      for (d = 1; d < 64; d = d * 2) p = p & ((p << d) | ((64'd1 << d) - 64'd1));
      inc64 = v ^ p;
    end
  endfunction

  // A word's bits below `s` as one flag: shifted to the top and tested, no (1 << s) - 1 mask, no borrow chain.
  function below(input [127:0] x, input [13:0] s);
    begin
      below = (s == 14'd0) ? 1'b0 : ((x << (14'd128 - s)) != 128'd0);
    end
  endfunction

  // x - y over 72 bits as a Kogge-Stone prefix subtract; bit 72 of the result is the borrow (1 when x < y).
  function [72:0] sub72(input [71:0] x, input [71:0] yy);
    reg [71:0] yb, g, p, p0; integer d;
    begin
      yb = ~yy;
      p0 = x ^ yb;
      g = (x & yb) | (p0 & 72'd1);
      p = p0;
      for (d = 1; d < 72; d = d * 2) begin
        g = g | (p & (g << d));
        p = p & (p << d);
      end
      sub72 = {~g[71], p0 ^ {g[70:0], 1'b1}};
    end
  endfunction

  // rounding / packing registers
  reg  g,r,s,l,up;
  reg  [63:0] rnd;
  reg  [52:0] fsig;
  reg  signed [13:0] fe;
  reg  [13:0] rsh;
  reg  [127:0] wide;
  reg  g2,r2,s2,l2,up2;
  reg  [63:0] rr;

  // FIN pipeline: the final biased-exponent add (fe_r + 1023) lives alone in FIN2, off a register, so the
  // exponent output is never the tail of the deep FIN cone. normal_path picks the FIN2 assembly; the
  // subnormal / overflow / special results (constant exponent fields, no add) are pre-packed into y_reg.
  reg  [63:0] y_reg;
  reg          normal_path;
  reg  signed [13:0] fe_r;

  initial begin state = IDLE; done = 1'b0; y = 64'd0; end

  wire a_is_zero = (ea == 11'd0)   && (ma == 52'd0);
  wire b_is_zero = (eb == 11'd0)   && (mb == 52'd0);
  wire a_is_inf  = (ea == 11'h7FF) && (ma == 52'd0);
  wire b_is_inf  = (eb == 11'h7FF) && (mb == 52'd0);
  wire a_is_nan  = (ea == 11'h7FF) && (ma != 52'd0);
  wire b_is_nan  = (eb == 11'h7FF) && (mb != 52'd0);

  reg  [127:0] qwin;   // canonical quotient window for the subnormal path
  reg  [63:0]  qwin_r; // that window (at most 57 bits), held for the subnormal stages
  reg  [63:0]  den_win;// that window on the subnormal grid, its dropped bits folded into sticky
  reg  [13:0]  rsh_r;  // the subnormal grid's extra right shift
  reg          to_subnormal;
  reg  [11:0]  qlead;

  always @(posedge clk) begin
    if (rst) begin state <= IDLE; done <= 1'b0; y <= 64'd0; end
    else case (state)
      IDLE: if (start) begin
        done <= 1'b0;
        sa <= a[63]; sb <= b[63]; rs <= a[63]^b[63];
        ea <= a[62:52]; eb <= b[62:52]; ma <= a[51:0]; mb <= b[51:0];
        state <= SETUP;
      end
      SETUP: begin
        // ── cycle 1: special-case detection + count-leading-zeros only (register lza/lzb) ──
        if (a_is_nan || b_is_nan)        begin special <= 1'b1; special_y <= QNAN; state <= FIN; end
        else if (a_is_inf && b_is_inf)   begin special <= 1'b1; special_y <= QNAN; state <= FIN; end
        else if (a_is_inf)               begin special <= 1'b1; special_y <= {rs, 11'h7FF, 52'd0}; state <= FIN; end
        else if (b_is_inf)               begin special <= 1'b1; special_y <= {rs, 63'd0}; state <= FIN; end  // finite/inf=0
        else if (a_is_zero && b_is_zero) begin special <= 1'b1; special_y <= QNAN; state <= FIN; end          // 0/0=NaN
        else if (b_is_zero)              begin special <= 1'b1; special_y <= {rs, 11'h7FF, 52'd0}; state <= FIN; end // x/0=inf
        else if (a_is_zero)              begin special <= 1'b1; special_y <= {rs, 63'd0}; state <= FIN; end    // 0/x=0
        else begin
          special <= 1'b0;
          lza <= clz53({(ea!=0), ma});
          lzb <= clz53({(eb!=0), mb});
          state <= SETUP2;
        end
      end
      SETUP2: begin
        // ── cycle 2: barrel-shift the significands and form the unbiased exponent — each its own short
        // cone off the registered lza/lzb (no clz→shift→wide-add chained together in one cycle) ──
        shl_a <= ({53'd0, (ea!=0), ma}) << lza;
        shl_b <= ({53'd0, (eb!=0), mb}) << lzb;
        exp_res <= (ea != 0 ? $signed({3'd0, ea}) - 14'sd1023 : -14'sd1022)
                 - (eb != 0 ? $signed({3'd0, eb}) - 14'sd1023 : -14'sd1022)
                 - $signed(lza) + $signed(lzb);
        state <= SETUP3;
      end
      SETUP3: begin
        // ── cycle 3: seed the digit-recurrence from the registered normalized significands ──
        den <= shl_b[52:0];
        num <= {3'd0, shl_a[52:0]};   // dividend significand (leading 1 at bit 52), room above to shift
        quo <= 56'd0;
        cnt <= 7'd56;                 // produce 56 quotient bits (53 + 3 GRS), first bit at position 55
        state <= RUN;
      end
      RUN: begin
        if (cnt != 7'd0) begin
          // ── one restoring-division step: compare THEN shift, so the first emitted bit is the 2^0
          // digit of the significand ratio (both operands in [1,2), so the ratio is in (0.5,2)). ──
          diff = sub72({16'd0, num}, {19'd0, den});
          if (!diff[72]) begin                   // num >= den -> quotient bit 1, subtract
            num <= {diff[54:0], 1'b0};            // (num - den) << 1
            quo <= {quo[54:0], 1'b1};
          end else begin
            num <= {num[54:0], 1'b0};             // num << 1
            quo <= {quo[54:0], 1'b0};
          end
          cnt <= cnt - 7'd1;
        end else begin
          state <= FIN;
        end
      end
      FIN: begin
        // ── stage 1: normalize + round the quotient; register the significand (fsig) and unbiased
        // exponent (fe_r). Overflow and special results carry constant exponent fields and are pre-packed into
        // y_reg; a subnormal result goes through FINS and FINP. The biased-exponent ADD is deferred to FIN2. ──
        if (special) begin
          y_reg <= special_y; normal_path <= 1'b0;
        end else begin
          // quotient of two [1,2) significands is in (0.5,2). Its leading 1 is at bit 55 (if >=1) or
          // bit 54. Normalize so the leading 1 sits at bit 55 (window [55:3]=53-bit sig, [2:0]=GRS),
          // with a non-empty division remainder `num` OR'd into sticky.
          if (quo[55]) begin
            g = quo[2]; r = quo[1]; s = (quo[0] | (num != 56'd0)); l = quo[3];
            up = g & (r | s | l);
            rnd = inc64({11'd0, quo[55:3]}, up);
            fe  = exp_res;
            qwin = {72'd0, quo};                 // leading 1 at bit 55 already
            if (num != 56'd0) qwin[0] = 1'b1;
          end else begin
            g = quo[1]; r = quo[0]; s = (num != 56'd0); l = quo[2];
            up = g & (r | s | l);
            rnd = inc64({11'd0, quo[54:2]}, up);
            fe  = exp_res - 14'sd1;
            qwin = {72'd0, quo} << 1;            // shift leading 1 from bit 54 up to bit 55
            if (num != 56'd0) qwin[0] = 1'b1;
          end
          if (rnd[53]) begin fsig <= rnd[53:1]; fe = fe + 14'sd1; end
          else         begin fsig <= rnd[52:0]; end

          // pre-round exponent (of the leading quotient bit) drives the underflow decision so the
          // subnormal path rounds the exact quotient window exactly ONCE (no double rounding).
          if (quo[55]) bexp = exp_res; else bexp = exp_res - 14'sd1;

          if (bexp < -14'sd1022) begin
            // A subnormal quotient: the un-rounded window (leading 1 at bit 55) goes to FINS and FINP, which shift
            // it onto the subnormal grid and round it once.
            rsh_r  <= (-14'sd1022) - bexp;
            qwin_r <= qwin;
            normal_path <= 1'b0;
            to_subnormal <= 1'b1;
          end else if (fe > 14'sd1023) begin
            y_reg <= {rs, 11'h7FF, 52'd0};                // overflow -> inf
            normal_path <= 1'b0;
            to_subnormal <= 1'b0;
          end else begin
            fe_r <= fe;                                   // registered exponent for FIN2's biased add
            normal_path <= 1'b1;
            to_subnormal <= 1'b0;
          end
        end
        state <= (!special && bexp < -14'sd1022) ? FINS : FIN2;
      end
      FINS: begin
        if (rsh_r >= 14'd128)    den_win <= {63'd0, |qwin_r};
        else if (rsh_r != 14'd0) den_win <= (qwin_r >> rsh_r) | {127'd0, below({64'd0, qwin_r}, rsh_r)};
        else                     den_win <= qwin_r;
        state <= FINP;
      end
      FINP: begin
        g2 = den_win[2]; r2 = den_win[1]; s2 = den_win[0]; l2 = den_win[3];
        up2 = g2 & (r2 | s2 | l2);
        rr = inc64({11'd0, den_win[55:3]}, up2);
        if (rr[52]) y_reg <= {rs, 11'd1, rr[51:0]};       // rounded up to the smallest normal
        else        y_reg <= {rs, 11'd0, rr[51:0]};
        state <= FIN2;
      end
      FIN2: begin
        // ── stage 2: the sole remaining exponent op — a short (fe_r + 1023) biased-exponent add off a
        // register, then pack. This is what keeps the exponent out of the deep FIN cone on silicon. ──
        if (normal_path) begin
          bexp = fe_r + 14'sd1023;
          y <= {rs, bexp[10:0], fsig[51:0]};
        end else begin
          y <= y_reg;
        end
        done <= 1'b1; state <= IDLE;
      end
    endcase
  end
endmodule

// ─────────────────────────────────────────────────────────────────────────────────────────────────
// fp_sqrt — multi-cycle IEEE-754 binary64 square root, digit-recurrence (restoring, non-restoring
//   style bit-at-a-time), correctly rounded (RNE). start/done handshake.
//   sqrt(neg) -> NaN, sqrt(+inf)=+inf, sqrt(±0)=±0, sqrt(NaN)=NaN. Each step's trial subtract is a
//   parallel-prefix subtract; the leading-zero count, the normalizing shift and the round each take a stage.
// ─────────────────────────────────────────────────────────────────────────────────────────────────
module fp_sqrt(
  input         clk,
  input         rst,
  input         start,
  input  [63:0] a,
  output reg [63:0] y,
  output reg    done
);
  localparam [63:0] QNAN = 64'h7FF8000000000000;

  reg  [2:0] state;
  localparam IDLE = 3'd0, SETUP = 3'd1, RUN = 3'd2, FIN = 3'd3, NORM = 3'd4, PACK = 3'd5;

  reg  [10:0] ea;
  reg  [51:0] ma;
  reg  asign;                   // input sign (only matters for -0)
  reg  special;
  reg  [63:0] special_y;

  // Digit-recurrence sqrt. The radicand M (= significand, or 2×significand for an odd input exponent)
  // is in [1,4). We place M in a wide fixed-point lane with its binary point just below the top two
  // integer bits, then peel 2 radicand bits per root bit. `root` accumulates the root; the leading root
  // bit lands at a fixed position so we can extract sig/guard/round/sticky directly.
  reg  signed [13:0] exp_in;    // unbiased exponent of the input's leading significand bit
  reg  signed [13:0] exp_res;   // result exponent (floor(exp_in/2))
  reg  [131:0] rad;             // radicand lane (2 bits consumed per step)
  reg  [66:0]  root;            // accumulated root bits (leading root bit ends at a fixed position)
  reg  [67:0]  rem;             // running remainder
  reg  [7:0]   cnt;

  reg  [67:0] trial, test;
  reg  signed [13:0] lz;
  reg  [13:0]  lz_r;        // leading zeros of a subnormal input, for NORM
  reg  [72:0]  dt;
  reg  [63:0]  rnd_r;       // the rounded significand, for PACK
  // The highest set bit of a nonzero word, by halving: six levels, not a priority chain.
  function [5:0] lead_one64(input [63:0] m);
    reg [31:0] h5; reg [15:0] h4; reg [7:0] h3; reg [3:0] h2; reg [1:0] h1; reg [5:0] z;
    begin
      z[5] = ~|m[63:32];  h5 = z[5] ? m[31:0]  : m[63:32];
      z[4] = ~|h5[31:16]; h4 = z[4] ? h5[15:0] : h5[31:16];
      z[3] = ~|h4[15:8];  h3 = z[3] ? h4[7:0]  : h4[15:8];
      z[2] = ~|h3[7:4];   h2 = z[2] ? h3[3:0]  : h3[7:4];
      z[1] = ~|h2[3:2];   h1 = z[1] ? h2[1:0]  : h2[3:2];
      z[0] = ~h1[1];
      lead_one64 = ~z;
    end
  endfunction

  // Leading zeros of a 53-bit significand, 53 when it is zero.
  function [13:0] clz53(input [52:0] v);
    begin
      clz53 = (v == 53'd0) ? 14'd53 : 14'd52 - {8'd0, lead_one64({11'd0, v})};
    end
  endfunction

  // v + cin through a parallel-prefix AND: log2(64) levels. cin is the scan's bit 0, so bit i flips on cin and
  // every bit below it, and cin reaches the bits through the scan's tree rather than one net to all 64.
  function [63:0] inc64(input [63:0] v, input cin);
    reg [63:0] p; integer d;
    begin
      p = {v[62:0], cin};
      for (d = 1; d < 64; d = d * 2) p = p & ((p << d) | ((64'd1 << d) - 64'd1));
      inc64 = v ^ p;
    end
  endfunction

  // A word's bits below `s` as one flag: shifted to the top and tested, no (1 << s) - 1 mask, no borrow chain.
  function below(input [127:0] x, input [13:0] s);
    begin
      below = (s == 14'd0) ? 1'b0 : ((x << (14'd128 - s)) != 128'd0);
    end
  endfunction

  // x - y over 72 bits as a Kogge-Stone prefix subtract; bit 72 of the result is the borrow (1 when x < y).
  function [72:0] sub72(input [71:0] x, input [71:0] yy);
    reg [71:0] yb, g, p, p0; integer d;
    begin
      yb = ~yy;
      p0 = x ^ yb;
      g = (x & yb) | (p0 & 72'd1);
      p = p0;
      for (d = 1; d < 72; d = d * 2) begin
        g = g | (p & (g << d));
        p = p & (p << d);
      end
      sub72 = {~g[71], p0 ^ {g[70:0], 1'b1}};
    end
  endfunction

  reg  g,r,rr_s,l,up;
  reg  [63:0] rnd;
  reg  [52:0] fsig;
  reg  signed [13:0] fe;
  reg  signed [13:0] bexp;
  reg  [52:0] msig;             // normalized significand (leading 1 at bit 52)

  // Number of root bits we generate. We need 53 significand + guard + round + a sticky, so 56 useful
  // bits; produce a couple extra for the sticky tail. NROOT steps consume 2*NROOT radicand bits.
  localparam integer NROOT = 59;

  initial begin state = IDLE; done = 1'b0; y = 64'd0; end

  wire a_is_zero = (ea == 11'd0)   && (ma == 52'd0);
  wire a_is_inf  = (ea == 11'h7FF) && (ma == 52'd0);
  wire a_is_nan  = (ea == 11'h7FF) && (ma != 52'd0);

  always @(posedge clk) begin
    if (rst) begin state <= IDLE; done <= 1'b0; y <= 64'd0; end
    else case (state)
      IDLE: if (start) begin
        done <= 1'b0; asign <= a[63]; ea <= a[62:52]; ma <= a[51:0]; state <= SETUP;
      end
      SETUP: begin
        if (a_is_nan)                    begin special <= 1'b1; special_y <= QNAN; state <= FIN; end
        else if (asign && !a_is_zero)    begin special <= 1'b1; special_y <= QNAN; state <= FIN; end  // sqrt(neg)=NaN
        else if (a_is_inf)               begin special <= 1'b1; special_y <= 64'h7FF0000000000000; state <= FIN; end
        else if (a_is_zero)              begin special <= 1'b1; special_y <= {asign, 63'd0}; state <= FIN; end // sqrt(±0)=±0
        else begin
          special <= 1'b0;
          lz_r <= clz53({(ea!=0), ma});
          state <= NORM;
        end
      end
      NORM: begin
        begin
          lz = lz_r;
          msig = ({(ea!=0), ma} << lz);      // leading 1 at bit 52, value m in [1,2)
          exp_in = (ea != 0 ? $signed({3'd0, ea}) - 14'sd1023 : -14'sd1022) - $signed(lz);
          // Radicand M = m (even exp) or 2m (odd exp), in [1,4). Place M's binary point so the top two
          // lane bits [131:130] hold the integer part. m has its leading 1 at bit 52; shift it up to
          // bit 130 (for even) or 131 (for odd, = 2m). Then process pairs from the top down.
          if (exp_in[0]) begin
            rad <= {msig, 79'd0};             // 2m : leading 1 at bit 131 (52+79)
            exp_res <= (exp_in - 14'sd1) >>> 1;
          end else begin
            rad <= {1'b0, msig, 78'd0};       // m  : leading 1 at bit 130 (52+78)
            exp_res <= exp_in >>> 1;
          end
          root <= 67'd0; rem <= 68'd0; cnt <= NROOT[7:0];
          state <= RUN;
        end
      end
      RUN: begin
        if (cnt != 8'd0) begin
          // ── one restoring sqrt step ──
          test  = {rem[65:0], rad[131:130]};   // bring down the top 2 radicand bits
          trial = {root[65:0], 2'b01};          // 2*root + 1  at this scale
          dt = sub72({4'd0, test}, {4'd0, trial});
          if (!dt[72]) begin                    // test >= trial
            rem  <= dt[67:0];
            root <= {root[65:0], 1'b1};
          end else begin
            rem  <= test;
            root <= {root[65:0], 1'b0};
          end
          rad <= {rad[129:0], 2'b00};           // consume the two processed bits
          cnt <= cnt - 8'd1;
        end else state <= FIN;
      end
      FIN: begin
        if (special) begin
          y <= special_y; done <= 1'b1; state <= IDLE;
        end else begin
          // After NROOT steps the root is an NROOT-bit integer approximating sqrt(M) scaled up. The root
          // value is in [1,2) (since M in [1,4)), so its leading 1 is at bit (NROOT-1). We want the
          // 53-bit significand at the top: significand = root[NROOT-1 : NROOT-53], guard = root[NROOT-54],
          // round = root[NROOT-55], sticky = OR of the rest and the nonzero remainder.
          // With NROOT=59: leading at bit 58; sig=root[58:6]; guard=root[5]; round=root[4];
          // sticky = |root[3:0] | (rem!=0).
          g    = root[5];
          r    = root[4];
          rr_s = (|root[3:0]) | (rem != 68'd0);
          l    = root[6];
          up   = g & (r | rr_s | l);
          rnd_r <= inc64({11'd0, root[58:6]}, up);
          state <= PACK;
        end
      end
      PACK: begin
        rnd = rnd_r;
        if (rnd[53]) begin fsig = rnd[53:1]; fe = exp_res + 14'sd1; end
        else         begin fsig = rnd[52:0]; fe = exp_res; end
        // sqrt of any finite positive f64 lands in the normal range (the smallest positive subnormal
        // has sqrt ~ 2.2e-162, far above the subnormal threshold), so assemble directly.
        bexp = fe + 14'sd1023;
        y <= {1'b0, bexp[10:0], fsig[51:0]};
        done <= 1'b1; state <= IDLE;
      end
    endcase
  end
endmodule

// fp_conv — the f64 <-> i64 converters, FuncUnit::FFloorF (code 10, f64 -> i64 toward -inf) and FuncUnit::IntToF
// (code 13, i64 -> f64 round-to-nearest-ties-even), as a five-stage pipeline: no 64-bit carry chain, leading-one
// search or 64-bit shift shares a stage with another. `start` samples `x` and the direction into the unit's own
// registers, as every unit samples its operands, so no stage's logic reads a port another unit shares; `y` and `done`
// follow on the fifth clock. Bit-identical to the single-cycle conversions it replaces (== Rust `as` casts == the VM).
module fp_conv(input clk, input rst, input start, input to_float, input [63:0] x, output reg [63:0] y, output reg done);
  // Stage 0: the operand and the direction, as presented.
  reg        v0, f0;
  reg [63:0] x0;
  // Stage 1: the sign and magnitude (IntToF), or the decoded fields (FFloor).
  reg        v1, f1, s1, z1, small1, negsmall1;
  reg [63:0] m1;
  reg [10:0] ue1;
  // Stage 2: the leading one (IntToF), or the significand shifted to the binary point (FFloor).
  reg        v2, f2, s2, z2, small2, negsmall2, frac2;
  reg [63:0] m2;
  reg [5:0]  lead2;
  // Stage 3: the 53-bit significand and its round-up (IntToF), or |floor| before the sign (FFloor).
  reg        v3, f3, s3, z3, small3, negsmall3, up3;
  reg [52:0] sig3;
  reg [10:0] be3;
  reg [63:0] mag3;

  // The highest set bit of a nonzero word, by halving: each level asks whether the upper half is empty and keeps
  // the half that holds the leading one, six levels deep rather than a 64-long priority chain.
  function [5:0] lead_one(input [63:0] m);
    reg [31:0] h5; reg [15:0] h4; reg [7:0] h3; reg [3:0] h2; reg [1:0] h1; reg [5:0] z;
    begin
      z[5] = ~|m[63:32];  h5 = z[5] ? m[31:0]  : m[63:32];
      z[4] = ~|h5[31:16]; h4 = z[4] ? h5[15:0] : h5[31:16];
      z[3] = ~|h4[15:8];  h3 = z[3] ? h4[7:0]  : h4[15:8];
      z[2] = ~|h3[7:4];   h2 = z[2] ? h3[3:0]  : h3[7:4];
      z[1] = ~|h2[3:2];   h1 = z[1] ? h2[1:0]  : h2[3:2];
      z[0] = ~h1[1];
      lead_one = ~z;
    end
  endfunction

  // v + cin through a parallel-prefix AND of cin and v's low bits: log2(64) levels, never a ripple. cin is the
  // scan's bit 0, so it reaches the bits through the scan's tree rather than one net to all 64.
  function [63:0] inc64(input [63:0] v, input cin);
    reg [63:0] p; integer d;
    begin
      p = {v[62:0], cin};
      for (d = 1; d < 64; d = d * 2) p = p & ((p << d) | ((64'd1 << d) - 64'd1));
      inc64 = v ^ p;
    end
  endfunction

  wire [63:0] fsig = {11'd0, 1'b1, m1[51:0]};
  wire        fbig = ue1 >= 11'd52;
  wire [63:0] fmag = fbig ? (fsig << (ue1 - 11'd52)) : (fsig >> (11'd52 - ue1));
  wire        ffrac = !fbig && ((fsig << (ue1 + 11'd12)) != 64'd0);

  wire        wide = lead2 > 6'd52;
  wire [5:0]  sh = lead2 - 6'd52;
  wire [63:0] kept = m2 >> sh;
  wire [63:0] dropped = m2 << (7'd64 - {1'b0, sh});
  wire [63:0] aligned = m2 << (6'd52 - lead2);

  wire [63:0] rsig = inc64({11'd0, sig3}, up3);

  always @(posedge clk) begin
    if (rst) begin
      v0 <= 1'b0; v1 <= 1'b0; v2 <= 1'b0; v3 <= 1'b0; done <= 1'b0;
    end else begin
      v0 <= start;
      if (start) begin
        f0 <= to_float; x0 <= x;
      end

      v1 <= v0;
      if (v0) begin
        f1 <= f0;
        s1 <= x0[63];
        z1 <= x0 == 64'd0;
        m1 <= (f0 && x0[63]) ? inc64(~x0, 1'b1) : x0;
        small1 <= x0[62:52] < 11'd1023;
        negsmall1 <= x0[63] && !(x0[62:52] == 11'd0 && x0[51:0] == 52'd0);
        ue1 <= x0[62:52] - 11'd1023;
      end

      v2 <= v1; f2 <= f1; s2 <= s1; z2 <= z1; small2 <= small1; negsmall2 <= negsmall1;
      if (f1) begin
        m2 <= m1; lead2 <= lead_one(m1);
      end else begin
        m2 <= fmag; frac2 <= ffrac;
      end

      v3 <= v2; f3 <= f2; s3 <= s2; z3 <= z2; small3 <= small2; negsmall3 <= negsmall2;
      if (f2) begin
        be3 <= 11'd1023 + {5'd0, lead2};
        if (wide) begin
          sig3 <= kept[52:0];
          up3 <= dropped[63] && ((|dropped[62:0]) || kept[0]);
        end else begin
          sig3 <= aligned[52:0];
          up3 <= 1'b0;
        end
      end else begin
        mag3 <= inc64(m2, s2 && frac2);
      end

      done <= v3;
      if (f3) begin
        if (z3)            y <= 64'd0;
        else if (rsig[53]) y <= {s3, be3 + 11'd1, 52'd0};
        else               y <= {s3, be3, rsig[51:0]};
      end else begin
        if (small3)        y <= negsmall3 ? 64'hFFFF_FFFF_FFFF_FFFF : 64'd0;
        else if (s3)       y <= inc64(~mag3, 1'b1);
        else               y <= mag3;
      end
    end
  end
endmodule

// psram_cache — 8 lines of 2 64-bit words, direct-mapped, write-back, in front of psram_edge
// (codegen_sva::psram).
module psram_cache #(parameter integer IW = 3, parameter integer OW = 1) (
  input clk, input rst,
  input req_r, input [19:0] ra, input rhit,
  input req_w, input [19:0] wa, input whit, input [63:0] wd, input [1:0] wm,
  output [63:0] rd,
  output busy,
  output [127:0] tags, output [7:0] vals, output filled, output [2:0] fidx,
  output [15:0] ftag,
  output e_valid, input e_ready, output e_we, output [19:0] e_addr, output [7:0] e_len,
  output [63:0] e_wdata, input e_wdata_take, input [63:0] e_rdata, input e_rdata_valid
);
  localparam integer LINES = 1 << IW;
  localparam integer TW = 20 - IW - OW;
  localparam [2:0] C_IDLE = 3'd0, C_PEND = 3'd1, C_WBQ = 3'd2, C_WB = 3'd3, C_FQ = 3'd4, C_FL = 3'd5;
  reg [2:0] cs;
  reg [TW-1:0] ctag [0:LINES-1];
  reg [LINES-1:0] cval, cdirty;
  reg [31:0] cd_lo [0:(LINES << OW)-1];
  reg [31:0] cd_hi [0:(LINES << OW)-1];
  reg [63:0] cr_q;
  reg mis_we, pr;
  reg [OW-1:0] wcnt, rcnt;

  wire [IW-1:0] ri = ra[OW +: IW];
  wire [IW-1:0] wi = wa[OW +: IW];
  wire hit_r = rhit;
  wire hit_w = whit;
  wire [19:0] ma = mis_we ? wa : ra;
  wire [IW-1:0] mi = ma[OW +: IW];

  genvar g;
  generate for (g = 0; g < LINES; g = g + 1) begin : tag_out
    assign tags[g * TW +: TW] = ctag[g];
  end endgenerate
  assign vals = cval;
  assign filled = (cs == C_FL) && e_ready;
  assign fidx = mi;
  assign ftag = ma[19 -: TW];

`ifndef SYNTHESIS
  integer hit_mismatches = 0;
  always @(posedge clk) if (!rst) begin
    if ((^ra) !== 1'bx && rhit !== (cval[ri] && ctag[ri] == ra[19 -: TW])) begin
      hit_mismatches = hit_mismatches + 1; $display("PSRAM-CACHE-HIT-MISMATCH read %m %0t", $time);
    end
    if ((^wa) !== 1'bx && whit !== (cval[wi] && ctag[wi] == wa[19 -: TW])) begin
      hit_mismatches = hit_mismatches + 1; $display("PSRAM-CACHE-HIT-MISMATCH write %m %0t", $time);
    end
  end
`endif

  assign busy = (cs != C_IDLE) | (req_w & ~hit_w) | (req_r & ~hit_r) | (req_w & req_r);
  assign rd = cr_q;
  assign e_wdata = cr_q;
  assign e_valid = (cs == C_WBQ) | (cs == C_FQ);
  assign e_we = (cs == C_WBQ);
  assign e_addr = (cs == C_WBQ) ? {ctag[mi], mi, {OW{1'b0}}} : {ma[19:OW], {OW{1'b0}}};
  assign e_len = 8'd1 << OW;

  // One read port and one write port on the line store. The read address is the engine's, except
  // while a victim streams out; the write port takes an engine write hit or a filled word.
  wire [IW+OW-1:0] cr_a = (cs == C_WBQ || cs == C_WB) ? {mi, wcnt} : {ri, ra[OW-1:0]};
  wire hit_wr = cs == C_IDLE && req_w && hit_w;
  wire fill = cs == C_FL && e_rdata_valid;
  wire merge = fill && mis_we && rcnt == wa[OW-1:0];
  wire [IW+OW-1:0] dwa = (cs == C_FL) ? {mi, rcnt} : {wi, wa[OW-1:0]};
  wire [31:0] dwd_lo = (fill && !(merge && wm[0])) ? e_rdata[31:0] : wd[31:0];
  wire [31:0] dwd_hi = (fill && !(merge && wm[1])) ? e_rdata[63:32] : wd[63:32];

  always @(posedge clk) begin
    cr_q <= {cd_hi[cr_a], cd_lo[cr_a]};
    if (fill || (hit_wr && wm[0])) cd_lo[dwa] <= dwd_lo;
    if (fill || (hit_wr && wm[1])) cd_hi[dwa] <= dwd_hi;
  end

  task miss(input we, input [IW-1:0] idx);
    begin
      mis_we <= we; rcnt <= {OW{1'b0}}; wcnt <= {OW{1'b0}};
      cs <= (cval[idx] && cdirty[idx]) ? C_WBQ : C_FQ;
    end
  endtask

  always @(posedge clk) begin
    if (rst) begin
      cs <= C_IDLE; cval <= {LINES{1'b0}}; cdirty <= {LINES{1'b0}}; mis_we <= 1'b0; pr <= 1'b0;
    end else case (cs)
      C_IDLE: if (req_w) begin
                if (hit_w) begin cdirty[wi] <= 1'b1; if (req_r) cs <= C_PEND; end
                else begin pr <= req_r; miss(1'b1, wi); end
              end else if (req_r && !hit_r) miss(1'b0, ri);
      C_PEND: begin pr <= 1'b0; if (hit_r) cs <= C_IDLE; else miss(1'b0, ri); end
      C_WBQ:  if (e_ready) cs <= C_WB;
      C_WB:   begin if (e_wdata_take) wcnt <= wcnt + 1'b1; if (e_ready) cs <= C_FQ; end
      C_FQ:   if (e_ready) cs <= C_FL;
      C_FL:   begin
                if (e_rdata_valid) rcnt <= rcnt + 1'b1;
                if (e_ready) begin
                  ctag[mi] <= ma[19 -: TW]; cval[mi] <= 1'b1; cdirty[mi] <= mis_we;
                  cs <= pr ? C_PEND : C_IDLE;
                end
              end
      default: cs <= C_IDLE;
    endcase
  end
endmodule

// psram_arbiter — N psram_cache instances share one psram_edge (codegen_sva::psram).
module psram_arbiter #(parameter integer N = 1, parameter integer AW = 20) (
  input clk, input rst,
  input  [N-1:0] c_valid, output [N-1:0] c_ready, input [N-1:0] c_we,
  input  [N*AW-1:0] c_addr, input [N*8-1:0] c_len, input [N*64-1:0] c_wdata,
  output e_valid, input e_ready, output e_we, output [AW-1:0] e_addr, output [7:0] e_len, output [63:0] e_wdata
);
  reg pend;
  reg [7:0] owner;
  reg [7:0] pick;
  reg any;
  integer i;
  always @* begin
    any = 1'b0; pick = 8'd0;
    for (i = N - 1; i >= 0; i = i - 1) if (c_valid[i]) begin any = 1'b1; pick = i; end
  end
  wire [7:0] sel = pend ? owner : pick;
  assign e_valid = !pend && any;
  assign e_we = c_we[sel];
  assign e_addr = c_addr[sel*AW +: AW];
  assign e_len = c_len[sel*8 +: 8];
  assign e_wdata = c_wdata[sel*64 +: 64];
  genvar g;
  generate for (g = 0; g < N; g = g + 1) begin : grant
    assign c_ready[g] = e_ready && (pend ? owner == g : (any && pick == g));
  end endgenerate
  always @(posedge clk) begin
    if (rst) begin pend <= 1'b0; owner <= 8'd0; end
    else if (pend) begin if (e_ready) pend <= 1'b0; end
    else if (e_valid && e_ready) begin pend <= 1'b1; owner <= pick; end
  end
endmodule

// psram_edge — the off-chip memory edge for the APS6404L-3SQN QSPI PSRAM (codegen_sva::psram).
// Power-up: tPU with CLK low and CE# high, Reset-Enable 0x66 + Reset 0x99 in SPI, tRST,
// then 0x35 into QPI. A request is one QPI burst: 0xeb (wait 6) to read, 0x38 to write,
// a 24-bit byte address, 16 nibbles per 64-bit word (byte 0 first, high nibble first). Outputs
// change at SCLK's falling edge; the part samples at its rising edge, and read data is taken at
// the rising edge. Emitted by `cargo run -p logicaffeine-compile --example emit_psram_edge`.
module psram_edge #(
  parameter integer H = 2,
  parameter integer POWERUP = 9375,
  parameter integer CPH = 2,
  parameter integer RSTGAP = 4
) (
  input clk, input rst,
  input req_valid, output req_ready, input req_we, input [19:0] req_addr, input [7:0] req_len,
  input [63:0] wdata, output reg wdata_take,
  output reg [63:0] rdata, output reg rdata_valid,
  output reg ce_n, output reg sclk, output reg [3:0] sio_out, output reg [3:0] sio_oe, input [3:0] sio_in
);
  localparam S_PU = 2'd0, S_OP = 2'd1, S_GAP = 2'd2, S_IDLE = 2'd3;
  localparam O_SPI = 2'd0, O_READ = 2'd1, O_WRITE = 2'd2;
  reg [1:0] state, op, init;
  reg [7:0] spi_byte;
  reg [23:0] baddr;
  reg [11:0] ei, nei;
  reg [7:0] phase;
  reg [31:0] count;
  reg [63:0] wbuf, rbuf;
  assign req_ready = (state == S_IDLE);

  // The nibble to present on edge `e` of the current operation, and whether to drive it.
  function [4:0] nibble(input [1:0] o, input [11:0] e, input [7:0] sb, input [23:0] a, input [63:0] w);
    reg [11:0] d; reg [3:0] j;
    begin
      if (o == O_SPI) nibble = {1'b1, 3'b000, sb[3'd7 - e[2:0]]};
      else if (e == 12'd0) nibble = {1'b1, (o == O_READ) ? 4'he : 4'h3};
      else if (e == 12'd1) nibble = {1'b1, (o == O_READ) ? 4'hb : 4'h8};
      else if (e < 12'd8) nibble = {1'b1, a[5'd23 - 5'd4 * (e[4:0] - 5'd2) -: 4]};
      else if (o == O_READ) nibble = 5'b0_0000;
      else begin
        d = e - 12'd8; j = d[3:0];
        nibble = {1'b1, w[8 * j[3:1] + 7 - 4 * j[0] -: 4]};
      end
    end
  endfunction

  // Begin operation `o`: CE# falls with the first edge's output.
  task start(input [1:0] o, input [7:0] sb);
    reg [4:0] n;
    begin
      op <= o; spi_byte <= sb; ei <= 12'd0; phase <= 8'd0; state <= S_OP;
      ce_n <= 1'b0; sclk <= 1'b0;
      nei <= (o == O_SPI) ? 12'd8 : (o == O_READ) ? 12'd14 + {req_len, 4'b0000} : 12'd8 + {req_len, 4'b0000};
      n = nibble(o, 12'd0, sb, (o == O_SPI) ? 24'd0 : {1'b0, req_addr, 3'b000}, wdata);
      sio_oe <= (o == O_SPI) ? 4'b0001 : {4{n[4]}}; sio_out <= n[3:0];
    end
  endtask

  reg [4:0] nx;
  reg [11:0] dn;
  reg [11:0] ds;
  always @(posedge clk) begin
    wdata_take <= 1'b0; rdata_valid <= 1'b0;
    if (rst) begin
      state <= S_PU; count <= 32'd0; init <= 2'd0;
      ce_n <= 1'b1; sclk <= 1'b0; sio_oe <= 4'b1111; sio_out <= 4'b0000;
    end else case (state)
      S_PU: if (count >= POWERUP - 1) start(O_SPI, 8'h66); else count <= count + 32'd1;
      S_IDLE: if (req_valid) begin
        baddr <= {1'b0, req_addr, 3'b000};
        start(req_we ? O_WRITE : O_READ, 8'h00);
      end
      S_GAP: if (count <= 32'd1) begin
        case (init)
          2'd1: start(O_SPI, 8'h99);
          2'd2: start(O_SPI, 8'h35);
          default: state <= S_IDLE;
        endcase
      end else count <= count - 32'd1;
      S_OP: begin
        if (phase == H - 1) begin
          sclk <= 1'b1;
          if (op == O_READ && ei >= 12'd14) begin
            ds = ei - 12'd14;
            if (ds[3:0] == 4'd15) begin
              rdata <= {rbuf[63:60], sio_in, rbuf[55:0]}; rdata_valid <= 1'b1;
            end else rbuf[8 * ds[3:1] + 7 - 4 * ds[0] -: 4] <= sio_in;
          end
        end
        if (phase == 2 * H - 1) begin
          sclk <= 1'b0; phase <= 8'd0;
          if (ei == nei - 12'd1) begin
            ce_n <= 1'b1; sio_oe <= 4'b0000; state <= S_GAP;
            if (op == O_SPI) begin
              init <= init + 2'd1;
              count <= (init == 2'd1) ? RSTGAP : CPH;
            end else count <= CPH;
          end else begin
            ei <= ei + 12'd1;
            dn = ei + 12'd1 - 12'd8;
            if (op == O_WRITE && ei + 12'd1 >= 12'd8 && dn[3:0] == 4'd0) begin
              wbuf <= wdata; wdata_take <= 1'b1;
              nx = nibble(op, ei + 12'd1, spi_byte, baddr, wdata);
            end else nx = nibble(op, ei + 12'd1, spi_byte, baddr, wbuf);
            sio_oe <= (op == O_SPI) ? 4'b0001 : {4{nx[4]}}; sio_out <= nx[3:0];
          end
        end else phase <= phase + 8'd1;
      end
    endcase
  end
endmodule

// wpe_user_project — the whole-program engine as a Caravel user macro (codegen_sva::wpe_caravel). UART rx/tx
// on GPIO 8/9; PSRAM CE# 10, SCLK 11, SIO[3:0] 12..15; engine clock user_clock2 (21000 ps), 115200
