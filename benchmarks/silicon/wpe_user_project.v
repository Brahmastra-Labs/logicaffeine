  // x - y as a Kogge-Stone prefix subtract; bit 64 is the borrow (1 when x < y).
  function [64:0] sub65(input [63:0] x, input [63:0] y);
    reg [63:0] yb, g, p, p0; integer d;
    begin
      yb = ~y; p0 = x ^ yb; g = (x & yb) | (p0 & 64'd1); p = p0;
      for (d = 1; d < 64; d = d * 2) begin g = g | (p & (g << d)); p = p & (p << d); end
      sub65 = {~g[63], p0 ^ {g[62:0], 1'b1}};
    end
  endfunction
