  assign io_out = {1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, psram_sio_out[3], psram_sio_out[2], psram_sio_out[1], psram_sio_out[0], psram_sclk, psram_ce_n, uart_tx, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0, 1'b0};
  assign io_oeb = {1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, ~psram_sio_oe[3], ~psram_sio_oe[2], ~psram_sio_oe[1], ~psram_sio_oe[0], 1'b0, 1'b0, 1'b0, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1};
  // Every Wishbone access is acknowledged the cycle after it is presented and reads zero.
  reg ack;
  always @(posedge wb_clk_i) ack <= !wb_rst_i && wbs_cyc_i && wbs_stb_i && !ack;
  assign wbs_ack_o = ack;
  assign wbs_dat_o = 32'd0;
  assign la_data_out = 128'd0;
