  function [63:0] inc64(input [63:0] v);
    reg [63:0] p; integer d;
    begin
      p = v;
      for (d = 1; d < 64; d = d * 2) p = p & ((p << d) | ((64'd1 << d) - 64'd1));
      inc64 = v ^ {p[62:0], 1'b1};
    end
