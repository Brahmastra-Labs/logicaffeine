#!/usr/bin/env python3
"""Assemble one benchmark run's raw measurements into the results JSON the site renders.

    python3 lib/assemble.py <raw-dir> <out.json>

writes <out.json> and, beside it, <out>-jit-code.json: the machine code the LOGOS (JIT) row emitted, disassembled.

Reads the registries beside this file (benchmarks.tsv, languages.tsv, compilers.tsv) and, under <raw-dir>:

    per_lang/<bench>_<n>_<id>.json       hyperfine --export-json, one command named <id>
    <bench>_<n>_<id>.timeout             the language timed out at size n (skipped at larger sizes): timed_out[n][id]
    <bench>_<n>_<id>.limit               the language cannot run size n (lib/limits.tsv), and why
    per_lang/compile_<bench>_<cid>.json  hyperfine timing of compiler row <cid>
    compile_<bench>_<cid>.timeout        that compile timed out
    <bench>_mem.json                     {"method", "by_size": {n: {id: kB | null}}}
    <bench>_sizes.json                   {"method", "by_language": {id: {as_built, stripped}}}
    <bench>_opts.json                    `largo opts --json` for the program
    <bench>_jit.txt                      the LOGOS (JIT) run's `logos-engine:` trace lines
    <bench>_jitcode/index.tsv, <n>.bin   the machine code that run emitted (`LOGOS_JIT_CODE`): `n START SIZE name` per region
    run.json                             the run's metadata (written by run.sh)

and the generated sources under $SUITE_GENERATED (../generated by default)/<bench>.{rs,c,bytecode.c}. Every speedup is "x the speed of C" (C time / language
time), so higher is faster. A language's ratio for a benchmark is taken at the benchmark's reference size — the largest
size where C and LOGOS (Rust) both have a timing — or, when that language timed out there, at the largest size where it
and C both finished, recorded under summary.ratio_sizes so a reader sees which.
"""

import json
import math
import os
import pathlib
import shutil
import subprocess
import sys

LIB = pathlib.Path(__file__).resolve().parent
ROOT = LIB.parent
sys.path.insert(0, str(LIB))
GENERATED = pathlib.Path(os.environ.get("SUITE_GENERATED") or ROOT / "generated")
C_USER_CODE = "// ==== LOGOS user code (device-liftable) ===="


from suite import benchmarks, compilers, languages


def read_json(path, default=None):
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return default


def sizes_of(bench_id, raw=None):
    """The benchmark's timed sizes (sizes.txt), and any other size this run timed (a `BENCH_SIZES=ref` run times the
    registry's ref_size, which need not be one of them)."""
    sizes = (ROOT / "programs" / bench_id / "sizes.txt").read_text().split()
    if raw is not None:
        for f in (raw / "per_lang").glob(f"{bench_id}_*.json"):
            n = f.name[len(bench_id) + 1:].split("_", 1)[0]
            if n.isdigit() and n not in sizes:
                sizes.append(n)
    return sorted(sizes, key=int)


def timing(result):
    """One hyperfine result → the page's timing record, in milliseconds."""
    ms = lambda s: None if s is None else s * 1000.0
    times = [t * 1000.0 for t in result.get("times", [])]
    mean = ms(result["mean"])
    stddev = ms(result.get("stddev")) or 0.0
    return {
        "mean_ms": mean,
        "median_ms": ms(result["median"]),
        "stddev_ms": stddev,
        "min_ms": ms(result["min"]),
        "max_ms": ms(result["max"]),
        "cv": (stddev / mean) if mean else 0.0,
        "runs": len(times),
        "user_ms": ms(result.get("user")),
        "system_ms": ms(result.get("system")),
        "times_ms": times,
    }


def scaling_for(raw, bench_id, sizes, lang_ids):
    scaling, timed_out, limits = {}, {}, {}
    for n in sizes:
        row = {}
        for lid in lang_ids:
            data = read_json(raw / "per_lang" / f"{bench_id}_{n}_{lid}.json")
            if data and data.get("results"):
                row[lid] = timing(data["results"][0])
            marker = raw / f"{bench_id}_{n}_{lid}.timeout"
            if marker.exists():
                timed_out.setdefault(n, {})[lid] = float(marker.read_text().strip() or 0) * 1000.0
            limit = raw / f"{bench_id}_{n}_{lid}.limit"
            if limit.exists():
                limits.setdefault(n, {})[lid] = limit.read_text().strip()
        if row:
            scaling[n] = row
    return scaling, timed_out, limits


def reference_size(scaling, fallback):
    def largest(pred):
        found = [int(n) for n, row in scaling.items() if pred(row)]
        return str(max(found)) if found else None

    return (
        largest(lambda r: "c" in r and "logos_release" in r)
        or largest(lambda r: "logos_release" in r)
        or largest(lambda r: True)
        or fallback
    )


def generated(bench_id, ext):
    path = GENERATED / f"{bench_id}.{ext}"
    return path.read_text() if path.exists() else ""


def c_program_part(full):
    """The program's own C, after the runtime the emitter prepends."""
    i = full.find(C_USER_CODE)
    return full[i + len(C_USER_CODE):].lstrip("\n") if i >= 0 else full


def jit_code(raw, bench_id):
    """The regions the LOGOS (JIT) row's verified run compiled, each disassembled at its own address (Intel syntax).
    Without objdump on the PATH a region keeps its size and its listing says why it has none."""
    index = raw / f"{bench_id}_jitcode" / "index.tsv"
    if not index.exists():
        return []
    objdump = shutil.which("objdump")
    regions = []
    for line in index.read_text().splitlines():
        n, start, size, name = line.split("\t", 3)
        binary = index.parent / f"{n}.bin"
        if objdump:
            listing = subprocess.run(
                [objdump, "-D", "-b", "binary", "-m", "i386:x86-64", "-M", "intel", f"--adjust-vma=0x{start}", str(binary)],
                capture_output=True, text=True,
            ).stdout
            body = listing.split(">:\n", 1)[-1]
            asm = "\n".join(l.rstrip() for l in body.splitlines() if l.strip())
        else:
            asm = "objdump was not on the PATH when this run was assembled."
        regions.append({"name": name, "start": f"0x{start}", "bytes": int(size, 16), "asm": asm})
    return regions


def jit_record(raw, bench_id):
    path = raw / f"{bench_id}_jit.txt"
    if not path.exists():
        return None
    lines = [l.strip() for l in path.read_text().splitlines() if l.startswith("logos-engine:")]
    engine = next((
        l.split(": ", 1)[1]
        for l in lines
        if not l.startswith("logos-engine: native-tier")
        and not l.startswith("logos-engine: native-declines")
        and not l.startswith("logos-engine: native-opts")
        and not l.startswith("logos-engine: native-runtime")
    ), None)
    summary = next((l.split(": ", 2)[2] for l in lines if l.startswith("logos-engine: native-tier")), None)
    declines = next((l.split(": ", 2)[2] for l in lines if l.startswith("logos-engine: native-declines")), "")
    native_opts = next((l.split(": ", 2)[2] for l in lines if l.startswith("logos-engine: native-opts")), "")
    execution = next((l.split(": ", 2)[2] for l in lines if l.startswith("logos-engine: native-runtime")), "")
    return {
        "engine": engine,
        "compiled": summary,
        "declines": declines,
        "optimizations": [opt for opt in native_opts.split(",") if opt],
        "execution": execution,
    }


def require_optimizer_parity(opts, bench_id):
    """Refuse to publish a run where a backend silently skipped its shared optimizer.

    Backend-specific lowering is allowed to differ (and is shown separately),
    but the front half is shared by construction: Rust/direct-C/bytecode-C use
    the AOT optimizer, while tree/VM/JIT use the run optimizer.  A mismatch is
    wiring drift, never a target limitation.
    """
    # Partial BENCH_ONLY development runs intentionally leave untouched
    # benchmarks without an opts artifact; validate every trace that is
    # present, while the full publishing run still covers the whole corpus.
    if not opts:
        return
    stages = opts.get("stages") or {}

    def optimizer(name):
        stage = stages.get(name)
        if not isinstance(stage, dict) or not isinstance(stage.get("optimizer"), list):
            raise RuntimeError(f"{bench_id}: optimization trace is missing stages.{name}.optimizer")
        return stage["optimizer"]

    compiled = optimizer("compiled")
    for backend in ("c", "c_bytecode"):
        got = optimizer(backend)
        # Direct-C and bytecode-C may expose additional target-applicable work
        # after their IR diverges (for example C fast division after
        # monomorphization). The parity invariant is that neither backend loses
        # a shared Rust-AOT optimization, not that its complete target-specific
        # optimizer list is byte-for-byte identical.
        missing = [opt for opt in compiled if opt not in got]
        if missing:
            raise RuntimeError(
                f"{bench_id}: {backend} silently lost Rust-AOT optimizer passes "
                f"{missing!r}: rust={compiled!r} {backend}={got!r}"
            )

    run = optimizer("run")
    for backend in ("vm", "jit"):
        got = optimizer(backend)
        if got != run:
            raise RuntimeError(
                f"{bench_id}: {backend} optimizer trace diverged from tree-walker: "
                f"run={run!r} {backend}={got!r}"
            )

    native = opts.get("jit_native")
    if not isinstance(native, dict) or not isinstance(native.get("lowering"), list):
        raise RuntimeError(f"{bench_id}: optimization trace is missing jit_native.lowering")
    for unit in ("functions", "loops"):
        coverage = native.get(unit)
        if not isinstance(coverage, dict):
            raise RuntimeError(f"{bench_id}: optimization trace is missing jit_native.{unit}")
        attempted = coverage.get("attempted")
        compiled = coverage.get("compiled")
        if not isinstance(attempted, int) or not isinstance(compiled, int) or compiled > attempted:
            raise RuntimeError(
                f"{bench_id}: malformed jit_native.{unit} coverage: {coverage!r}"
            )
    if "unclassified=" in str(native.get("declines", "")):
        raise RuntimeError(
            f"{bench_id}: JIT contains an unclassified native decline: {native['declines']}"
        )


def assemble_benchmark(raw, bench, lang_ids, compiler_ids):
    bid = bench["id"]
    sizes = sizes_of(bid, raw)
    scaling, timed_out, limits = scaling_for(raw, bid, sizes, lang_ids)
    compilation = {}
    for cid in compiler_ids:
        data = read_json(raw / "per_lang" / f"compile_{bid}_{cid}.json")
        if data and data.get("results"):
            r = data["results"][0]
            compilation[cid] = {"mean_ms": r["mean"] * 1000.0, "stddev_ms": (r.get("stddev") or 0.0) * 1000.0}
        if (raw / f"compile_{bid}_{cid}.timeout").exists():
            timed_out.setdefault("compile", {})[cid] = float((raw / f"compile_{bid}_{cid}.timeout").read_text() or 0) * 1000.0
    opts = read_json(raw / f"{bid}_opts.json", {}) or {}
    require_optimizer_parity(opts, bid)
    full_c = generated(bid, "c")
    return {
        "id": bid,
        "name": bench["name"],
        "short": bench["short"],
        "category": bench["category"],
        "description": bench["description"],
        "collapse": bench["collapse"] or None,
        "output": {"proof": bench["proof"], "prints": bench["output"]},
        "reference_size": reference_size(scaling, bench["ref_size"]),
        "sizes": sizes,
        "logos_source": (ROOT / "programs" / bid / "main.lg").read_text(),
        "generated_rust": generated(bid, "rs"),
        "generated_c": c_program_part(full_c),
        "generated_c_bytecode": c_program_part(generated(bid, "bytecode.c")),
        "scaling": scaling,
        "compilation": compilation,
        "timed_out": timed_out,
        "limits": limits,
        "memory": read_json(raw / f"{bid}_mem.json"),
        "binary_sizes": read_json(raw / f"{bid}_sizes.json"),
        "complexity": {"time": bench["time"], "space": bench["space"]},
        "jit": jit_record(raw, bid),
        "fired": opts.get("fired", []),
        "fired_paths": opts.get("paths", {}),
        "optimization_stages": opts.get("stages", {}),
        "changes_algorithm": opts.get("changes_algorithm", []),
        "blockers": opts.get("blockers", []),
        "dependencies": opts.get("dependencies", []),
    }


def ratio(bench, lid, base="c"):
    """(base time / lid time, the size it was taken at), or None when the two never both finished."""
    ref = bench["reference_size"]
    row = bench["scaling"].get(ref, {})
    if base in row and lid in row:
        return row[base]["mean_ms"] / row[lid]["mean_ms"], ref
    both = [int(n) for n, r in bench["scaling"].items() if base in r and lid in r]
    if not both:
        return None
    n = str(max(both))
    r = bench["scaling"][n]
    return r[base]["mean_ms"] / r[lid]["mean_ms"], n


def geomean(values):
    return math.exp(sum(math.log(v) for v in values) / len(values)) if values else None


def summarize(bench_records, lang_ids):
    everything, same_algorithm, coverage, ratio_sizes = {}, {}, {}, {}
    total = len(bench_records)
    for lid in lang_ids:
        all_r, same_r, off_ref = [], [], {}
        for b in bench_records:
            got = ratio(b, lid)
            if got is None:
                continue
            r, n = got
            all_r.append(r)
            if not b["collapse"]:
                same_r.append(r)
            if n != b["reference_size"]:
                off_ref[b["id"]] = n
        if all_r:
            everything[lid] = round(geomean(all_r), 3)
        if same_r:
            same_algorithm[lid] = round(geomean(same_r), 3)
        coverage[lid] = {"benchmarks": len(all_r), "of": total, "at_reference_size": len(all_r) - len(off_ref)}
        if off_ref:
            ratio_sizes[lid] = off_ref
    return {
        "geometric_mean_speedup_vs_c": everything,
        "same_algorithm_speedup_vs_c": same_algorithm,
        "coverage": coverage,
        "ratio_sizes": ratio_sizes,
    }


def assemble(raw):
    raw = pathlib.Path(raw)
    run = read_json(raw / "run.json", {}) or {}
    langs = languages()
    lang_ids = [l["id"] for l in langs]
    compiler_ids = [c["id"] for c in compilers()]
    records = [assemble_benchmark(raw, b, lang_ids, compiler_ids) for b in benchmarks()]
    present = {lid for b in records for row in b["scaling"].values() for lid in row}
    languages_out = [
        {"id": l["id"], "label": l["label"], "color": l["color"], "tier": l["tier"]}
        for l in langs
        if l["id"] in present
    ]
    full_c = next((generated(b["id"], "c") for b in records if generated(b["id"], "c")), "")
    runtime = full_c[: full_c.find(C_USER_CODE)] if C_USER_CODE in full_c else ""
    metadata = dict(run.get("metadata", {}))
    metadata["c_runtime"] = {"bytes": len(runtime.encode()), "lines": runtime.count("\n")}
    metadata["compilers"] = {c["id"]: {"label": c["label"]} for c in compilers()}
    return {
        "schema_version": 1,
        "metadata": metadata,
        "languages": languages_out,
        "benchmarks": records,
        "summary": summarize(records, [l["id"] for l in languages_out]),
    }


def main(argv):
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    out = assemble(argv[1])
    target = pathlib.Path(argv[2])
    target.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")
    code = {"schema_version": 1, "benchmarks": {b["id"]: jit_code(pathlib.Path(argv[1]), b["id"]) for b in benchmarks()}}
    target.with_name(f"{target.stem}-jit-code.json").write_text(json.dumps(code, ensure_ascii=False) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
