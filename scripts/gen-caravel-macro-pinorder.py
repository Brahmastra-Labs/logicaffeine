#!/usr/bin/env python3
"""Derive a Caravel user MACRO's pin order from the FIXED wrapper DEF, so wrapper→macro nets are
short hops instead of die-length runs.

THE BUG THIS FIXES. `user_project_wrapper` is hardened onto a fixed Caravel DEF template whose pin
placement we do not control: 494 of its 637 pins — including all 104 Wishbone pins — sit on the SOUTH
edge, x 14.5..623.5 um. Our macro was hardened with NO pin-order config, so OpenLane auto-placed its
ports wherever it liked: `wbs_dat_i[24]` landed on the macro's RIGHT edge at x~2858, y~1210. With the
macro at (60,880), every Wishbone net then ran ~2.4 mm across the die. Long net = large upper-metal
area on one gate pin = ANTENNA. That is where the wrapper's 14 met3/met4/met5 violators come from,
and no amount of jogging or diode insertion fixes a net that is simply too long: the ratios barely
exceed 1.0, so the fix is to stop routing 2.4 mm to reach a pin that could have been 880 um away.

So: place the macro's pins in the SAME ORDER, ON THE SAME SIDE, as the wrapper pins they connect to.
Each net becomes a short vertical hop from the die edge up to the macro's bottom edge.

  gen-caravel-macro-pinorder.py <wrapper.def> <macro.v> <out pin_order.cfg> <macro_module>
"""
import re
import sys


def wrapper_pins(def_path):
    """Every wrapper pin as (name, x_um, y_um, edge), from the fixed DEF."""
    txt = open(def_path, encoding="utf-8", errors="replace").read()
    unit = int(re.search(r"UNITS DISTANCE MICRONS (\d+)", txt).group(1))
    m = re.search(r"DIEAREA \( *(-?\d+) +(-?\d+) *\) *\( *(-?\d+) +(-?\d+) *\)", txt)
    _, _, w, h = (int(v) for v in m.groups())
    out = []
    for name, x, y in re.findall(
        r"- (\S+) \+ NET \S+ \+ DIRECTION \w+.*?\+ PLACED \( (-?\d+) (-?\d+) \)", txt, re.S
    ):
        x, y = int(x), int(y)
        edge = "S" if y <= 0 else "N" if y >= h else "W" if x <= 0 else "E"
        out.append((name, x / unit, y / unit, edge))
    return out


def macro_ports(v_path, module):
    """The macro's port names, bus bits expanded — the set we are allowed to place."""
    txt = open(v_path, encoding="utf-8", errors="replace").read()
    head = re.search(r"module\s+" + re.escape(module) + r"\s*\((.*?)\n\);", txt, re.S)
    if head is None:
        sys.exit(f"{v_path}: could not find the {module} port list")
    names = set()
    for line in head.group(1).splitlines():
        line = line.split("//")[0].strip().rstrip(",")
        if not line or line.startswith("`"):
            continue
        m = re.match(r"(?:input|output|inout)\s+(?:reg\s+)?(?:\[(\d+):(\d+)\]\s+)?(\w+)$", line)
        if not m:
            continue
        hi, lo, nm = m.groups()
        if nm in ("vccd1", "vssd1"):
            continue  # power comes through the PDN macro hooks, not a placed signal pin
        if hi is None:
            names.add(nm)
        else:
            for i in range(int(lo), int(hi) + 1):
                names.add(f"{nm}[{i}]")
    return names


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    def_path, v_path, out, module = sys.argv[1:5]

    pins = wrapper_pins(def_path)
    ports = macro_ports(v_path, module)

    # Same side, same order. Sort along the edge the way the pin sits on it: south/north run in x,
    # east/west in y. A macro port the wrapper does not expose (there are none on the golden
    # interface, but be fail-soft) lands on the north edge rather than vanishing.
    by_edge = {"N": [], "E": [], "S": [], "W": []}
    placed = set()
    for name, x, y, edge in pins:
        if name not in ports:
            continue
        by_edge[edge].append((x if edge in "SN" else y, name))
        placed.add(name)
    for e in by_edge:
        by_edge[e].sort()

    leftover = sorted(ports - placed)
    if leftover:
        print(f"note: {len(leftover)} macro port(s) not on the wrapper boundary → north edge", file=sys.stderr)
        by_edge["N"].extend((0.0, n) for n in leftover)

    # NOTE: OpenLane's io_place.py parser splits every line on whitespace, rejects any line with
    # more than one token, and accepts only #N/#E/#S/#W(+R)/#BUS_SORT as '#' tokens — so this file
    # can carry NO comments of any kind. The provenance goes in a sidecar instead.
    with open(out + ".provenance", "w", encoding="utf-8") as fh:
        fh.write(
            "GENERATED by scripts/gen-caravel-macro-pinorder.py — do not hand-edit pin_order.cfg.\n"
            f"Mirrored from: {def_path}\n"
            f"Macro ports from: {v_path}\n"
            "Every wrapper->macro net becomes a short hop to the nearest die edge instead of a\n"
            "die-length run, which is what produced the wrapper's met3/met4/met5 antenna violators.\n"
        )
    with open(out, "w", encoding="utf-8") as fh:
        for e in ("N", "E", "S", "W"):
            fh.write(f"#{e}\n")
            for _, name in by_edge[e]:
                fh.write(re.sub(r"([\[\]])", r"\\\1", name) + "\n")

    print(f"wrote {out}: " + ", ".join(f"{e}={len(by_edge[e])}" for e in "NESW"))


if __name__ == "__main__":
    main()
