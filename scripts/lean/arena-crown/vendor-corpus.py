#!/usr/bin/env python3
"""Vendor the live Lean Kernel Arena test corpus into the kernel's test fixtures.

Source of truth: the Arena website's published `results.json` (every test's name and expected
outcome) and `lean-arena-tests.tar.gz` (the official bytes of every scored test), both downloaded
into `reference-kernels/lean-arena-live-<rev>/` and pinned here by SHA-256.

Every case gets bytes from the first available source, in order of authority:
  1. the official archive (`official_archive`);
  2. the export `build-arena-inputs.py` regenerated from the pinned sources into
     `reference-kernels/arena-inputs-<rev>/` (`regenerated_from_pinned_source`) — the archive omits the
     unscored corner cases and the large inputs. A case an earlier round already exported to the same
     bytes is taken from that round's directory (`REGENERATED_ROUNDS`): the digest names the case, not
     the round.
A source is taken only if its SHA-256 is the one `results.json` publishes for that case, so every
case is the Arena's exact bytes, with one named exception: a case whose Lean build is not
reproducible (`NONDETERMINISTIC`, each with its evidence) takes the regenerated export
build-arena-inputs.py kept as `<name>.mismatch.ndjson`, recorded with both digests and provenance
`regenerated_nondeterministic_upstream`. Payloads at or under the size cap are copied into
`crates/logicaffeine_tests/tests/fixtures/arena_corpus/`; larger ones stay where they are and are
recorded as `heavy`. A case with no identical bytes anywhere is `absent`, and the lock test fails on it.

Also writes the generated test list `crates/logicaffeine_tests/tests/arena_corpus/cases.rs`.
"""
import hashlib, json, os, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
REVISION = "87512b60eb2483562967ebc93a5fb42eaa135389"
LIVE = os.path.join(ROOT, "reference-kernels/lean-arena-live-87512b60")
LIVE_TAR_SHA256 = "609baebb26a438e61a5ee28b7c3551793ab4066ae7af54f20e60e71cea74d6b5"
LIVE_RESULTS_SHA256 = "1e2c90211db7e67de3734ed5fa4804051f338ffacca0de87a08db0eee213af9e"
OUT = os.path.join(ROOT, "crates/logicaffeine_tests/tests/fixtures/arena_corpus")
CASES_RS = os.path.join(ROOT, "crates/logicaffeine_tests/tests/arena_corpus/cases.rs")
CAP = 4 * 1024 * 1024
DIR_OF = {"accept": "good", "reject": "bad", "either": "either"}
# The rounds whose regenerated exports may hold a case's bytes, this round's first.
REGENERATED_ROUNDS = [REVISION[:8], "66c354d6"]
REGENERATED = "reference-kernels/arena-inputs-{round}/{name}/{base}.ndjson"
REGENERATED_MISMATCH = "reference-kernels/arena-inputs-" + REVISION[:8] + "/{name}/{base}.mismatch.ndjson"
# Cases no build reproduces byte for byte, with the evidence.
NONDETERMINISTIC = {
    "cedar": "every export of cedar-spec@017c35c3 with Lean v4.34.1 differs: the Arena's rounds hold 15,316,784 "
             "records (66c354d6) and 15,316,785 (87512b60), three local builds exported 15,316,769, 15,316,775 "
             "and 15,316,782",
}
# Cases whose check takes seconds today; they run with the `#[ignore]` heavy set until the
# instruction ratchet brings them under a second.
SLOW = {"perf/app-lam", "perf/beta-ladder", "perf/magma-list-deep-n21", "perf/magma-list-deep-n36",
        "perf/magma-list-pair-n7", "perf/magma-list-pair-n21", "perf/let-ladder"}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def ident(name):
    out = "".join(ch if ch.isalnum() else "_" for ch in name.lower())
    return "case_" + "_".join(p for p in out.split("_") if p)


def write_cases(rows):
    lines = [
        "// GENERATED by scripts/lean/arena-crown/vendor-corpus.py from the pinned Arena manifest — do not edit.",
        "// `arena_corpus_lock` fails if this list and `fixtures/arena_corpus/manifest.json` disagree.",
        "",
    ]
    expect_of = {"accept": "Accept", "reject": "Reject", "either": "Either"}
    for r in rows:
        expect = expect_of[r["outcome"]]
        if r["location"] == "heavy":
            lines.append(
                f'arena_heavy_case!(#[ignore = "heavy: a large input read from reference-kernels/"] '
                f'{ident(r["name"])}, "{r["path"]}", {expect});'
            )
        elif r["location"] == "vendored":
            attr = '#[ignore = "heavy: seconds today; run with the ignored set"] ' if r["name"] in SLOW else ""
            lines.append(f'arena_case!({attr}{ident(r["name"])}, "{r["path"]}", {expect});')
    with open(CASES_RS, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    tar, results = os.path.join(LIVE, "lean-arena-tests.tar.gz"), os.path.join(LIVE, "results.json")
    if sha256(tar) != LIVE_TAR_SHA256 or sha256(results) != LIVE_RESULTS_SHA256:
        sys.exit("the live archive or results.json does not match its pinned SHA-256")
    live = json.load(open(results))
    if live["meta"]["git_revision"] != REVISION:
        sys.exit("results.json is not from the pinned revision")
    staging = OUT + ".new"
    shutil.rmtree(staging, ignore_errors=True)
    os.makedirs(staging)
    rows = []
    for test in sorted(live["tests"], key=lambda t: t["name"]):
        name, outcome = test["name"], test["outcome"]
        row = {"name": name, "outcome": outcome, "upstream_size": test.get("size"),
               "upstream_sha256": test["sha256"], "timeout": test.get("timeout")}
        src = None
        candidates = [("official_archive", os.path.join(LIVE, "payloads", DIR_OF[outcome], name + ".ndjson"))] + [
            ("regenerated_from_pinned_source",
             os.path.join(ROOT, REGENERATED.format(round=r, name=name, base=os.path.basename(name))))
            for r in REGENERATED_ROUNDS
        ]
        for provenance, cand in candidates:
            if os.path.exists(cand) and sha256(cand) == test["sha256"]:
                src, row["provenance"] = cand, provenance
                break
        if src is None and name in NONDETERMINISTIC:
            cand = os.path.join(ROOT, REGENERATED_MISMATCH.format(name=name, base=os.path.basename(name)))
            if os.path.exists(cand):
                src, row["provenance"] = cand, "regenerated_nondeterministic_upstream"
                row["nondeterministic"] = NONDETERMINISTIC[name]
        if src is None:
            row["location"] = "absent"
            rows.append(row)
            continue
        size = os.path.getsize(src)
        row["sha256"] = test["sha256"] if row["provenance"] != "regenerated_nondeterministic_upstream" else sha256(src)
        row["size"] = size
        if size <= CAP:
            rel = os.path.join(DIR_OF[outcome], name + ".ndjson")
            dst = os.path.join(staging, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copyfile(src, dst)
            row["location"], row["path"] = "vendored", rel
        else:
            row["location"], row["path"] = "heavy", os.path.relpath(src, ROOT)
        rows.append(row)
    doc = {
        "schema": "logos-arena-corpus/2",
        "upstream": "https://github.com/leanprover/lean-kernel-arena",
        "revision": REVISION,
        "source": "https://arena.lean-lang.org/ (lean-arena-tests.tar.gz and results.json)",
        "archive_sha256": LIVE_TAR_SHA256,
        "results_sha256": LIVE_RESULTS_SHA256,
        "license": "Apache-2.0 (lean-kernel-arena test corpus)",
        "cases": rows,
    }
    with open(os.path.join(staging, "manifest.json"), "w") as f:
        json.dump(doc, f, indent=1, sort_keys=True)
        f.write("\n")
    shutil.rmtree(OUT, ignore_errors=True)
    os.rename(staging, OUT)
    write_cases(rows)
    counts = {}
    for r in rows:
        key = (r["location"], r.get("provenance"))
        counts[key] = counts.get(key, 0) + 1
    print(len(rows), "cases:", {f"{k[0]}/{k[1]}": v for k, v in sorted(counts.items(), key=str)})


if __name__ == "__main__":
    sys.exit(main())
