#!/usr/bin/env python3
"""Write `crates/logicaffeine_compile/src/model/quant/grids.rs`: the lattice tables ggml's IQ formats decode through,
read out of the pinned llama.cpp's `ggml/src/ggml-common.h` (each `GGML_TABLE_BEGIN(type, name, size) … GGML_TABLE_END()`).
`model_quant_lock::every_grid_is_ggmls` reads the same header and holds the module to it.

  ggml-grids.py [ggml-common.h] [grids.rs]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / "external/competitors/llama.cpp/ggml/src/ggml-common.h"
OUT = ROOT / "crates/logicaffeine_compile/src/model/quant/grids.rs"

# (ggml's table, the Rust constant, its element type, what it holds)
TABLES = [
    ("kmask_iq2xs", "KMASK_IQ2XS", "u8", "The bit of a sign byte that negates element `j` of an eight-element group."),
    ("ksigns_iq2xs", "KSIGNS_IQ2XS", "u8",
     "Seven sign bits widened to eight, the eighth making the count of negated elements even."),
    ("iq2xxs_grid", "IQ2XXS_GRID", "u64", "IQ2_XXS's 256 points of eight magnitudes, a byte each."),
    ("iq2xs_grid", "IQ2XS_GRID", "u64", "IQ2_XS's 512 points of eight magnitudes, a byte each."),
    ("iq2s_grid", "IQ2S_GRID", "u64", "IQ2_S's 1024 points of eight magnitudes, a byte each."),
    ("iq3xxs_grid", "IQ3XXS_GRID", "u32", "IQ3_XXS's 256 points of four magnitudes, a byte each."),
    ("iq3s_grid", "IQ3S_GRID", "u32", "IQ3_S's 512 points of four magnitudes, a byte each."),
    ("iq1s_grid", "IQ1S_GRID", "u64", "IQ1_S's and IQ1_M's 2048 points of eight values in -1, 0, 1, a signed byte each."),
]


def table(text: str, name: str) -> list[int]:
    m = re.search(r"GGML_TABLE_BEGIN\(\w+,\s*" + re.escape(name) + r",\s*(\w+)\)(.*?)GGML_TABLE_END\(\)", text, re.S)
    if not m:
        raise SystemExit(f"{name}: no table in the header")
    body = re.sub(r"//[^\n]*", "", m.group(2))
    return [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\d+", body)]


def main() -> None:
    header = Path(sys.argv[1]) if len(sys.argv) > 1 else HEADER
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else OUT
    text = header.read_text()
    lines = [
        "//! The lattice tables ggml's IQ formats decode through, as the pinned llama.cpp's `ggml-common.h` defines them.",
        "//! Generated by `scripts/accel/ggml-grids.py`; `model_quant_lock::every_grid_is_ggmls` holds them to the header.",
        "",
    ]
    for ggml, rust, ty, doc in TABLES:
        values = table(text, ggml)
        width = {"u8": 2, "u32": 8, "u64": 16}[ty]
        per = {"u8": 16, "u32": 8, "u64": 4}[ty]
        lines.append(f"/// {doc} ggml's `{ggml}`.")
        lines.append(f"pub const {rust}: [{ty}; {len(values)}] = [")
        for i in range(0, len(values), per):
            row = ", ".join(f"0x{v:0{width}x}" for v in values[i:i + per])
            lines.append(f"    {row},")
        lines.append("];")
        lines.append("")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines).rstrip("\n") + "\n")
    print(f"grids → {out}")


if __name__ == "__main__":
    main()
